"""
Fusion Meta-Classifier — Training script.

Trains a lightweight XGBoost binary classifier on the 20-dim feature vector:
    [network_probs(7)] + [can_probs(6)] + [gps_probs(2)] + [lidar_probs(4)]
    + [zero_day_anomaly_score(1)]

Labels: 0 = NORMAL, 1 = ATTACK

Training data is generated by running all 4 supervised runners on labelled
samples from each domain's original dataset (benign + attack rows).

Run with:
    python fusion/fusion_train.py
"""
import json
import sys
import time
from pathlib import Path

import joblib
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
import xgboost as xgb
from sklearn.metrics import (classification_report, confusion_matrix,
                             f1_score, roc_auc_score, roc_curve)
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

HERE = Path(__file__).parent
CODES = HERE.parent
sys.path.insert(0, str(CODES))

from network.network_runner import NetworkDetector
from can.can_runner import CANDetector
from gps.gps_runner import GPSDetector
from lidar.lidar_runner import LiDARDetector
from unsupervised.unsupervised_runner import ZeroDayDetector

DATA = CODES / "data"

NETWORK_CLASSES = ["BENIGN","Bot","BruteForce","DoS","Infiltration","PortScan","WebAttack"]
CAN_CLASSES     = ["BENIGN","DoS","GAS","RPM","SPEED","STEERING_WHEEL"]
GPS_CLASSES     = ["Normal","Spoofing"]
LIDAR_CLASSES   = ["Normal","PointDrop","IntensitySpoof","GhostCluster"]

MAX_PER_CLASS = 1000   # samples per label (benign / attack) per domain pass
RNG = np.random.default_rng(42)


# ── Feature vector builder ────────────────────────────────────────────────────

def build_vector(net_r, can_r, gps_r, lid_r, zd_r=None) -> np.ndarray:
    def probs(res, classes):
        if "probabilities" in res:
            p = res["probabilities"]
            return [p.get(c, 0.0) for c in classes]
        return [res.get("prob_normal", 0.0), res.get("prob_spoof", 0.0)]

    zd_score = [float(zd_r.get("anomaly_score", 0.0))] if zd_r else [0.0]
    return np.array(
        probs(net_r, NETWORK_CLASSES) +
        probs(can_r, CAN_CLASSES) +
        probs(gps_r, GPS_CLASSES) +
        probs(lid_r, LIDAR_CLASSES) +
        zd_score,
        dtype=np.float32
    )


def feature_names():
    names  = [f"net_{c}" for c in NETWORK_CLASSES]
    names += [f"can_{c}" for c in CAN_CLASSES]
    names += [f"gps_{c}" for c in GPS_CLASSES]
    names += [f"lid_{c}" for c in LIDAR_CLASSES]
    names += ["zd_score"]
    return names


# ── Sample collectors ─────────────────────────────────────────────────────────

def collect_network_samples(det, df_benign, df_attack, feats):
    benign_rows  = df_benign[feats].replace([np.inf,-np.inf],0).fillna(0).to_dict(orient="records")
    attack_rows  = df_attack[feats].replace([np.inf,-np.inf],0).fillna(0).to_dict(orient="records")
    net_b = det.predict(benign_rows[:MAX_PER_CLASS])
    net_a = det.predict(attack_rows[:MAX_PER_CLASS])
    return net_b, net_a


def collect_can_samples(det, df_benign, df_attack):
    cols = ["ID","DATA_0","DATA_1","DATA_2","DATA_3","DATA_4","DATA_5","DATA_6","DATA_7"]
    can_b = det.predict(df_benign[cols].head(MAX_PER_CLASS).to_dict(orient="records"))
    can_a = det.predict(df_attack[cols].head(MAX_PER_CLASS).to_dict(orient="records"))
    return can_b, can_a


def collect_gps_samples(det, gps_dir):
    drop = ["Clock Time","GPS MGRS","Hobbs","Data Type","Hobbs Time","Arming State","Flight Mode"]
    benign_rows, attack_rows = [], []
    for i in range(4):
        df = pd.read_csv(gps_dir / f"AV-GPS-Dataset-{i}.csv")
        d  = df.drop(columns=[c for c in drop if c in df.columns], errors="ignore")
        benign_rows += d[df["Data Type"]==0].to_dict(orient="records")
        attack_rows += d[df["Data Type"]==1].to_dict(orient="records")
    gps_b = det.predict(benign_rows[:MAX_PER_CLASS])
    gps_a = det.predict(attack_rows[:MAX_PER_CLASS]) if attack_rows else []
    return gps_b, gps_a


def collect_lidar_samples(det):
    seq_dirs = [
        DATA/"Depth"/"2011_09_26_drive_0001_sync"/"2011_09_26"/"2011_09_26_drive_0001_sync"/"velodyne_points"/"data",
        DATA/"Depth"/"2011_09_26_drive_0015_sync"/"2011_09_26"/"2011_09_26_drive_0015_sync"/"velodyne_points"/"data",
    ]
    bins = []
    for d in seq_dirs:
        bins += sorted(d.glob("*.bin"))

    lid_normal = det.predict(bins)

    # Synthesize attacks (same as training — different RNG seed)
    lid_attack = []
    for fp in bins:
        pts = np.fromfile(fp, dtype=np.float32).reshape(-1, 4)
        attack_type = RNG.integers(0, 3)
        if attack_type == 0:
            keep = RNG.random(len(pts)) > RNG.uniform(0.40, 0.70)
            apts = pts[keep] if keep.sum() > 100 else pts[:100]
        elif attack_type == 1:
            apts = pts.copy(); apts[:,3] = RNG.uniform(0.88,1.0,len(pts)).astype(np.float32)
        else:
            n_g = RNG.integers(2000,6000)
            ghost = np.stack([
                RNG.uniform(8,20,n_g).astype(np.float32),
                RNG.uniform(-1.5,1.5,n_g).astype(np.float32),
                RNG.uniform(-1.5,1.5,n_g).astype(np.float32),
                RNG.uniform(0.1,0.6,n_g).astype(np.float32),
            ], axis=1)
            apts = np.concatenate([pts, ghost])
        lid_attack.append(det.predict_one(apts))

    return lid_normal, lid_attack


# ── Save evaluation PNG ───────────────────────────────────────────────────────

def save_evaluation_png(y_true, y_pred, y_score, out_path):
    fig, axes = plt.subplots(1, 3, figsize=(18, 6))

    # Confusion matrix
    cm = confusion_matrix(y_true, y_pred)
    sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
                xticklabels=["NORMAL","ATTACK"],
                yticklabels=["NORMAL","ATTACK"], ax=axes[0])
    axes[0].set_title("Confusion Matrix (meta-classifier)")
    axes[0].set_xlabel("Predicted"); axes[0].set_ylabel("True")

    # ROC
    fpr, tpr, _ = roc_curve(y_true, y_score)
    auc = roc_auc_score(y_true, y_score)
    axes[1].plot(fpr, tpr, lw=2, color="#4C72B0", label=f"AUC = {auc:.4f}")
    axes[1].plot([0,1],[0,1],"k--", lw=1)
    axes[1].set_xlabel("False Positive Rate"); axes[1].set_ylabel("True Positive Rate")
    axes[1].set_title("ROC Curve — Fusion Meta-Classifier")
    axes[1].legend()

    # Score distribution
    axes[2].hist(y_score[y_true==0], bins=40, alpha=0.6, color="#4C72B0",
                 label="Normal", density=True)
    axes[2].hist(y_score[y_true==1], bins=40, alpha=0.6, color="#C44E52",
                 label="Attack", density=True)
    axes[2].axvline(0.5, color="black", linestyle="--", linewidth=1.5,
                    label="Threshold 0.5")
    axes[2].set_title("Attack Probability Distribution")
    axes[2].set_xlabel("P(attack)"); axes[2].set_ylabel("Density")
    axes[2].legend()

    plt.tight_layout()
    plt.savefig(out_path, dpi=150)
    plt.close()
    print(f"  Saved: {out_path}")


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    t0 = time.time()
    print("=== Fusion Meta-Classifier Training ===")

    # Load all runners
    print("\n[1/6] Loading runners ...")
    net_det = NetworkDetector()
    can_det = CANDetector()
    gps_det = GPSDetector()
    lid_det = LiDARDetector()
    zd_det  = ZeroDayDetector(
        network_det=net_det, can_det=can_det,
        gps_det=gps_det, lidar_det=lid_det
    )
    print("  All runners loaded.")

    # Collect domain samples
    print("\n[2/6] Collecting domain samples ...")

    net_feats = json.load(open(CODES / "network" / "network_features.json"))
    df_net    = pd.read_csv(DATA / "CICIDS2017_sample.csv")
    df_net_b  = df_net[df_net["Label"]=="BENIGN"]
    df_net_a  = df_net[df_net["Label"]!="BENIGN"]
    net_b, net_a = collect_network_samples(net_det, df_net_b, df_net_a, net_feats)
    print(f"  Network: {len(net_b)} benign, {len(net_a)} attack")

    df_can_b = pd.read_csv(DATA/"CICIoV2024"/"decimal"/"decimal_benign.csv",
                           encoding="latin-1", nrows=MAX_PER_CLASS*2)
    df_can_a = pd.read_csv(DATA/"CICIoV2024"/"decimal"/"decimal_DoS.csv",
                           encoding="latin-1", nrows=MAX_PER_CLASS*2)
    can_b, can_a = collect_can_samples(can_det, df_can_b, df_can_a)
    print(f"  CAN    : {len(can_b)} benign, {len(can_a)} attack")

    gps_b, gps_a = collect_gps_samples(gps_det, DATA/"AV-GPS-Dataset")
    print(f"  GPS    : {len(gps_b)} normal, {len(gps_a)} spoofing")

    lid_n, lid_a = collect_lidar_samples(lid_det)
    print(f"  LiDAR  : {len(lid_n)} normal, {len(lid_a)} attack")

    # Build 20-dim feature matrix
    print("\n[3/6] Building feature vectors ...")
    m = min(len(net_b), len(can_b), len(gps_b), len(lid_n),
            len(net_a), len(can_a), len(lid_a))
    gps_a_safe = gps_a if gps_a else gps_b   # fallback if no GPS attack rows

    X_rows, y_rows = [], []
    for i in range(m):
        # Normal sample
        net_r = net_b[i]; can_r = can_b[i]
        gps_r = gps_b[i % len(gps_b)]; lid_r = lid_n[i % len(lid_n)]
        # Use ZeroDayDetector's OC-SVM directly on the pre-computed vector
        from unsupervised.unsupervised_runner import _probs_vec
        zd_vec = np.concatenate([
            _probs_vec(net_r, ["BENIGN","Bot","BruteForce","DoS","Infiltration","PortScan","WebAttack"]),
            _probs_vec(can_r, ["BENIGN","DoS","GAS","RPM","SPEED","STEERING_WHEEL"]),
            _probs_vec(gps_r, ["Normal","Spoofing"]),
            _probs_vec(lid_r, ["Normal","PointDrop","IntensitySpoof","GhostCluster"]),
        ])
        zd_sc = zd_det.scaler.transform(zd_vec.reshape(1,-1))
        zd_score = float(zd_det.ocsvm.decision_function(zd_sc)[0])
        zd_flag  = bool(zd_det.ocsvm.predict(zd_sc)[0] == -1)
        zd_r = {"anomaly_score": zd_score, "is_zero_day": zd_flag}

        X_rows.append(build_vector(net_r, can_r, gps_r, lid_r, zd_r))
        y_rows.append(0)

        # Attack sample
        net_r = net_a[i]; can_r = can_a[i]
        gps_r = gps_a_safe[i % len(gps_a_safe)]; lid_r = lid_a[i % len(lid_a)]
        zd_vec2 = np.concatenate([
            _probs_vec(net_r, ["BENIGN","Bot","BruteForce","DoS","Infiltration","PortScan","WebAttack"]),
            _probs_vec(can_r, ["BENIGN","DoS","GAS","RPM","SPEED","STEERING_WHEEL"]),
            _probs_vec(gps_r, ["Normal","Spoofing"]),
            _probs_vec(lid_r, ["Normal","PointDrop","IntensitySpoof","GhostCluster"]),
        ])
        zd_sc2 = zd_det.scaler.transform(zd_vec2.reshape(1,-1))
        zd_score2 = float(zd_det.ocsvm.decision_function(zd_sc2)[0])
        zd_flag2  = bool(zd_det.ocsvm.predict(zd_sc2)[0] == -1)
        zd_r2 = {"anomaly_score": zd_score2, "is_zero_day": zd_flag2}

        X_rows.append(build_vector(net_r, can_r, gps_r, lid_r, zd_r2))
        y_rows.append(1)

    X = np.array(X_rows, dtype=np.float32)
    y = np.array(y_rows, dtype=np.int32)
    print(f"  Dataset: {X.shape}, labels: {np.bincount(y)}")

    # Split + scale
    print("\n[4/6] Splitting and scaling ...")
    X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.20,
                                               stratify=y, random_state=42)
    scaler = StandardScaler()
    X_tr = scaler.fit_transform(X_tr)
    X_te  = scaler.transform(X_te)

    # Train XGBoost meta-classifier (GPU)
    print("[5/6] Training XGBoost meta-classifier (GPU) ...")
    model = xgb.XGBClassifier(
        n_estimators=200,
        max_depth=4,
        learning_rate=0.1,
        subsample=0.8,
        colsample_bytree=0.8,
        eval_metric="logloss",
        device="cuda",
        random_state=42,
    )
    model.fit(X_tr, y_tr, eval_set=[(X_te, y_te)], verbose=50)

    # Evaluate
    y_pred  = model.predict(X_te)
    y_score = model.predict_proba(X_te)[:, 1]
    acc  = (y_pred == y_te).mean()
    f1   = f1_score(y_te, y_pred, average="weighted")
    auc  = roc_auc_score(y_te, y_score)

    print(f"\nTest accuracy : {acc:.4%}")
    print(f"Test F1 (w)   : {f1:.4%}")
    print(f"ROC AUC       : {auc:.4f}")
    print(classification_report(y_te, y_pred, target_names=["NORMAL","ATTACK"]))

    # Save
    print("\n[6/6] Saving artifacts ...")
    out = HERE
    model.save_model(str(out / "fusion_meta_model.json"))
    joblib.dump(scaler, str(out / "fusion_meta_scaler.pkl"))
    feat_names = feature_names()
    (out / "fusion_meta_features.json").write_text(json.dumps(feat_names, indent=2))

    meta = {
        "strategy": "meta",
        "feat_dim": 20,
        "domain_weights": {
            "network": 0.9104, "can": 1.0, "gps": 0.9998, "lidar": 0.9963
        },
        "train_samples": int(X.shape[0]),
        "test_accuracy": float(acc),
        "test_f1": float(f1),
        "roc_auc": float(auc),
    }
    (out / "fusion_meta.json").write_text(json.dumps(meta, indent=2))

    save_evaluation_png(y_te, y_pred, y_score, out / "fusion_evaluation.png")

    print(f"\nDone in {time.time()-t0:.1f}s")
    print("Artifacts: fusion_meta_model.json, fusion_meta_scaler.pkl,")
    print("           fusion_meta_features.json, fusion_meta.json, fusion_evaluation.png")


if __name__ == "__main__":
    main()
