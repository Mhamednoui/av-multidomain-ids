"""WP3 S3: segmentation sanity numbers from the cached object tables (clean scans): objects per scan and median points by range,
ground fraction, runtime, frame-to-frame association with OXTS ego-motion (parts train / val / test, parameters fixed on val),
car-like count vs the S2 reference (lidar.objects.clusters) on validation scans. Writes results/WP3/S3/sanity.json and S3_tables.md."""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common.config import RESULTS
from lidar import assoc, ego
from lidar import geometry as G
from lidar import objects as O
from lidar.data import CACHE, DRIVES, VAL, load, part_of, scan_files

RES = RESULTS / "WP3" / "S3"
BINS = [(0, 10), (10, 20), (20, 30), (30, 40), (40, 60)]
TABLE = G.RingTable.load(RESULTS / "WP3" / "S2" / "ring_table.json")


def main():
    data = {d: pd.read_pickle(CACHE / "S3" / f"objects_{d}.pkl") for d in DRIVES}
    out = {"params": data[DRIVES[0]]["params"]}
    for part in ("train", "val", "test"):
        ds = [d for d in DRIVES if part_of(d) == part]
        objs = pd.concat([data[d]["objects"] for d in ds], ignore_index=True)
        sc = pd.concat([data[d]["scans"] for d in ds], ignore_index=True)
        r = {"scans": int(len(sc)), "objects_per_scan_median": float(sc.n_obj.median()), "ground_frac_mean": float(sc.ground_frac.mean()),
             "secs_median": float(sc.secs.median()), "secs_p90": float(sc.secs.quantile(0.9)), "carlike_per_scan": float(objs.carlike.sum() / len(sc)),
             "oversize_frac": float((objs.length > 8.0).mean()), "bins": {}}
        for lo, hi in BINS:
            o = objs[(objs.range >= lo) & (objs.range < hi)]
            r["bins"][f"{lo}-{hi}"] = {"objects_per_scan": float(len(o) / len(sc)), "median_points": float(o.n_points.median()),
                                       "median_length": float(o.length.median()), "median_rings": float(o.n_rings.median()),
                                       "carlike_per_scan": float(o.carlike.sum() / len(sc))}
        # association between consecutive scans (all pairs)
        acc = {f"{lo}-{hi}": dict(n=0, m=0, dist=[], ratio=[]) for lo, hi in BINS}
        for d in ds:
            P = ego.poses(d)
            g = dict(tuple(data[d]["objects"].groupby("idx")))
            for i in range(len(P) - 1):
                if i not in g or i + 1 not in g:
                    continue
                for lo, hi in BINS:
                    cand, jj, dist, ratio = assoc.match(g[i], P[i], g[i + 1], P[i + 1], 1.0, lo, hi)
                    a = acc[f"{lo}-{hi}"]
                    a["n"] += len(cand)
                    a["m"] += int((jj >= 0).sum())
                    a["dist"].append(dist[jj >= 0])
                    a["ratio"].append(ratio[jj >= 0])
        r["assoc"] = {}
        for k, a in acc.items():
            dist, ratio = np.concatenate(a["dist"]), np.concatenate(a["ratio"])
            r["assoc"][k] = {"n": a["n"], "match_rate": a["m"] / max(a["n"], 1), "dist_median": float(np.median(dist)),
                             "dist_p90": float(np.quantile(dist, 0.9)), "count_ratio_median": float(np.median(ratio)),
                             "count_ratio_iqr": [float(np.quantile(ratio, 0.25)), float(np.quantile(ratio, 0.75))]}
        out[part] = r
    # car-like count vs S2 reference on validation scans (every 8th)
    ref, new = [], []
    for d in VAL:
        ob = data[d]["objects"]
        for i in range(0, len(scan_files(d)), 8):
            ref.append(len(O.clusters(load(scan_files(d)[i]), TABLE)))
            new.append(int(ob[ob.idx == i].carlike.sum()))
    ref, new = np.array(ref), np.array(new)
    out["carlike_vs_S2"] = {"scans": len(ref), "ref_mean": float(ref.mean()), "new_mean": float(new.mean()), "ratio": float(new.mean() / ref.mean()),
                            "per_scan_within_25pct": float((np.abs(new - ref) <= 0.25 * np.maximum(ref, 1)).mean())}
    (RES / "sanity.json").write_text(json.dumps(out, indent=1))
    L = ["# WP3 S3 segmentation sanity (clean scans; generated by tools/WP3_S3_stats.py from sanity.json)", "",
         f"Parameters: {out['params']}", ""]
    L += ["| part | scans | objects/scan | ground frac (<40 m) | car-like/scan | oversize (>8 m) | s/scan median | p90 |", "|---|---|---|---|---|---|---|---|"]
    for p in ("train", "val", "test"):
        r = out[p]
        L.append(f"| {p} | {r['scans']} | {r['objects_per_scan_median']:.0f} | {r['ground_frac_mean']:.3f} | {r['carlike_per_scan']:.2f} | {100*r['oversize_frac']:.2f} % | {r['secs_median']:.2f} | {r['secs_p90']:.2f} |")
    for p in ("train", "val", "test"):
        r = out[p]
        L += ["", f"## {p}: per range bin", "", "| range m | objects/scan | median points | median length m | median rings | car-like/scan | match rate (1 m) | centroid residual med / p90 m | count ratio med (IQR) |", "|---|---|---|---|---|---|---|---|---|"]
        for k, b in r["bins"].items():
            a = r["assoc"][k]
            L.append(f"| {k} | {b['objects_per_scan']:.1f} | {b['median_points']:.0f} | {b['median_length']:.2f} | {b['median_rings']:.0f} | {b['carlike_per_scan']:.2f} | {100*a['match_rate']:.1f} % | {a['dist_median']:.2f} / {a['dist_p90']:.2f} | {a['count_ratio_median']:.2f} ({a['count_ratio_iqr'][0]:.2f}-{a['count_ratio_iqr'][1]:.2f}) |")
    c = out["carlike_vs_S2"]
    L += ["", f"Car-like clusters, val scans (n={c['scans']}): S2 reference {c['ref_mean']:.2f}/scan, S3 table {c['new_mean']:.2f}/scan, ratio {c['ratio']:.2f}; per-scan within +-25 %: {100*c['per_scan_within_25pct']:.0f} %."]
    (RES / "S3_tables.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
