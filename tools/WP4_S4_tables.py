"""WP4 S4: markdown tables from results/WP4/s4_d10.json, s4_d23.json, s4_limit.json, s4_dev_val.json -> results/WP4/s4_tables.md,
and the acceptance numbers -> results/WP4/s4_acceptance.json."""
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from tools.WP4_S3_tables import EVAL, SHORT, p, table

RES = os.path.join(os.path.dirname(__file__), "..", "results", "WP4")


def main():
    d10 = json.load(open(os.path.join(RES, "s4_d10.json")))
    d23 = json.load(open(os.path.join(RES, "s4_d23.json")))
    lim = json.load(open(os.path.join(RES, "s4_limit.json")))
    dev = json.load(open(os.path.join(RES, "s4_dev_val.json")))
    fams = [f for f in EVAL if f in d10["families"]]
    out = ["# WP4 S4 tables (generated by tools/WP4_S4_tables.py from results/WP4/s4_*.json)\n"]
    out.append(f"Test side: {d10['test_side']} (mode {d10['mode']}). Detection in % of the attack flows of the family (pre-dedup stage flows). "
               "FA headline = benign flows outside the audited Infiltration file; published = all BENIGN-labelled flows.\n")
    out.append("## 1. Bot flows and groups per split (pre-dedup stage flows; group = source, destination, port)\n")
    rows = [[sp, v["flows"], v["groups"], v["groups_ge10_flows"], v["flows_in_groups_ge10"], v["active_minutes"]] for sp, v in d10["bot_split_counts"].items()]
    out.append(table(["split", "Bot flows", "groups", "groups with >= 10 flows", "flows in those groups", "active minutes"], rows))
    out.append("\n## 2. net.beacon and single statistics, D10 test (flow unit; window unit = group x 64-min block)\n")
    rows = []
    for n, r in d10["layers"].items():
        f, w, e = r["flow"], r["window"], r["extra"]
        rows.append([n, p(f["fa_benign"], 2), p(f["fa_benign_published_labels"], 2), p(w["fa_benign_cells"], 2), p(w["fa_benign_cells_published_labels"], 2),
                     p(f["detection"].get("Bot")), p(w["detection"].get("Bot")), p(e["testable_share_benign"], 2), p(e["fa_among_testable_benign"], 1),
                     p(e["bot_testable_share"]), p(e["bot_detection_among_testable"])])
    out.append(table(["layer", "FA flow %", "FA flow published %", "FA window %", "FA window published %", "Bot flows %", "Bot windows %",
                      "testable benign flows %", "FA among testable benign %", "Bot flows testable %", "Bot detected among testable %"], rows))
    out.append("Testable = the flow's group has >= 6 active minutes in the trailing 64 min and a median gap >= 2 min (otherwise the phase statistics are undefined and the score is 0).\n")
    out.append("\n## 3. Bot groups with >= 10 flows (net.beacon, test)\n")
    rows = [[i + 1, g["flows"], g["testable"], g["alarmed"], g["span_min"], "-" if g["first_alarm_delay_min"] is None else g["first_alarm_delay_min"]]
            for i, g in enumerate(d10["layers"]["net.beacon"]["extra"]["bot_pairs"])]
    out.append(table(["group", "flows", "testable flows", "alarmed flows", "span (min)", "delay of first alarm (min)"], rows))
    out.append(f"Bot on the flows that survive de-duplication: {d10['bot_dedup_subset']['flows']} flows, detection {p(d10['bot_dedup_subset']['detection'])} %.\n")
    out.append("\n## 4. Per-family detection, flow unit, % (net.beacon alone, OR views)\n")
    b = d10["layers"]["net.beacon"]["flow"]["detection"]
    rows = [["net.beacon", p(d10["layers"]["net.beacon"]["flow"]["fa_benign"], 2)] + [p(b.get(f)) for f in fams]]
    for k, nm in (("or_l2a", "OR 5 L2a"), ("or_l2a_beacon", "OR 5 L2a + beacon")):
        rows.append([nm, p(d10[k]["fa_benign"], 2)] + [p(d10[k]["detection"].get(f)) for f in fams])
    out.append(table(["view", "FA %"] + [SHORT.get(f, f) for f in fams], rows))
    out.append("\n## 5. Detection delay of net.beacon (minutes from the first attack flow of the test segment to the first alarmed flow)\n")
    dl = d10["layers"]["net.beacon"]["flow"]["delay_min"]
    rows = []
    for f in fams:
        v = dl.get(f)
        if not v:
            continue
        got = [x for x in v if x is not None]
        rows.append([f, f"{np.median(got):.0f}" if got else "never", f"{len(got)}/{len(v)}"])
    out.append(table(["family", "median delay (min)", "segments detected"], rows))
    out.append("\n## 6. Harness ablation, D10 (logistic combiner; tcp_flags + L2a (+ beacon))\n")
    acc = {}
    for nm in ("l1_l2a", "l1_l2a_beacon", "l2a_beacon", "l1_beacon", "beacon_only"):
        h = d10["harness_" + nm]
        rows = []
        for k, r in h["ablation"].items():
            vals = [r["detection_by_attack"].get(f) for f in fams]
            mac = float(np.mean([v if v is not None else 0.0 for v in vals]))
            acc[f"{nm}:{k}"] = mac
            rows.append([k, f"{r['auc']:.3f}", p(r["detection"]), p(r["false_alarm_rate"], 2), p(mac)] + [p(v) for v in vals])
        c = h["combined"]
        out.append(f"\n### {nm}\n")
        out.append(table(["configuration", "AUC", "detection (all attack flows) %", "FA %", "macro over the 11 families %"] + [SHORT.get(f, f) for f in fams], rows))
        out.append(f"combined: FA {p(c['false_alarm_rate'], 2)} %, median delay {c['delay']['median_delay_s']:.0f} s, segments detected {p(c['delay']['detected_fraction'])} %\n")
    out.append("\n## 7. Transfer D10 -> D23 Tue-20-02 (only D23 file with addresses; no Bot there). D23 Fri-02-03 Bot: not evaluable (src_ip / dst_ip 100% NaN)\n")
    rows = []
    for k in ("transfer", "refit"):
        r = d23[k]
        rows.append([k, p(r["flow"]["fa_benign"], 2), p(r["flow"]["fa_benign_published_labels"], 2), p(r["window"]["fa_benign_cells"], 2),
                     p(r["flow"]["detection"].get("DDoS-LOIC-HTTP"))])
    out.append(table(["variant", "FA flow %", "FA flow published %", "FA window %", "LOIC flows %"], rows))
    out.append(f"testable benign flows (D23 Tue, transfer): {p(d23['transfer']['testable_share_benign'], 2)} %\n")
    out.append("\n## 8. Resolvable period (synthetic groups, thresholds from validation; pair = at least one alarm in the group; 20 groups, 720 min each)\n")
    periods = sorted({int(k.split("|")[1]) for k in lim})
    for jit in ("0.0", "0.1", "0.3", "poisson"):
        pass
    rows = []
    for P in periods:
        row = [P]
        for jit in ("0.0", "0.1", "0.3", "poisson"):
            r = lim[f"{jit}|{P}"]
            row.append(f"{p(r['phase_pair'], 0)} / {p(r['rate_pair'], 0)}")
        rows.append(row)
    out.append(table(["period (s)", "jitter 0: phase / rate pair %", "jitter 10%", "jitter 30%", "Poisson (control)"], rows))
    out.append("phase = max(cv, mad, tol, acf); rate = sub-minute metronome statistic (also fires on high-rate Poisson: it is a steady-rate detector, not a period detector).\n")
    out.append("\n## 9. Validation choices (s4_dev_val.json): Bot flow detection on val at 1% benign FA, per (window, N_MIN, port-conditioned)\n")
    rows = [[k, p(v["net.beacon"]["fa"], 2), p(v["net.beacon"]["bot"])] for k, v in dev.items()]
    out.append(table(["win_nmin_portcond", "FA val %", "Bot val %"], rows))
    open(os.path.join(RES, "s4_tables.md"), "w").write("\n".join(out))
    L = d10["layers"]["net.beacon"]
    pairs = L["extra"]["bot_pairs"]
    a = {"C1_fa_flow": L["flow"]["fa_benign"], "C1_fa_flow_published": L["flow"]["fa_benign_published_labels"], "C1_fa_window": L["window"]["fa_benign_cells"],
         "C2_bot_flows": L["flow"]["detection"].get("Bot"), "C2_pairs_alarmed": int(sum(g["alarmed"] > 0 for g in pairs)), "C2_pairs": len(pairs),
         "C3_bot_harness_l1_l2a": d10["harness_l1_l2a"]["combined"]["detection_by_attack"].get("Bot"),
         "C3_bot_harness_with_beacon": d10["harness_l1_l2a_beacon"]["combined"]["detection_by_attack"].get("Bot"),
         "C3_macro_l1_l2a": acc.get("l1_l2a:all"), "C3_macro_with_beacon": acc.get("l1_l2a_beacon:all"),
         "C3_fa_with_beacon": d10["harness_l1_l2a_beacon"]["combined"]["false_alarm_rate"],
         "C5_transfer_fa": d23["transfer"]["flow"]["fa_benign"], "C5_refit_fa": d23["refit"]["flow"]["fa_benign"]}
    json.dump(a, open(os.path.join(RES, "s4_acceptance.json"), "w"), indent=1)
    print(json.dumps(a, indent=1))


if __name__ == "__main__":
    main()
