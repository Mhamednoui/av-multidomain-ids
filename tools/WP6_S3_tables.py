"""WP6 S3 tables + POST-TEST DIAGNOSTIC (labelled; nothing is re-chosen): results/WP6/s3_tables.md from s3_crosschoice.json, s3_dev.json,
s3_test.json; diagnostic results/WP6/s3_diag.json = (a) per-domain calibration shift: share of clean ticks above the 0.99 level of the fusion
ECDF (half A) on validation half B vs test, (b) which domain is the strongest contributor at the clean-composite alarm ticks of the test
(deterministic replay of the same frozen fusion on the same clean composites: same seed, clean composites are built first).
Run: python -u -W ignore tools/WP6_S3_tables.py
"""
import json
import pickle
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from common.config import results_dir  # noqa: E402
from fusion import composite as CP  # noqa: E402
import WP6_S3_lib as L  # noqa: E402

OUT = results_dir("WP6")
pc = lambda x, d=1: "-" if x is None else f"{100 * x:.{d}f}%"


def diag(fz):
    pv, pt = L.load_packs("val"), L.load_packs("test")
    H = fz["halves"]
    out = {"note": "POST-TEST diagnostic; no choice", "shift": {}, "clean_alarm_top_domain": {}}
    for fam in ("K", "C"):
        fus = fz["fusions"][(fz["chosen"], fam, "all")]
        out["shift"][fam] = {}
        for d in fus.domains:
            gb = set(H["B"][fam][d])
            vb = np.concatenate([s["score"] for s in pv[fam][d]["series"] if s["kind"] == "clean" and s["group"] in gb])
            te = np.concatenate([s["score"] for s in pt[fam][d]["series"] if s["kind"] == "clean"])
            out["shift"][fam][d] = {"val_B_above_0.99": float((fus.cal[d].transform(vb) >= 0.99).mean()),
                                    "test_above_0.99": float((fus.cal[d].transform(te) >= 0.99).mean()), "val_B_ticks": int(len(vb)), "test_ticks": int(len(te))}
        c = fz["composites"][fam]
        B = CP.Builder(fam, pt[fam], None, c["seed"])
        comps = B.clean_composites(c["n_clean"])
        X, s = L.system_scores(fus, comps)
        al = s >= fus.threshold
        top = np.array(fus.domains)[np.argmax(X, axis=1)][al]
        u, n = np.unique(top, return_counts=True)
        out["clean_alarm_top_domain"][fam] = {"alarm_ticks": int(al.sum()), "fa_tick_replay": float(al.mean()),
                                              "share": {str(a): float(b / al.sum()) for a, b in zip(u, n)}}
    return out


def main():
    cc = json.loads((OUT / "s3_crosschoice.json").read_text())
    dv = json.loads((OUT / "s3_dev.json").read_text())
    ts = json.loads((OUT / "s3_test.json").read_text())
    fz = pickle.load(open(OUT / "s3_frozen.pkl", "rb"))
    dg = diag(fz)
    (OUT / "s3_diag.json").write_text(json.dumps(dg, indent=1))
    L_ = ["# WP6 S3 tables (generated by tools/WP6_S3_tables.py from results/WP6/s3_*.json)", ""]
    L_ += ["## 1. Cross-domain additions (validation only, S2b leave-one-group-out dev folds)", "",
           "| data | candidate | FA rows | worst group | selection det | mean det | correct / wrong / undecided blame |", "|---|---|---|---|---|---|---|"]
    for ds in ("kitti", "comma"):
        for k, v in cc[ds].items():
            if not isinstance(v, dict):
                continue
            p = v["pooled_single"]
            L_.append(f"| {ds} | {k}{' (chosen)' if cc['choice'][ds] == k else ''} | {pc(v['fa_rows'], 2)} | {v['worst_group'][0]} {pc(v['worst_group'][1])} | "
                      f"{pc(v['selection_mean_detection'])} | {pc(v['mean_detection_single'])} | {pc(p['correct_blame'])} / {pc(p['wrong_blame'])} / {pc(p['undecided'])} |")
    L_ += ["", f"KITTI poor ICP quality fraction on dev: {cc['kitti']['poor_quality_fraction']}; comma glitch-filtered edge-seconds: {pc(cc['comma']['filtered_fraction'], 3)}.", ""]
    L_ += ["## 2. Combiner choice (validation half B)", "", "| combiner | family | FA tick | alarm events / h | mean det (single-domain families) |", "|---|---|---|---|---|"]
    for m, v in dv["methods"].items():
        for fam in ("K", "C"):
            x = v[fam]
            L_.append(f"| {m} | {fam} | {pc(x['fa_tick'], 2)} | {x['fa_events_per_hour']:.1f} | {pc(x['mean_detection_single'])} |")
    L_ += ["", f"Pooled half-B mean detection: {dv['selection']['pooled_mean_detection_half_B']} -> chosen **{dv['selection']['chosen']}**.", ""]
    L_ += ["## 3. Test (ONE run): headline and alternative rows", "", "| family | row | FA tick | alarm events / h | mean det (single) | per attacked domain |", "|---|---|---|---|---|---|"]
    for fam in ("K", "C"):
        R = ts["families"][fam]
        h = R["headline"]
        pd_ = ", ".join(f"{d} {pc(x)}" for d, x in h["per_domain_mean_detection"].items())
        L_.append(f"| {fam} | **{ts['chosen']} (headline, zero-shot)** | {pc(h['fa_tick'], 2)} [{pc(h['ci']['fa_tick'][0], 1)}, {pc(h['ci']['fa_tick'][1], 1)}] | "
                  f"{h['fa_events_per_hour']:.1f} | {pc(h['mean_detection_single'])} [{pc(h['ci']['mean_detection'][0])}, {pc(h['ci']['mean_detection'][1])}] | {pd_} |")
        for k, v in R.items():
            if k in ("headline", "ablation"):
                continue
            pd_ = ", ".join(f"{d} {pc(x)}" for d, x in v["per_domain_mean_detection"].items())
            L_.append(f"| {fam} | {k} | {pc(v['fa_tick'], 2)} | {v['fa_events_per_hour']:.1f} | {pc(v['mean_detection_single'])} | {pd_} |")
    L_ += ["", "Brackets: 95% cluster bootstrap over the vehicle groups (K: 7 KITTI test drives, C: 4 comma test routes).", ""]
    L_ += ["## 4. Test ablation (same combiner, threshold re-fitted on validation half B for each configuration)", "",
           "| family | configuration | FA tick | alarm events / h | mean det (single) |", "|---|---|---|---|---|"]
    for fam in ("K", "C"):
        h = ts["families"][fam]["headline"]
        L_.append(f"| {fam} | all | {pc(h['fa_tick'], 2)} | {h['fa_events_per_hour']:.1f} | {pc(h['mean_detection_single'])} |")
        for k, v in ts["families"][fam]["ablation"].items():
            L_.append(f"| {fam} | {k} | {pc(v['fa_tick'], 2)} | {v['fa_events_per_hour']:.1f} | {pc(v['mean_detection_single'])} |")
    L_ += ["", "## 5. Test: detection, median delay, attribution per attack family (headline)", ""]
    for fam in ("K", "C"):
        L_ += [f"### Family {fam}", "", "| family | attacked domain | n | detection | without cross | median delay s | attributed | cross blame (detected) |", "|---|---|---|---|---|---|---|---|"]
        h = ts["families"][fam]["headline"]["families"]
        noc = ts["families"][fam]["ablation"].get("without cross", {}).get("families", {})
        for f, v in sorted(h.items(), key=lambda x: (x[1]["attacked"], x[0])):
            tag = " (v2 comparison, physically impossible)" if f in CP.V2_COMPARISON else (" (coordinated)" if f in CP.COORDINATED[fam] else "")
            L_.append(f"| {f}{tag} | {v['attacked']} | {v['n']} | {pc(v['detection'])} | {pc(noc.get(f))} | {v['median_delay_s']} | {pc(v['attributed'])} | "
                      f"{v.get('cross_blame_counts', '')} |")
        L_.append("")
    L_ += ["## 6. Cross-domain layer alone at its own 1% threshold (S2b choice + S3 addition: FIRST test number, labelled)", "",
           "| data | FA rows | detection per attack (run level) |", "|---|---|---|"]
    for f, v in ts["cross_first_test"].items():
        L_.append(f"| {'KITTI' if f == 'K' else 'comma'} | {pc(v['fa_rows'], 2)} ({v['clean_rows']} rows) | " + ", ".join(f"{a} {pc(x)}" for a, x in v["detection"].items()) + " |")
    L_ += ["", "Blame counts (detected runs): see s3_test.json `cross_first_test`.", ""]
    L_ += ["## 7. Each domain at its own threshold on the clean test ticks (tick = max of the second's samples)", "", "| domain | FA ticks | clean ticks |", "|---|---|---|"]
    for d, v in ts["domain_own_fa_ticks"].items():
        L_.append(f"| {d} | {pc(v['fa_ticks_own_threshold'], 2)} | {v.get('clean_ticks', '-')} |")
    L_ += ["", "## 8. POST-TEST diagnostic (s3_diag.json; no choice made from it)", "", "| family | domain | val half B above 0.99 | test above 0.99 | test clean ticks |", "|---|---|---|---|---|"]
    for fam, v in dg["shift"].items():
        for d, x in v.items():
            L_.append(f"| {fam} | {d} | {pc(x['val_B_above_0.99'], 2)} | {pc(x['test_above_0.99'], 2)} | {x['test_ticks']} |")
    L_ += ["", "Strongest contributor at the clean-composite alarm ticks (test): " + "; ".join(
        f"{fam}: " + ", ".join(f"{d} {pc(s)}" for d, s in sorted(v["share"].items(), key=lambda x: -x[1])) for fam, v in dg["clean_alarm_top_domain"].items()), ""]
    L_ += ["## 9. v2 side by side (NOT like-for-like)", "",
           f"v2 meta fusion: {pc(ts['v2_reference']['accuracy'], 2)} accuracy at {pc(ts['v2_reference']['fa'], 2)} FA ({ts['v2_reference']['source']}): one row per domain drawn "
           "independently per SAMPLE, 50% all-normal mix, a supervised meta-classifier trained on the attack classes it is tested on, random halves for CAN / network.",
           "v3 composite view (50% clean composites / 50% attacked composites, composite = whole drive of 8-45 s (K) / 120 s (C), an alarm anywhere in a clean composite is a false composite):", ""]
    for fam in ("K", "C"):
        v = ts["families"][fam]["headline"]["v2_style"]
        L_.append(f"- {fam}: accuracy {pc(v['accuracy'])}, composite FA {pc(v['composite_FA'])}, composite detection {pc(v['composite_detection'])} (n = {v['n']}).")
    L_ += ["", "## 10. Acceptance (s3_acceptance.json)", "", "| check | value | rule | verdict |", "|---|---|---|---|"]
    for k, v in ts["acceptance"].items():
        val = v["value"]
        if isinstance(val, dict):
            val = "; ".join(f"{d}: fused {pc(x['fused'])} vs alone {pc(x['alone'])}" for d, x in val.items())
        elif isinstance(val, float):
            val = f"{val:.4f}"
        L_.append(f"| {k} | {val} | {v['rule']} | {'MET' if v['met'] else 'NOT MET'} |")
    (OUT / "s3_tables.md").write_text("\n".join(L_) + "\n", encoding="utf-8")
    print(json.dumps(dg, indent=1))


if __name__ == "__main__":
    main()
