"""WP4 S1: markdown tables (cleaning counts per file, labels, split counts, held-out families) from results/WP4/s1_clean_*.json.
Writes results/WP4/s1_tables.md and results/WP4/s1_heldout.json. Held-out rule (fixed in the notes before the counts):
a family is evaluable if test >= 100 and val >= 30 flows after cleaning; every evaluable family is held out in S7 (leave-one-attack-out).
"""
import json, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
R = os.path.join(ROOT, "results", "WP4")


def main():
    out = ["# WP4 S1 tables (generated by tools/WP4_s1_tables.py from results/WP4/s1_clean_*.json)", ""]
    held = {}
    for ds in ["D10", "D23"]:
        p = os.path.join(R, "s1_clean_%s.json" % ds)
        if not os.path.exists(p):
            continue
        j = json.load(open(p))
        out += ["## %s cleaning per file" % ds, "",
                "| file | lines read | empty rows | repeated headers | rows | exact dup | conflicting | clean | bad ts |",
                "|---|---|---|---|---|---|---|---|---|"]
        for f, v in sorted(j["files"].items()):
            out.append("| %s | %d | %d | %d | %d | %d | %d | %d | %d |" % (
                f[:42], v["lines_read"], v["empty_rows"], v["repeated_header_rows"], v["rows_after_header_empty"],
                v["exact_duplicates_removed"], v["conflicting_label_rows_removed"], v["rows_clean"], v["bad_timestamp"]))
        t = j["total"]
        out.append("| TOTAL | %d | %d | %d | %d | %d | %d | %d | %d |" % (
            t["lines_read"], t["empty_rows"], t["repeated_header_rows"], t["rows_after_header_empty"],
            t["exact_duplicates_removed"], t["conflicting_label_rows_removed"], t["rows_clean"], t["bad_timestamp"]))
        out += ["", "## %s labels and split counts (clean rows)" % ds, "",
                "| family | before dedup | clean | train | val | test | gap | evaluable |", "|---|---|---|---|---|---|---|---|"]
        ev = []
        for fam in sorted(j["labels_before_dedup"]):
            sc = [j["split_counts"].get(s, {}).get(fam, 0) for s in ["train", "val", "test", "gap"]]
            ok = fam != "BENIGN" and sc[2] >= 100 and sc[1] >= 30 and sc[0] > 0
            if ok:
                ev.append(fam)
            out.append("| %s | %d | %d | %d | %d | %d | %d | %s |" % (fam, j["labels_before_dedup"][fam],
                                                                       j["labels_clean"].get(fam, 0), *sc, "yes" if ok else "no"))
        out.append("| (all) | %d | %d | %d | %d | %d | %d | |" % (sum(j["labels_before_dedup"].values()), t["rows_clean"],
                                                                  *[j["split_totals"].get(s, 0) for s in ["train", "val", "test", "gap"]]))
        held[ds] = ev
        out += ["", "## %s days" % ds, "", "| day | train | val | test | gap |", "|---|---|---|---|---|"]
        for d, v in sorted(j["days"].items()):
            out.append("| %s | %d | %d | %d | %d |" % (d, *[v.get(s, 0) for s in ["train", "val", "test", "gap"]]))
        out.append("")
    json.dump({"rule": "test >= 100 and val >= 30 flows after cleaning", "evaluable_families": held}, open(os.path.join(R, "s1_heldout.json"), "w"), indent=1)
    open(os.path.join(R, "s1_tables.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out[-60:]))


if __name__ == "__main__":
    main()
