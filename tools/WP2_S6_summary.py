"""WP2 S6: generated summary tables (no hand-typed numbers) from results/WP2/s6_*.json -> results/WP2/s6_summary.md
Usage: python tools/WP2_S6_summary.py
"""
import json
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parent.parent / "results" / "WP2"


def p(x):
    return "-" if x is None else f"{100 * x:.1f}%"


def main():
    road, ch, d11, c2r = (json.load(open(OUT / f)) for f in ("s6_road.json", "s6_ch.json", "s6_d11.json", "s6_ch2road.json"))
    L = ["# WP2 S6 summary (generated by tools/WP2_S6_summary.py from results/WP2/s6_*.json)", ""]
    L += ["## Leakage checks", "", "### Gain importance (top 3, share of total gain)", "", "| dataset | timing model | payload model |", "|---|---|---|"]
    top = lambda imp: ", ".join(f"{a} {100 * b:.0f}%" for a, b in sorted(imp.items(), key=lambda x: -x[1])[:3])
    L.append(f"| ROAD P1 | {top(json.load(open(OUT.parent.parent.parent / 'data_extra' / 'WP2_S6_cache' / 'road_run' / 'p1_info.json'))['t']['importance'])} | "
             f"{top(json.load(open(OUT.parent.parent.parent / 'data_extra' / 'WP2_S6_cache' / 'road_run' / 'p1_info.json'))['p']['importance'])} |")
    L.append(f"| Car-Hacking | {top(ch['importance']['t'])} | {top(ch['importance']['p'])} |")
    for s, v in d11.items():
        L.append(f"| D11 {s} | {top(v['fit']['t']['importance'])} | {top(v['fit']['p']['importance'])} |")
    L += ["", "### Shuffled-label control (5 seeds; mean AUC on validation; bound 0.55; count = AUC of the number of frames per window)", "",
          "| dataset | model | frame AUC mean | window AUC mean | count AUC | pass |", "|---|---|---|---|---|---|"]
    for ds, sh in [("ROAD", road["shuffle"]), ("Car-Hacking", ch["shuffle"])] + [(f"D11 {s}", v["shuffle"]) for s, v in d11.items()]:
        for m, r in sh.items():
            cnt = r.get("count_auc_reference", road.get("count_auc_reference_val") if ds == "ROAD" else None)
            L.append(f"| {ds} | {m} | {r['mean_frame_auc']:.3f} | {r['mean_window_auc']:.3f} | {cnt if cnt is None else round(cnt, 3)} | {r['pass']} |")
    L += ["", "### dt == 0 (D11): fraction of frames with dt_prev == 0", "", "| set | clean | injected | timing AP with zero dt / zero dt set to NaN |", "|---|---|---|---|"]
    for s, v in d11.items():
        z = v["dt_prev_zero"]
        ab = v["dt_zero_ablation"]
        L.append(f"| {s} | {z['clean_zero']}/{z['clean_n']} = {100 * z['clean_zero'] / z['clean_n']:.4f}% | {z['inj_zero']}/{z['inj_n']} = {100 * z['inj_zero'] / z['inj_n']:.3f}% | "
                 + (f"{ab['val_ap_with_zero_dt']:.5f} / {ab['val_ap_zero_dt_set_nan']:.5f}" if ab else "not run") + " |")
    L += ["", "## v2 failure cases", "", "### Reverse-bit windows (ID 0xD0 byte2 & 0x08; out-of-fold; ambient_dyno_reverse itself is a TEST capture and not scored)", "",
          "| model | alarms / windows | rate | other clean ambient windows | per capture (alarms/windows) |", "|---|---|---|---|---|"]
    for m, r in road["oof"].items():
        rv = r["reverse_windows"]
        L.append(f"| {m} | {rv['alarms']}/{rv['n']} | {p(rv['rate'])} | {p(rv['other_clean_ambient_rate'])} (n {rv['n_other']}) | " +
                 "; ".join(f"{c.replace('ambient_', '')} {x['alarms']}/{x['windows']}" for c, x in rv["by_capture"].items()) + " |")
    L += ["", "### Car-Hacking-trained models on ROAD validation captures (v2: 0.5% recall)", "",
          "| model | threshold | window recall (attack windows) | window FA clean | frame recall | frame FA clean | frame recall / FA at p=0.5 |", "|---|---|---|---|---|---|---|"]
    for m, v in c2r.items():
        for t in ("T0_carhacking_thresholds", "T1_road_val_calibrated"):
            x = v[t]
            L.append(f"| {m} | {t} | {p(x['window_recall_all_attack'])} | {p(x['fa_clean_windows'])} | {p(x['frame_recall_all'])} | {p(x['frame_fa_clean'])} | "
                     f"{p(x['frame_recall_at_prob_0.5'])} / {p(x['frame_fa_at_prob_0.5'])} |")
    L += ["", "## ROAD per-family window detection (validation captures)", "", "| model | protocol | family (original / masquerade): detected, mean window recall |", "|---|---|---|"]
    for prot in ("p1", "oof"):
        for m, r in road[prot].items():
            L.append(f"| {m} | {'P1 seen families (instance 2, val threshold)' if prot == 'p1' else 'OOF unseen families (pooled OOF threshold)'} | " +
                     "; ".join(f"{k} {v['detected']}/{v['n']} ({p(v['mean_window_recall'])})" for k, v in r["by_family"].items()) + " |")
    L += ["", "OOF clean-window FA per ambient capture (pooled 1%): "]
    for m, r in road["oof"].items():
        L.append(f"- {m}: pooled {p(r['pooled_fa_clean'])}; " + ", ".join(f"{c.replace('ambient_', '')} {p(x)}" for c, x in r["ambient_fa"].items()))
    L += ["", "## Car-Hacking test blocks (scored once)", "", "| config | clean FA | other-normal FA | " + " | ".join(ch["test"]["cfg"]["L1"]["recall"]) + " |", "|---|---|---|" + "---|" * len(ch["test"]["cfg"]["L1"]["recall"])]
    for c, x in ch["test"]["cfg"].items():
        L.append(f"| {c} | {p(x['fa_clean'])} | {p(x['fa_other_normal'])} | " + " | ".join(p(v) for v in x["recall"].values()) + " |")
    L += ["", "## D11 test subsets (scored once): clean-window FA and mean attack-type window recall", "",
          "| set | subset | vehicle | regime | FA L1 | FA L4t | FA L4p | FA L1+L4t | recall L1 | recall L4t | recall L4p | recall L1+L4t | adds (t / p) |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for s, v in d11.items():
        for sub, x in v["subsets"].items():
            for rn, r in x["regimes"].items():
                c = r["test"]["cfg"]
                mr = lambda k: np.mean(list(c[k]["recall"].values()))
                L.append(f"| {s} | {sub} | {x['vehicle'][0]} | {rn} | " + " | ".join(p(c[k]["fa_clean"]) for k in ("L1", "L4t", "L4p", "L1+L4t")) + " | " +
                         " | ".join(p(mr(k)) for k in ("L1", "L4t", "L4p", "L1+L4t")) + f" | {r['test']['adds']['L1+L4t']['adds']} / {r['test']['adds']['L1+L4p']['adds']} |")
    open(OUT / "s6_summary.md", "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
