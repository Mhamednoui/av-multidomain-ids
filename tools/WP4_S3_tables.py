"""WP4 S3: markdown tables generated from results/WP4/s3_d10.json, s3_d23.json, s3_dev_val.json -> results/WP4/s3_tables.md
(and the macro summary numbers used by the acceptance check -> results/WP4/s3_acceptance.json)."""
import json
import os

import numpy as np

RES = os.path.join(os.path.dirname(__file__), "..", "results", "WP4")
EVAL = ["Bot", "DDoS-LOIC-HTTP", "DoS-GoldenEye", "DoS-Hulk", "DoS-SlowHTTPTest", "DoS-Slowloris", "FTP-Patator", "SSH-Patator", "PortScan",
        "Web-BruteForce", "Web-XSS"]
SHORT = {"DDoS-LOIC-HTTP": "LOIC", "DoS-GoldenEye": "GoldenEye", "DoS-Hulk": "Hulk", "DoS-SlowHTTPTest": "SlowHTTP", "DoS-Slowloris": "Slowloris",
         "FTP-Patator": "FTP", "SSH-Patator": "SSH", "Web-BruteForce": "WebBF", "Web-XSS": "XSS"}
DOS5 = ["DoS-Hulk", "DoS-GoldenEye", "DoS-Slowloris", "DoS-SlowHTTPTest", "DDoS-LOIC-HTTP"]


def p(x, d=1):
    return "-" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{100 * x:.{d}f}"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def det_table(layers, extra, fams, key="detection"):
    head = ["layer", "W", "FA headline %", "FA published labels %", "AUC"] + [SHORT.get(f, f) for f in fams]
    rows = []
    for n, r in layers.items():
        f = r["flow"]
        rows.append([n, r["W"] or "-", p(f["fa_benign"], 2), p(f["fa_benign_published_labels"], 2), f"{f['auc']:.3f}"] + [p(f["detection"].get(x)) for x in fams])
    for n, r in extra.items():
        rows.append([n, "-", p(r["fa_benign"], 2), p(r["fa_benign_published_labels"], 2), "-"] + [p(r["detection"].get(x)) for x in fams])
    return table(head, rows)


def main():
    out = []
    dev = json.load(open(os.path.join(RES, "s3_dev_val.json")))
    d10 = json.load(open(os.path.join(RES, "s3_d10.json")))
    d23 = json.load(open(os.path.join(RES, "s3_d23.json")))
    fams = [f for f in EVAL if f in d10["families"]]
    out.append("# WP4 S3 tables (generated by tools/WP4_S3_tables.py from results/WP4/s3_*.json)\n")
    out.append(f"Test side: {d10['test_side']} (mode {d10['mode']}). Detection in % of the attack flows of the family (pre-dedup stage flows). "
               "FA headline = benign flows outside the audited Infiltration file; published = all BENIGN-labelled flows.\n")
    out.append("## 1. D10 test, flow unit (alarm = layer score >= its 1% benign-val threshold)\n")
    out.append(det_table(d10["layers"], {"OR of the 5 L2a layers": d10["or_l2a"]}, fams))
    out.append("\n## 2. D10 test, window unit (cell = layer key x minute; detection = share of attack cells alarmed; FA = benign cells)\n")
    rows = [[n, r["W"], p(r["window"]["fa_benign_cells"], 2), p(r["window"]["fa_benign_cells_published_labels"], 2), r["window"]["n_benign_cells"]] +
            [p(r["window"]["detection"].get(f)) for f in fams] for n, r in d10["layers"].items() if r["window"]]
    out.append(table(["layer", "W", "FA cells %", "FA cells published %", "benign cells"] + [SHORT.get(f, f) for f in fams], rows))
    out.append("\n## 3. Detection delay (median minutes from the first attack flow of the test segment to the first alarmed attack flow; n detected / n segments)\n")
    rows = []
    for n, r in d10["layers"].items():
        cells = []
        for f in fams:
            dl = r["flow"]["delay_min"].get(f)
            if not dl:
                cells.append("-")
                continue
            got = [x for x in dl if x is not None]
            cells.append(f"{np.median(got):.0f} ({len(got)}/{len(dl)})" if got else f"never (0/{len(dl)})")
        rows.append([n] + cells)
    out.append(table(["layer"] + [SHORT.get(f, f) for f in fams], rows))
    out.append("Resolution is one minute (D10 timestamps); a window alarms at its end, so a delay of 0 means the first minute.\n")
    out.append("\n## 4. False alarms on benign test flows: where they come from (flow unit)\n")
    rows = []
    for n, r in d10["layers"].items():
        f = r["flow"]
        rows.append([n, p(f["fa_benign"], 2), p(f["fa_benign_in_attack_cells"], 2), p(f["fa_benign_other"], 2), p(f["benign_in_attack_cells_share"], 2), p(f["fa_benign_audit_file"], 2)] +
                    [f"{k[-5:]}: {p(v, 2)}" for k, v in sorted(f["fa_by_day"].items())][:0])
    out.append(table(["layer", "FA headline %", "of which benign flows in a cell that contains an attack %", "other %", "share of benign flows in attack cells %", "FA in audited file %"], rows))
    out.append("\nFA by test day (headline benign flows, flow unit, %)\n")
    days = sorted({k for r in d10["layers"].values() for k in r["flow"]["fa_by_day"]})
    out.append(table(["layer"] + days, [[n] + [p(r["flow"]["fa_by_day"].get(k), 2) for k in days] for n, r in d10["layers"].items()]))
    out.append("\n## 5. Effect of de-duplication (OR of the L2a layers; detection on the test flows that survive the S1 de-duplication vs all pre-dedup flows)\n")
    o = d10["or_l2a"]
    out.append(table(["family", "all pre-dedup flows %", "flows kept by de-dup %"], [[f, p(o["detection"][f]), p(o.get("detection_dedup_subset", {}).get(f))] for f in fams if f in o["detection"]]))
    out.append("\n## 6. Harness ablation, D10 (topology-free L1 net.tcp_flags + L2a; logistic combiner; subsample drawn after the window features)\n")
    acc = {}
    for nm in ("l1_l2a", "l2a_only"):
        h = d10["harness_" + nm]
        att = sorted({a for r in h["ablation"].values() for a in r["detection_by_attack"]})
        rows = []
        for k, r in h["ablation"].items():
            vals = [r["detection_by_attack"].get(f) for f in fams]
            mac = float(np.mean([v if v is not None else 0.0 for v in vals]))
            acc[f"{nm}:{k}"] = mac
            rows.append([k, f"{r['auc']:.3f}", p(r["detection"]), p(r["false_alarm_rate"], 2), p(mac)] + [p(v) for v in vals])
        out.append(f"\n### {nm}\n")
        out.append(table(["configuration", "AUC", "detection (all attack flows) %", "FA %", "macro over the 11 families %"] + [SHORT.get(f, f) for f in fams], rows))
        c = h["combined"]
        out.append(f"combined: FA {p(c['false_alarm_rate'], 2)} %, median delay {c['delay']['median_delay_s']:.0f} s, segments detected {p(c['delay']['detected_fraction'])} %\n")
    out.append("\n## 7. D23 Tue-20-02 (the only D23 file with IPs)\n")
    fams23 = d23["families"]
    for key, title in (("transfer", "transfer: D10 tables and thresholds, no refit, dos_rate without destination lookup"), ("refit", "refit on D23 benign train / val")):
        out.append(f"\n### {title}\n")
        extra = {"OR of the 5 L2a layers": d23[key + "_or"]}
        out.append(det_table(d23[key], extra, fams23))
        out.append(table(["layer", "FA cells %"], [[n, p(r["window"]["fa_benign_cells"], 2)] for n, r in d23[key].items()]))
    open(os.path.join(RES, "s3_tables.md"), "w").write("\n".join(out))
    # acceptance numbers
    L = d10["layers"]
    best = lambda f: max(L[n]["flow"]["detection"].get(f, 0.0) for n in L if n.startswith("net.") and n != "net.tcp_flags")
    a = {"B1_max_fa_flow_headline": max(L[n]["flow"]["fa_benign"] for n in L),
         "B1_max_fa_window": max(L[n]["window"]["fa_benign_cells"] for n in L if L[n]["window"]),
         "B1_or_fa": d10["or_l2a"]["fa_benign"], "B1_stack_fa": d10["harness_l1_l2a"]["combined"]["false_alarm_rate"],
         "B2": {f: best(f) for f in ("PortScan", "SSH-Patator", "FTP-Patator")},
         "B3": {f: best(f) for f in DOS5}, "B3_n_ge_50": int(sum(best(f) >= 0.5 for f in DOS5)),
         "B4_macro": {"tcp_flags_alone": acc.get("l1_l2a:only_net.tcp_flags"), "l1_l2a_all": acc.get("l1_l2a:all"), "l2a_only_all": acc.get("l2a_only:all")},
         "B5_transfer": {"fa_or": d23["transfer_or"]["fa_benign"], "loic_or": d23["transfer_or"]["detection"].get("DDoS-LOIC-HTTP"),
                         "fa_by_layer": {n: r["flow"]["fa_benign"] for n, r in d23["transfer"].items()},
                         "loic_by_layer": {n: r["flow"]["detection"].get("DDoS-LOIC-HTTP") for n, r in d23["transfer"].items()}},
         "B5_refit": {"fa_or": d23["refit_or"]["fa_benign"], "loic_or": d23["refit_or"]["detection"].get("DDoS-LOIC-HTTP")}}
    json.dump(a, open(os.path.join(RES, "s3_acceptance.json"), "w"), indent=1)
    print(json.dumps(a, indent=1))


if __name__ == "__main__":
    main()
