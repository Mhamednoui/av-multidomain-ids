"""WP4 S6 tables + acceptance numbers from the JSON results (no hand-typed numbers): results/WP4/s6_tables.md, s6_acceptance.json."""
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from tools.WP4_S6_lib import EVAL10, EVAL23, RES

J = lambda n: json.load(open(os.path.join(RES, n)))  # noqa: E731
dev, d10, d23, loao = J("s6_dev_val.json"), J("s6_d10.json"), J("s6_d23.json"), J("s6_loao.json")
p = lambda x: "-" if x is None else "%.1f" % (100 * x)  # noqa: E731
f3 = lambda x: "-" if x is None else "%.3f" % x  # noqa: E731
out = []
w = out.append


def table(head, rows):
    w("| " + " | ".join(head) + " |")
    w("|" + "---|" * len(head))
    for r in rows:
        w("| " + " | ".join(str(c) for c in r) + " |")
    w("")


w("# WP4 S6 tables (generated by tools/WP4_S6_tables.py from results/WP4/s6_*.json)\n")
w("## 1. Hyperparameter search on validation (rule: macro detection of 11 families at 1% benign-val FA; ties -> macro AUC)\n")
table(["trial", "max_depth", "lr", "subsample", "colsample", "min_child", "lambda", "trees", "val macro %", "val macro AUC", "val FA %"],
      [[i + 1, t["params"]["max_depth"], t["params"]["learning_rate"], t["params"]["subsample"], t["params"]["colsample_bytree"], t["params"]["min_child_weight"],
        t["params"]["reg_lambda"], t["n_trees"], p(t["macro"]), f3(t["macro_auc"]), p(t["fa_val"])] for i, t in enumerate(dev["trials"])])
w("chosen: %s, %d trees; train rows %d, val rows %d. Check in the verdict script: val macro %.4f (dev %.4f)\n" % (
    dev["chosen"]["params"], dev["chosen"]["n_trees"], dev["n_train"], dev["n_val"], d10["val_check"]["macro"], dev["val_macro"]))

w("## 2. D10 test: L4 alone, 1%% budget (threshold %.3f log-odds from dedup benign validation)\n" % d10["val_check"]["threshold"])
S = d10["d10"]
table(["row set", "benign n", "attack n", "FA %", "macro11 %", "macro AUC", "blind4 %", "AUC all"],
      [[k, d10["n"][k]["benign"], d10["n"][k]["attack"], p(S[k]["fa_benign"]), p(S[k]["macro"]), f3(S[k]["macro_auc"]), p(S[k]["blind4"]), f3(S[k]["auc_all"])] for k in S if k in d10["n"]])
w("Per family (detection %, n = test flows in the row set):\n")
fams = sorted(S["dedup"]["detection"])
table(["family", "n dedup", "dedup det %", "dedup AUC", "n stage", "stage det %", "stage AUC"],
      [[f, S["dedup"]["n"][f], p(S["dedup"]["detection"][f]), f3(S["dedup"]["auc"][f]), S["stage"]["n"][f], p(S["stage"]["detection"][f]), f3(S["stage"]["auc"][f])] for f in fams])
w("Binary operating point p = 0.5 (margin 0) on dedup test (information; v2's 99.73%% was D01, random split, 7 classes: NOT comparable): %s\n" % json.dumps({k: round(v, 4) if isinstance(v, float) else v for k, v in S["v2_style_p05"].items()}))
w("Benign false alarms by destination port (dedup): %s\n" % json.dumps(d10["benign_fa_ports"]))

w("## 3. Null control (shuffled TRAIN labels, flow unit, same hyperparameters and trees; bound mean AUC <= 0.55 fixed before running)\n")
nl = d10["null"]
table(["seed", "AUC test dedup", "FA test % (own 1% threshold)", "detection % (own threshold)", "FA % at real threshold", "detection % at real threshold"],
      [[n["seed"], f3(n["auc_test_dedup"]), p(n["fa_test"]), p(n["detection_test"]), p(n["fa_at_real_threshold"]), p(n["detection_at_real_threshold"])] for n in nl["seeds"]])
w("mean AUC %.4f (bound %.2f): %s; real model AUC on the same rows %.4f\n" % (nl["mean_auc"], nl["bound"], "MET" if nl["met"] else "NOT MET", nl["real_auc_dedup"]))

w("## 4. Feature importance (share of total gain) and attributions of alarms\n")
imp = d10["importance"]["total_gain_share"]
table(["feature", "gain share %"], [[k, p(v)] for k, v in list(imp.items())[:15]])
if "ablation_drop_top1_val" in d10["importance"]:
    a = d10["importance"]["ablation_drop_top1_val"]
    w("Ablation (top feature %s dropped, retrained, validation): macro %.1f%% vs %.1f%% with it\n" % (a["dropped"], 100 * a["val_macro"], 100 * a["val_macro_full"]))
table(["group (alarmed flows, top 300 by score)", "top-5 features (mean share of |tree contribution|)"],
      [[g, "; ".join("%s %.0f%%" % (k, 100 * v) for k, v in x["top"])] for g, x in d10["attribution"].items()])

w("## 5. Bot: is it the fixed flow shape?\n")
B = d10["bot"]
w("Bot (dedup test): n %d, detection %s%%, AUC vs benign %s\n" % (B["bot_all_dedup"]["n"], p(B["bot_all_dedup"]["detection"]), f3(B["bot_all_dedup"]["auc_vs_benign"])))
table(["shape", "fwd/bwd pkts", "duration us (p5-p95)", "defining Bot flows", "Bot matched", "Bot unmatched", "benign matched", "benign matched on 8080", "det Bot matched %", "det Bot unmatched %",
       "FA benign matched %", "AUC Bot vs benign same shape", "reading", "byte-signature share Bot / benign %"],
      [[nm, "%g/%g" % (B["shapes"][nm]["fwd_pkts"], B["shapes"][nm]["bwd_pkts"]), "%.0f-%.0f" % tuple(B["shapes"][nm]["duration_us_p5_p95"]), B["shapes"][nm]["n_defining_bot_flows"],
        B[nm]["bot_matched"], B[nm]["bot_unmatched"], B[nm]["benign_matched"], B[nm]["benign_matched_port8080"], p(B[nm]["detection_bot_matched"]), p(B[nm]["detection_bot_unmatched"]),
        p(B[nm]["fa_benign_matched"]), f3(B[nm].get("auc_bot_vs_benign_same_shape")), B[nm].get("reading", "-"),
        "%s / %s" % (p(B[nm]["bot_matched_byte_signature_share"]), p(B[nm]["benign_matched_byte_signature_share"]))] for nm in ("train_shape", "val_shape")])
bb = J("s6_bot_benign_shape.json")
w("Who are the BENIGN-labelled flows with the Bot beacon shape (3/3 packets, 0.99-1.03 s, port 8080)? (tools/WP4_S6_botlabels.py, final D10 tables) Bot sources: %s; C2: %s\n" % (", ".join(bb["bot_sources"]), ", ".join(bb["bot_c2_8080"])))
table(["split", "Bot-labelled shape flows", "benign-labelled shape flows", "benign src is a Bot source", "benign dst is the Bot C2", "benign files"],
      [[sp, bb[sp]["shape_flows_bot"], bb[sp]["shape_flows_benign"], bb[sp]["benign_src_in_bot_sources"], bb[sp]["benign_dst_is_bot_c2"], bb[sp]["benign_files"]] for sp in ("train", "val", "test")])
w("top features of the alarmed Bot flows: %s\n" % json.dumps(B.get("bot_top_features")))

w("## 6. Leave-one-attack-out preview on VALIDATION (train without X; threshold = 1% of benign validation; test never read)\n")
rows = []
for nm, r in loao.items():
    for m, e in r["per_member"].items():
        rows.append([nm if len(r["members"]) > 1 else "family", m, e["n"], p(e["detection_l4"]), f3(e["auc_l4"]), p(e.get("detection_base")), p(e.get("detection_union")), p(r["fa_val_benign"]),
                     p(r.get("fa_union_val_benign"))])
table(["held out", "family", "n val", "L4 unseen det %", "L4 unseen AUC", "base det % (tcp_flags + L2a)", "base OR L4 det %", "L4 FA % (val)", "union FA % (val)"], rows)
w("Groups held out together (all members unseen):\n")
table(["group", "n val", "L4 det %", "AUC", "base det %", "union det %"],
      [[nm, r["group"]["n"], p(r["group"]["detection_l4"]), f3(r["group"]["auc_l4"]), p(r["group"].get("detection_base")), p(r["group"].get("detection_union"))] for nm, r in loao.items() if "group" in r])

fam_single = [f for f in EVAL10 if f in loao]
mac = lambda key: float(np.mean([loao[f]["per_member"][f][key] for f in fam_single]))  # noqa: E731
LO = {"macro_l4_unseen": mac("detection_l4"), "macro_base": mac("detection_base"), "macro_union": mac("detection_union"),
      "fa_base_val": float(np.mean([loao[f]["fa_base_val_benign"] for f in fam_single])), "fa_union_val": float(np.mean([loao[f]["fa_union_val_benign"] for f in fam_single])),
      "families_l4_unseen_ge50": [f for f in fam_single if loao[f]["per_member"][f]["detection_l4"] >= 0.5]}
w("Summary over the 11 single-family hold-outs (validation): macro detection L4 UNSEEN %.1f%%, base (tcp_flags + L2a, never trained on attacks) %.1f%%, base OR L4-unseen %.1f%%; FA base %.1f%%, union %.1f%% (budgets add up). "
  "Families where unseen L4 >= 50%%: %s\n" % (100 * LO["macro_l4_unseen"], 100 * LO["macro_base"], 100 * LO["macro_union"], 100 * LO["fa_base_val"], 100 * LO["fa_union_val"], ", ".join(LO["families_l4_unseen_ge50"])))

w("## 7. Harness (logistic combiner on the S3-S5 subsample protocol): does L4 add to the topology-free stack?\n")
for rs in ("dedup", "stage"):
    H = d10["harness"][rs]
    w("Row set **%s** (subsample val %d / test %d). Per family combined detection %%, FA %%.\n" % (rs, H["subsample"]["val"], H["subsample"]["test"]))
    cfgs = [c for c in H if c != "subsample"]
    table(["config", "FA %", "det %", "macro11 %", "blind4 %"] + [f[:9] for f in EVAL10],
          [[c, p(H[c]["combined"]["false_alarm_rate"]), p(H[c]["combined"]["detection"]), p(H[c]["macro11"]), p(H[c]["blind4"])] +
           [p(H[c]["combined"]["detection_by_attack"].get(f, 0.0)) for f in EVAL10] for c in cfgs])
    O = d10["or_view"][rs]
    w("OR view (each layer at its own 1%% budget, whole test table), row set %s.\n" % rs)
    table(["config", "FA %", "macro11 %"] + [f[:9] for f in EVAL10], [[c, p(O[c]["fa_benign"]), p(O[c]["macro11"])] + [p(O[c]["detection"][f]) for f in EVAL10] for c in O])

w("## 8. D23 (CSE-CIC-IDS2018 sample, test side)\n")
rows = []
for k in ("zero_shot", "recalibrated_no_refit", "on_network_refit"):
    z = d23[k]
    rows.append([k, p(z["fa_benign"]), p(z["macro"]), f3(z["macro_auc"])] + [p(z["detection"].get(f)) for f in EVAL23])
table(["regime", "FA benign %", "macro9 det %", "macro9 AUC"] + [f[:9] for f in EVAL23], rows)
w("AUC per family (zero-shot = same ranking as recalibrated): %s\n" % json.dumps({f: round(v, 3) for f, v in d23["zero_shot"]["auc"].items()}))
w("FA by day, zero-shot: %s\n" % json.dumps({k: round(v, 3) for k, v in d23["zero_shot"]["fa_by_day"].items()}))
w("n test: %s\n" % json.dumps(d23["n"]))
open(os.path.join(RES, "s6_tables.md"), "w").write("\n".join(out))

# ---------------- acceptance numbers
H = d10["harness"]["dedup"]
acc = {"E1_fa_dedup": S["dedup"]["fa_benign"], "E1_fa_stage": S["stage"]["fa_benign"], "E1_fa_published": S["published_labels_dedup"]["fa_benign"], "E1_met": bool(S["dedup"]["fa_benign"] <= 0.02),
       "E2_null_mean_auc": nl["mean_auc"], "E2_met": nl["met"],
       "E3_top5": d10["importance"]["top5"], "E3_top_share": list(imp.values())[0], "E3_flag_over_30pct": bool(list(imp.values())[0] > 0.30),
       "E4_reading_val_shape": B["val_shape"].get("reading"), "E4_auc_val_shape": B["val_shape"].get("auc_bot_vs_benign_same_shape"),
       "E4_reading_train_shape": B["train_shape"].get("reading"), "E4_auc_train_shape": B["train_shape"].get("auc_bot_vs_benign_same_shape"),
       "E5_loao_bot_det": loao["Bot"]["per_member"]["Bot"]["detection_l4"], "E5_loao_bot_met_70": bool(loao["Bot"]["per_member"]["Bot"]["detection_l4"] > 0.70),
       "E5_summary": LO, "E5_loao_det": {nm: {m: e["detection_l4"] for m, e in r["per_member"].items()} for nm, r in loao.items()},
       "E6_zero_shot_fa": d23["zero_shot"]["fa_benign"], "E6_met": bool(d23["zero_shot"]["fa_benign"] <= 0.05),
       "E7_macro_dedup": {c: H[c]["macro11"] for c in H if c != "subsample"}, "E7_fa_dedup": {c: H[c]["combined"]["false_alarm_rate"] for c in H if c != "subsample"},
       "E7_gain_base_to_base_l4": H["base_l4"]["macro11"] - H["base"]["macro11"],
       "E7_gain_stack_with_l3_to_with_l4": H["base_l3_l4"]["macro11"] - H["base_l3"]["macro11"],
       "E7_met": bool(H["base_l4"]["macro11"] - H["base"]["macro11"] >= 0.05 and H["base_l4"]["combined"]["false_alarm_rate"] <= 0.02)}
json.dump(acc, open(os.path.join(RES, "s6_acceptance.json"), "w"), indent=1)
print(json.dumps(acc, indent=1))
