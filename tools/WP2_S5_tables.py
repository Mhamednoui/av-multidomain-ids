"""WP2 S5: generates results/WP2/s5_summary.md from the JSON results (no hand-typed numbers)."""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "results" / "WP2"
sel, val, test = (json.load(open(OUT / f)) for f in ("s5_select.json", "s5_val.json", "s5_test.json"))
hw, dg = json.load(open(OUT / "s5_highway_fold.json")), json.load(open(OUT / "s5_diag_test.json"))
f = lambda x: "-" if x is None else (f"{x:.3f}" if isinstance(x, float) else str(x))
L = ["# WP2 S5 summary tables (generated by tools/WP2_S5_tables.py)", ""]
L += ["## Variant selection on train+val (s5_select.json)", "| variant | mean masquerade recall (L3c+L3d) | lead FA | lead windows |", "|---|---|---|---|"]
for k, v in sel["variants"].items():
    L.append(f"| {k} {v['name']} | {f(v['mean_masq_recall_union'])} | {f(v['lead_fa_union'])} | {v['lead_windows']} |")
L.append(f"\nChosen: {sel['chosen']} ({sel['chosen_rule']})\n")
L += ["## LOCO window FA per held-out clean capture at the pooled 1% threshold (chosen variant; s5_test.json)", "| capture | windows | L3c | L3d |", "|---|---|---|---|"]
for c, v in test["loco_fa_per_fold"].items():
    L.append(f"| {c} | {v['windows']} | {f(v['l3c'])} | {f(v['l3d'])} |")
L += ["", "## Unseen-regime fold: highway drive left out of the fit (s5_highway_fold.json)", "| variant | alarm rate at pooled 1% | median score |", "|---|---|---|"]
for k, v in hw.items():
    L.append(f"| {k} | {f(v['alarm_rate_at_pooled_1pct'])} | {f(v['median_score'])} |")
L += ["", "## Test, ROAD (exposure 5, ONE run) per capture: detected / delay s / clean FA", ""]
L += open(OUT / "s5_test_tables.md").read().split("\n")
L += ["", "## Clean test windows: FA per layer combination", "| combination | all clean (n=%d) | ambient only (n=%d) | attack-capture leads (n=%d) |" % (
    test["clean_window_fa_all"]["n"], test["clean_window_fa_ambient_only"]["n"], test["clean_window_fa_leads_only"]["n"]), "|---|---|---|---|"]
for k in ["L1", "L2b", "L3c", "L3d", "L3", "L1+L2b", "L2b+L3", "L1+L3", "L1+L2b+L3"]:
    L.append(f"| {k} | {f(test['clean_window_fa_all'][k])} | {f(test['clean_window_fa_ambient_only'][k])} | {f(test['clean_window_fa_leads_only'][k])} |")
L += ["", "## Masquerade captures detected (test), per combination", "| combination | " + " | ".join(c.replace("_attack", "").replace("_masquerade", "") for c in test["masquerade_detected"]["L3"]) + " | total |", "|---|" + "---|" * 6]
for k, d in test["masquerade_detected"].items():
    L.append(f"| {k} | " + " | ".join(str(x) for x in d.values()) + f" | {sum(bool(x) for x in d.values())}/5 |")
L += ["", "## Median z of the most deviating signals in the attack steps ([median z, inner OOF R2]; test)"]
for c, r in test["captures"].items():
    if r.get("median_z_top_signals_[z, r2]"):
        L.append(f"- {c}: {r['median_z_top_signals_[z, r2]']}")
L += ["", "## Post-verdict diagnostic (descriptive, s5_diag_test.json)"]
for c, r in dg.items():
    L.append(f"- {c}: {r}")
L += ["", "## Frame level (1% each, test): recall on injected frames / clean-frame FA"]
for c, r in test["captures"].items():
    L.append(f"- {c}: recall {f(r['frame_L3']['recall_1pct_each'])}, FA {f(r['frame_L3']['fa_clean'])}")
L += ["", f"AUC (window, L3, all test): {f(test['auc_window_l3_all'])}", f"Thresholds: {test['thresholds']}"]
open(OUT / "s5_summary.md", "w").write("\n".join(L))
print("\n".join(L[:30]))
