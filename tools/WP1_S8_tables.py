"""WP1 S8: readable tables (results/WP1/S8_tables.md) and the acceptance verdicts (results/WP1/S8_acceptance.json), generated from the JSON
files of the dev pass (S8_dev.json), the single test pass (S8_kitti.json), the controls (S8_control.json, S8_noise_nested.json), the
external tests (S8_external.json) and the freeze check (S8_freeze.json). No number is typed by hand.
Run from codes_v3/: python -u -W ignore tools/WP1_S8_tables.py
"""
import json
import re
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parent.parent / "results" / "WP1"
ATT = ["drift", "accel_drift", "jump", "freeze", "doppler_spoof", "meaconing"]
SHORT = {"drift": "drift", "accel_drift": "accel", "jump": "jump", "freeze": "freeze", "doppler_spoof": "Doppler", "meaconing": "meacon"}


def J(name):
    return json.loads((OUT / name).read_text())


def p(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def ci(c, d=0):
    return "-" if c is None else f"[{100 * c[0]:.{d}f}, {100 * c[1]:.{d}f}]"


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(map(str, r)) + " |" for r in rows])


def layer_row(n, r):
    rd = r["run_detected"]
    return [n, p(r["fa_clean_runs"], 2), p(r["worst_drive_fa"]), r["n_drives_fa_gt_3pct"], f"{r['auc_row_level']:.3f}"] + [p(rd[a], 0) for a in ATT] + [p(r["mean_run_detected"])]


HEAD = ["layer / configuration", "FA clean runs", "worst drive FA", "drives > 3%", "AUC"] + [SHORT[a] for a in ATT] + ["mean run-level"]


def main():
    dev, te, ctl, noise, ext, frz = J("S8_dev.json"), J("S8_kitti.json"), J("S8_control.json"), J("S8_noise_nested.json"), J("S8_external.json"), J("S8_freeze.json")
    names = [n for n in te["layers_test"] if not n.startswith("opt.")]
    opt = [n for n in te["layers_test"] if n.startswith("opt.")]
    md = ["# WP1 S8 tables (generated by tools/WP1_S8_tables.py from results/WP1/S8_*.json)\n"]
    # --- 1 test layers alone
    md.append("## 1. KITTI test (7 drives, 490 runs): every layer alone, LODO calibration of the 15 dev drives (run-level detection of the 6 attacks)\n")
    md.append(table(HEAD, [layer_row(n, te["layers_test"][n]) for n in names + opt]))
    # --- 2 combiners
    md.append("\n## 2. Combiner methods on the 16 default layers (test; nested dev in brackets = FA / mean run-level)\n")
    rows = []
    for m, r in te["combiners_test"].items():
        d = dev["combiners_nested"].get(m)
        rows.append(layer_row(m, r) + [f"{p(d['fa_clean_runs'], 2)} / {p(d['mean_run_detected'])}" if d else "-"])
    md.append(table(HEAD + ["nested dev"], rows))
    md.append(f"\nChosen on the nested dev results by the pre-registered rule: **{dev['chosen_method']}** ({dev['chosen_reason']}). All methods are fitted without the Doppler / meaconing attack rows except the row logistic_all6_seen.\n")
    # --- 3 deployed detail
    dep = te["deployed"]
    b = dep["bootstrap"]
    md.append("## 3. Deployed combined detector (test): run-level and row-level detection, 95% bootstrap intervals, delay\n")
    rows = []
    for a in ATT:
        dl = dep["summary"]["delays"][a]
        rows.append([a, p(dep["run_detected"][a], 1), ci(b["drives"][a]), ci(b["runs"][a]), p(dep["row_detection"][a], 1),
                     "-" if dl["delays_q10_25_50_75_90_s"] is None else " / ".join(f"{x:.0f}" for x in dl["delays_q10_25_50_75_90_s"]),
                     p(dl["within_10s"], 0), p(dl["within_30s"], 0)])
    rows.append(["mean of 6", p(dep["mean_run_detected"], 1), ci(b["drives"]["mean_run"]), ci(b["runs"]["mean_run"]), p(dep["mean_row_detection"], 1), "", "", ""])
    md.append(table(["attack", "run-level", "CI drives (7)", "CI runs (70)", "row-level", "delay q10/25/50/75/90 (fixes = s)", "detected within 10 s", "within 30 s"], rows))
    md.append(f"\nClean-run FA {p(dep['fa_clean_runs'], 2)}; CI drives {ci(b['drives']['fa_clean_runs'], 2)}, CI runs {ci(b['runs']['fa_clean_runs'], 2)}. AUC {b['point']['auc']:.3f}, CI drives {b['drives']['auc'][0]:.3f}-{b['drives']['auc'][1]:.3f}. "
              f"Slow drift < 0.5 m/s within 30 s: {dep['summary']['slow_drift_lt_0.5_within_30s']['detected']} of {dep['summary']['slow_drift_lt_0.5_within_30s']['runs']} runs flagged inside the window the run has; "
              f"runs with a full 30 s window: {dep['summary']['slow_drift_lt_0.5_within_30s']['runs_with_full_30s']} (target UNTESTABLE on KITTI).\n")
    md.append("Per-drive clean-row FA (test): " + ", ".join(f"{d} {p(v, 2)}" for d, v in dep["per_drive_fa"].items()) + "\n")
    md.append("Paired difference to B2 (cluster bootstrap over 7 drives): mean run-level " + f"{100 * dep['vs_B2_paired']['mean_run_diff']:+.1f} points {ci(dep['vs_B2_paired']['mean_run_diff_ci'])}, FA difference {ci(dep['vs_B2_paired']['fa_diff_ci'], 2)}; "
              f"to cusum_dr (best single layer): {100 * dep['vs_cusum_dr_paired']['mean_run_diff']:+.1f} points {ci(dep['vs_cusum_dr_paired']['mean_run_diff_ci'])}.\n")
    md.append("### Detection by attack severity (run-level, three equal bins of the generator range)\n")
    rows = []
    for a, v in dep["by_severity"].items():
        rows.append([a] + [f"{p(d, 0)} (n={n}, {e0:.2g}-{e1:.2g})" for d, n, e0, e1 in zip(v["detected"], v["runs"], v["edges"][:-1], v["edges"][1:])])
    md.append(table(["attack", "low", "middle", "high"], rows))
    # --- 4 ablation
    md.append("\n## 4. Ablation of the deployed combiner (method fixed; each configuration refitted). Test and nested dev side by side\n")
    allt, alld = te["ablation_test"]["all"], dev["ablation_nested"]["all"]
    rows = []
    for k, r in te["ablation_test"].items():
        d = dev["ablation_nested"].get(k)
        rows.append([k, p(r["fa_clean_runs"], 2), f"{r['auc_row_level']:.3f}", p(r["mean_run_detected"]), f"{100 * (r['mean_run_detected'] - allt['mean_run_detected']):+.1f}",
                     p(r["run_detected"]["doppler_spoof"], 0), p(r["run_detected"]["meaconing"], 0),
                     "-" if d is None else f"{p(d['fa_clean_runs'], 2)} / {p(d['mean_run_detected'])} / {100 * (d['mean_run_detected'] - alld['mean_run_detected']):+.1f}"])
    md.append(table(["configuration", "test FA", "test AUC", "test mean run-level", "delta vs all (points)", "Doppler", "meacon", "nested dev FA / mean / delta"], rows))
    # --- 5 per-drive FA
    md.append("\n## 5. Per-drive false-alarm spread (clean + pre-onset normal rows)\n")
    dd = dev["combiners_nested"][dev["chosen_method"]]["per_drive_fa"]
    md.append("Nested dev held-out (deployed method): " + ", ".join(f"{d} {p(v, 2)}" for d, v in dd.items()) + "\n")
    md.append("Test, per layer (worst drive): " + ", ".join(f"{n.split('.')[-1]} {p(te['layers_test'][n]['worst_drive_fa'])}" for n in names) + "\n")
    # --- 6 val-only
    vo = te["val_only"]
    md.append("## 6. Calibration on the 3 validation drives only (side by side, S2-S3 practice)\n")
    rows = [layer_row("deployed, val-only (3 drives)", vo["deployed"]), layer_row("deployed, LODO (15 drives)", dep)]
    rows += [layer_row(n + " (val-only)", vo["layers"][n]) for n in ("gps.dr_resid_10", "gps.ekf_nis", "gps.cusum_dr")]
    md.append(table(HEAD, rows))
    # --- 7 cusum selection
    cs = dev["cusum_selection"]
    md.append("\n## 7. Nested CUSUM configuration (selection inside each LODO fold)\n")
    md.append(f"Full development selection (= S4): ekf `{cs['full_dev']['ekf']}` (J {cs['full_dev']['J_ekf']:.3f}), dr `{cs['full_dev']['dr']}` (J {cs['full_dev']['J_dr']:.3f}).\n")
    for k in ("ekf", "dr"):
        md.append(f"Fold counts {k}: " + "; ".join(f"`{c}` x{n}" for c, n in cs["fold_counts"][k].items()) + "\n")
    s = noise["summary"]
    md.append(f"Noise model re-estimated inside the 15 folds: phi {s['phi_range'][0]:.4f}-{s['phi_range'][1]:.4f} (S3 {noise['s3_values']['phi']:.4f}), sigma {s['sigma_range'][0]:.4f}-{s['sigma_range'][1]:.4f} "
              f"(S3 {noise['s3_values']['sigma']:.4f}), q_acc selected {s['q_acc_selected_counts']} (S3 {noise['s3_values']['q_acc']}): selection unchanged in {15 - len(s['folds_with_q_different_from_s3'])} of 15 folds.\n")
    # --- 8 v2 comparison
    b2t = te["layers_test"]["gps.dr_resid_10"]
    md.append("## 8. Side by side with the v2 baseline (KITTI test, run-level detection; FA = clean runs)\n")
    rows = [["v2 B2 (WP0 S3, = v3 B2 with pooled 16-drive threshold)", p(b2t["fa_clean_runs"], 2)] + [p(b2t["run_detected"][a], 0) for a in ATT] + [p(b2t["mean_run_detected"])],
            ["v3 best single layer (cusum_dr)", p(te["layers_test"]["gps.cusum_dr"]["fa_clean_runs"], 2)] + [p(te["layers_test"]["gps.cusum_dr"]["run_detected"][a], 0) for a in ATT] + [p(te["layers_test"]["gps.cusum_dr"]["mean_run_detected"])],
            ["v3 default stack, noisy_or_log (zero-shot on Doppler / meaconing)", p(dep["fa_clean_runs"], 2)] + [p(dep["run_detected"][a], 0) for a in ATT] + [p(dep["mean_run_detected"])],
            ["v3 same, combiner also trained on Doppler / meaconing (logistic, side row)", p(te["combiners_test"]["logistic_all6_seen"]["fa_clean_runs"], 2)] + [p(te["combiners_test"]["logistic_all6_seen"]["run_detected"][a], 0) for a in ATT] + [p(te["combiners_test"]["logistic_all6_seen"]["mean_run_detected"])]]
    md.append(table(["detector", "FA"] + [SHORT[a] for a in ATT] + ["mean"], rows))
    md.append("\nv2 reference numbers quoted from the WP file: C2 (KITTI-trained XGBoost) FA 0.82%, drift 63% of runs; AV-GPS model on KITTI FA 63%; drift < 0.5 m/s: 0-11% of rows for every detector; UAV: GPS-vs-IMU residual alarm at 118.0 s, PX4 EKF never.\n")
    # --- 9 control
    md.append("## 9. Shuffled-label control (L4 retrained C2, S7 procedure), 5 seeds\n")
    rows = [[sd, f"{r['auc_test_rows']:.4f}", p(r["fa_clean_runs"], 2), p(np.mean(list(r["run_detected"].values())))] for sd, r in ctl["runs"].items()]
    md.append(table(["seed", "test AUC", "FA clean runs", "mean run-level detection"], rows))
    md.append(f"\nMean AUC over the 5 pre-registered seeds {ctl['auc_mean']:.4f} (min {ctl['auc_min']:.4f}, max {ctl['auc_max']:.4f}); bound 0.55 on the mean: {'MET' if ctl['met'] else 'NOT MET'}. Seed 12345 re-run reproduces S7 (0.553).\n")
    # --- 10 external
    u = ext["uav"]
    md.append("## 10. UAV live-spoofing flight (benign flight = calibration flight; first spoofed fix 118.0 s; pre-onset = t < 117 s)\n")
    rows = []
    for n, v in u["layers"]["spoofing"].items():
        rows.append([n, v["pre_onset_alarms"], p(v["pre_onset_fa"], 2), v["first_alarm_after_118s"], p(v["fraction_flagged_from_118s"], 0), u["layers"]["benign"][n]["alarms"], u["layers"]["jamming"][n]["alarms"]])
    c = u["combined"]["spoofing"]
    rows.append(["COMBINED (noisy_or_log)", c["pre_onset_alarms"], p(c["pre_onset_fa"], 2), c["first_alarm_after_118s"], p(c["fraction_flagged_from_118s"], 0), u["combined"]["benign"]["alarms"], u["combined"]["jamming"]["alarms"]])
    md.append(table(["layer", "pre-onset alarms (of 118 fixes)", "pre-onset FA", "first alarm >= 118 s", "flagged from 118 s", "benign flight alarms", "jamming flight alarms"], rows))
    md.append(f"\nCombined pre-onset alarms at t = {u['combined']['spoofing']['alarm_times_s'][:3]} s; Wilson 95% interval of the pre-onset FA {ci(c['pre_onset_fa_wilson95'], 1)}. Layers firing within 2 s of 118 s: {', '.join(u['layers_firing_within_2s_of_118s_names'] if 'layers_firing_within_2s_of_118s_names' in u else u['layers_firing_within_2s_of_118s'])}.\n")
    md.append("All-but-one on the UAV (pre-onset alarms / first alarm): " + "; ".join(f"{k.replace('all_but_gps.', '-')}: {v['pre_onset_alarms']} / {v['first_alarm_after_118s']}" for k, v in u["ablation"].items()) + "\n")
    a = ext["avgps"]
    md.append("## 11. AV-GPS test sessions (files 2-3: 3 normal, 3 spoofed placeholder sessions)\n")
    rows = []
    for n, v in a["layers"].items():
        rows.append([n, p(v["fa_own"], 1), p(v["detection_own"], 1), f"{v['auc']:.3f}", p(v.get("fa_kitti_threshold"), 1), p(v.get("detection_kitti_threshold"), 1)])
    cc = a["combined"]
    rows.append(["COMBINED (noisy_or_log, own val calibration)", p(cc["fa_own"], 1), p(cc["detection_own"], 1), f"{cc['auc']:.3f}", "-", "-"])
    md.append(table(["layer", "FA (own val threshold)", "detection attack rows", "AUC", "FA at KITTI threshold", "detection at KITTI threshold"], rows))
    md.append("\nSessions: " + "; ".join(f"{k} label {v['label']} rows {v['rows']} sats {v['mean_numsats']:.1f} hdop {v['mean_hdop']:.0f}" for k, v in a["test_sessions"].items())
              + f". Combined AUC permutation null (labels shuffled across the 6 sessions) 5th-95th percentile {cc['auc_session_label_permutation_null_q05_q95'][0]:.3f}-{cc['auc_session_label_permutation_null_q05_q95'][1]:.3f}. "
              f"Detection by spoofed session: {', '.join(f'{k} {p(v, 0)}' for k, v in cc['detected_by_session'].items())}; FA by normal session: {', '.join(f'{k} {p(v, 1)}' for k, v in cc['fa_by_session'].items())}.\n")
    (OUT / "S8_tables.md").write_text("\n".join(md) + "\n")

    # ------------------------------------------------------------------ acceptance
    L = te["layers_test"]
    best_auc_single = max((L[n]["auc_row_level"], n) for n in names)
    best_mean_single = max((L[n]["mean_run_detected"], n) for n in names)
    acc = {}
    tail = (OUT / "logs" / "S8_tests_tail.log").read_text() if (OUT / "logs" / "S8_tests_tail.log").exists() else ""
    m = re.search(r"(\d+) passed, (\d+) failed", tail)
    acc["G1_tests"] = {"verdict": "MET" if m and int(m.group(2)) == 0 else "NOT MET", "value": m.group(0) if m else "not run"}
    acc["G2_false_alarms"] = {"test_fa_clean_runs": dep["fa_clean_runs"], "nested_dev_fa": dev["combiners_nested"][dev["chosen_method"]]["fa_clean_runs"], "bound": 0.015,
                              "worst_test_drive_fa": dep["worst_drive_fa"], "test_drives_above_3pct": dep["n_drives_fa_gt_3pct"],
                              "verdict": "MET" if dep["fa_clean_runs"] <= 0.015 and dev["combiners_nested"][dev["chosen_method"]]["fa_clean_runs"] <= 0.015 else "NOT MET (test)"}
    acc["G3_targets"] = {"doppler": dep["run_detected"]["doppler_spoof"], "meaconing": dep["run_detected"]["meaconing"], "ci_drives_doppler": b["drives"]["doppler_spoof"], "ci_drives_meaconing": b["drives"]["meaconing"],
                         "verdict": "MET" if min(dep["run_detected"]["doppler_spoof"], dep["run_detected"]["meaconing"]) >= 0.75 else "NOT MET"}
    d_mean = dep["mean_run_detected"] - b2t["mean_run_detected"]
    worst_att = min(dep["run_detected"][x] - b2t["run_detected"][x] for x in ATT)
    acc["G4_beats_B2"] = {"mean_gain": d_mean, "mean_gain_ci_drives": dep["vs_B2_paired"]["mean_run_diff_ci"], "worst_attack_difference": worst_att,
                          "fa_dep": dep["fa_clean_runs"], "fa_b2": b2t["fa_clean_runs"],
                          "verdict": "MET" if d_mean >= 0.10 and worst_att >= -0.05 and dep["fa_clean_runs"] <= b2t["fa_clean_runs"] + 0.005 else "NOT MET"}
    acc["G5_combining_helps"] = {"auc_combined": dep["auc_row_level"], "best_single_auc": best_auc_single, "mean_combined": dep["mean_run_detected"], "best_single_mean": best_mean_single,
                                 "vs_cusum_dr_diff_ci": dep["vs_cusum_dr_paired"]["mean_run_diff_ci"],
                                 "verdict": "MET" if dep["auc_row_level"] >= best_auc_single[0] - 0.005 and dep["mean_run_detected"] >= best_mean_single[0] - 0.02 else "NOT MET"}
    earn, nodrop = [], []
    for n in names:
        r = te["ablation_test"]["all_but_" + n]
        costs = (allt["mean_run_detected"] - r["mean_run_detected"], allt["auc_row_level"] - r["auc_row_level"])
        (earn if costs[0] >= 0.01 or costs[1] >= 0.005 else nodrop).append((n, round(100 * costs[0], 1), round(costs[1], 4)))
    acc["G5_ablation"] = {"layers_earning_their_place_test": earn, "layers_not_earning": nodrop,
                          "max_single_drop_cost_points": max(100 * (allt["mean_run_detected"] - te["ablation_test"]["all_but_" + n]["mean_run_detected"]) for n in names),
                          "preregistered_expectation_no_drop_costs_2_points": bool(max(allt["mean_run_detected"] - te["ablation_test"]["all_but_" + n]["mean_run_detected"] for n in names) < 0.02)}
    acc["G6_shuffled_label_control"] = {"auc_mean": ctl["auc_mean"], "auc_max": ctl["auc_max"], "verdict": "MET" if ctl["met"] else "NOT MET"}
    acc["G7_intervals"] = {"verdict": "MET", "note": "bootstrap over 7 test drives and over runs in S8_kitti.json deployed.bootstrap"}
    cu = u["combined"]["spoofing"]
    acc["G8_uav"] = {"first_alarm_s": cu["first_alarm_after_118s"], "delay_s": cu["delay_from_first_spoofed_fix_s"], "pre_onset_fa": cu["pre_onset_fa"], "pre_onset_alarms": cu["pre_onset_alarms"],
                     "wilson95": cu["pre_onset_fa_wilson95"],
                     "verdict": "NOT MET (FA 2.54% > 2%; alarm time met)" if cu["pre_onset_fa"] > 0.02 and cu["delay_from_first_spoofed_fix_s"] <= 5 else
                                ("MET" if cu["delay_from_first_spoofed_fix_s"] is not None and cu["delay_from_first_spoofed_fix_s"] <= 5 else "NOT MET")}
    acc["G9_avgps"] = {"combined_fa_own": cc["fa_own"], "combined_detection_own": cc["detection_own"], "combined_auc": cc["auc"], "auc_null_q05_q95": cc["auc_session_label_permutation_null_q05_q95"],
                       "verdict": "as pre-registered: nothing usable (signal = placeholder artefact; FA far above budget)"}
    acc["G10_frozen"] = {"max_abs_diff_statistic": frz["max_abs_diff_statistic"], "alarm_disagreements": frz["alarm_disagreements"], "evidence_path_alarm_disagreements": frz["evidence_path_alarm_disagreements"],
                         "verdict": "MET" if frz["max_abs_diff_statistic"] < 1e-9 and frz["alarm_disagreements"] == 0 else "NOT MET"}
    acc["G11_v2_comparison"] = {"verdict": "reported (S8_tables.md section 8)"}
    acc["regression_vs_S7"] = te.get("regression_vs_S7")
    (OUT / "S8_acceptance.json").write_text(json.dumps(acc, indent=1, default=float))
    print(json.dumps({k: (v.get("verdict") if isinstance(v, dict) else v) for k, v in acc.items()}, indent=1, default=str))


if __name__ == "__main__":
    main()
