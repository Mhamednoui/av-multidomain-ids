"""WP6 S4 stage 4: markdown tables from results/WP6/s4_test.json, s4_dev.json, s4_acceptance.json (no number is typed by hand) -> results/WP6/s4_tables.md.
v2 reference numbers are read from ../codes_v2/results/zeroday_unseen.json and zeroday.json (read only).
Run: python -u -W ignore tools/WP6_S4_tables.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from common.config import results_dir  # noqa: E402
import WP6_S4_lib as L  # noqa: E402

OUT = results_dir("WP6")
V2 = Path(__file__).resolve().parent.parent.parent / "codes_v2" / "results"


def pc(x, d=1):
    return "-" if x is None else f"{100 * x:.{d}f}"


def ci(c):
    return "" if not c else f" [{pc(c[0])}, {pc(c[1])}]"


def main():
    T = json.loads((OUT / "s4_test.json").read_text())
    D = json.loads((OUT / "s4_dev.json").read_text())
    A = json.loads((OUT / "s4_acceptance.json").read_text())
    v2u = json.loads((V2 / "zeroday_unseen.json").read_text())
    o = []
    w = o.append
    w("# WP6 S4 zero-day v3: tables (generated by tools/WP6_S4_tables.py from results/WP6/s4_*.json)\n")
    w(f"Chosen on validation (seen families only): {T['chosen']}. Exposure: {T['exposure_caveat']}.\n")
    w("## 1. Acceptance (test, scored once)\n")
    w("| id | value | rule | verdict |\n|---|---|---|---|")
    for k, v in A.items():
        val = v.get("value")
        if isinstance(val, dict):
            val = "; ".join(f"{d}: rules {pc(x['rules'])} vs L3 {pc(x['l3'])}" for d, x in val.items())
        elif isinstance(val, float):
            val = pc(val, 2) if k.startswith(("Z1", "Z2")) else f"{val:.2f}"
        if k.startswith("Z5"):
            val = (f"K: held-out {v['delta_heldout_points_K']:+.1f} pts, FA {v['delta_fa_points_K']:+.2f} pts; C: held-out {v['delta_heldout_points_C']:+.1f} pts, "
                   f"FA {v['delta_fa_points_C']:+.2f} pts")
        if k.startswith("Z3"):
            val = f"held-out {pc(v['heldout'])} vs seen {pc(v['seen'])} (gap {v['value']:.1f} pts)"
        w(f"| {k} | {val} | {v.get('rule', '')} | {'MET' if v['met'] else 'NOT MET'} |")
    w("")
    w("## 2. System level (S3 composites, 2% budget, noisy_or / label-free): FA and mean detection per family category\n")
    w("Detection = mean over the families of the category of the composite detection. Held-out CI: cluster bootstrap over vehicle groups. 'equal-FA' = threshold at 2% of "
      "TEST clean ticks (test-informed diagnostic).\n")
    w("| set | variant | FA tick % | events/h | held-out % | seen % | lidar (label-free) % | choice-seen % | equal-FA FA % | equal-FA held-out % | equal-FA seen % |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for fam in ("K", "C"):
        for name, m in T["system"][fam].items():
            if not isinstance(m, dict) or "by_category" not in m:
                continue
            b, e = m["by_category"], m["equal_fa"]
            w(f"| {fam} | {name} | {pc(m['fa_tick'], 2)}{ci(m['ci_heldout']['fa_tick']) if m.get('ci_heldout') else ''} | {m['fa_events_per_hour']:.0f} | "
              f"{pc(b['heldout'])}{ci(m['ci_heldout']['mean_detection']) if m.get('ci_heldout') else ''} | {pc(b['seen'])} | {pc(b['lidar_labelfree'])} | {pc(b['choice_seen'])} | "
              f"{pc(e['fa_tick'], 2)} | {pc(e['by_category']['heldout'])} | {pc(e['by_category']['seen'])} |")
    w("")
    for fam in ("K", "C"):
        r = T["system"][fam]["novelty_rescued_vs_lost"]
        w(f"- {fam}: novelty layer vs matched no-novelty system: held-out composites rescued {r['heldout_rescued']}, lost {r['heldout_lost']} of {r['heldout_composites']}.")
    w("")
    w("## 3. Held-out types, detection per family (headline vs ablations; %)\n")
    for fam in ("K", "C"):
        S = T["system"][fam]
        cols = [n for n in ("headline (chosen)", "matched without novelty", "rules-only system", "l3-only system") if n in S]
        tab = S["headline (chosen)"]["families"]
        held = sorted([f for f, x in tab.items() if x["category"] == "heldout"], key=lambda f: (tab[f]["attacked"], f))
        w(f"### {fam}\n")
        w("| family | attacked domain | " + " | ".join(cols) + " | headline equal-FA | headline median delay s |")
        w("|---|---|" + "---|" * (len(cols) + 2))
        for f in held:
            w(f"| {f} | {tab[f]['attacked']} | " + " | ".join(pc(S[c]["families"][f]["detection"]) for c in cols) + f" | {pc(S['headline (chosen)']['equal_fa']['families'][f])} | "
              f"{'-' if tab[f]['median_delay_s'] is None else tab[f]['median_delay_s']} |")
        w("")
        w("Per attacked domain (held-out mean %, headline / without novelty / rules-only / L3-only): " + "; ".join(
            f"{k.split('|')[1]}: " + " / ".join(pc(S[c]["by_category_domain"].get(k)) for c in cols)
            for k in sorted(S["headline (chosen)"]["by_category_domain"]) if k.startswith("heldout|")))
        w("")
    w("## 4. Tier table per domain (tick level, group threshold = 1% of clean validation half-B ticks)\n")
    w("Group score = max of the group's calibrated layers. Detection = share of attack ticks above the threshold, families averaged equally; AUC vs clean test ticks. "
      "The cross rows' held-out families are the GPS doppler / meaconing seen through the motion witnesses.\n")
    w("| domain | row | thr | FA test % | held-out det % | held-out AUC | seen det % | seen AUC | other families det % (lidar / choice-seen) |")
    w("|---|---|---|---|---|---|---|---|---|")
    for key, rows in T["tier"].items():
        for r, x in rows.items():
            oth = x.get("mean_det_lidar_labelfree") if x.get("mean_det_lidar_labelfree") is not None else x.get("mean_det_choice_seen")
            ah = "-" if x["mean_auc_heldout"] is None else "%.3f" % x["mean_auc_heldout"]
            asn = "-" if x["mean_auc_seen"] is None else "%.3f" % x["mean_auc_seen"]
            w(f"| {key} | {r} | {x['thr']:.4f} | {pc(x['fa_test'], 2)} | {pc(x['mean_det_heldout'])} | {ah} | {pc(x['mean_det_seen'])} | {asn} | {pc(oth)} |")
    w("")
    w("### Held-out families, tick detection % per row\n")
    for key, rows in T["tier"].items():
        cf = L.domain_category_fn(L.DOM_OF.get(key, key))
        fams = sorted({f for x in rows.values() for f in x["families"] if cf(f) == "heldout"})
        if not fams:
            continue
        w(f"**{key}**\n")
        w("| row | " + " | ".join(fams) + " |")
        w("|---|" + "---|" * len(fams))
        for r, x in rows.items():
            w(f"| {r} | " + " | ".join(pc(x["families"][f]["det"]) if f in x["families"] else "-" for f in fams) + " |")
        w("")
    w("## 5. Novelty examples (alarms where the novelty entry is the strongest; layers that deviate most, in units of the clean spread)\n")
    for fam in ("K", "C"):
        for e in T["system"][fam]["headline (chosen)"].get("novelty_examples", []):
            w(f"- {fam} {e['family']} ({e['domain']}, tick {e['tick']}): " + ", ".join(f"{n} {z:.1f}" for n, z in e["top_layers"]))
    w("")
    w("## 6. Validation selection grid (seen families only, half B, K + C pooled)\n")
    w("| config | pooled seen det % | K seen % | C seen % | FA half B K / C % |")
    w("|---|---|---|---|---|")
    for k, v in D["grid"].items():
        w(f"| {k} | {pc(v['pooled_mean_detection_seen_K_C'])} | {pc(v['K']['mean_detection_seen'])} | {pc(v['C']['mean_detection_seen'])} | "
          f"{pc(v['K']['fa_tick_B'], 2)} / {pc(v['C']['fa_tick_B'], 2)} |")
    w(f"\nChosen: {D['chosen']}. Rule: {D['selection_rule']}.\n")
    w("### Same grid on test (information only; nothing is chosen from it)\n")
    w("| config | K FA % | K held-out % | K seen % | C FA % | C held-out % | C seen % |")
    w("|---|---|---|---|---|---|---|")
    for k in T["system"]["K"]["grid_all_configs"]:
        a, c = T["system"]["K"]["grid_all_configs"][k], T["system"]["C"]["grid_all_configs"][k]
        w(f"| {k} | {pc(a['fa_tick'], 2)} | {pc(a['by_category']['heldout'])} | {pc(a['by_category']['seen'])} | {pc(c['fa_tick'], 2)} | {pc(c['by_category']['heldout'])} | {pc(c['by_category']['seen'])} |")
    w("")
    w("## 7. v2 side-by-side (NOT like-for-like)\n")
    w("| | v2 (codes_v2/results/zeroday_unseen.json) | v3 (this step) |\n|---|---|---|")
    hk = T["system"]["K"]["headline (chosen)"]
    w(f"| zero-day layer | OCSVM (nu 0.02) on the outputs of the four detectors, trained on seen attacks' detector outputs | label-free physics / rule layers + normal-only L3 + evidence-novelty ({T['chosen']['nov']}) fitted on clean validation evidence |")
    w(f"| false alarms | benign FA {pc(v2u['benign_false_alarm_rate'], 2)}% per sample (val 2% budget) | clean composite tick FA {pc(hk['fa_tick'], 2)}% (K), {pc(T['system']['C']['headline (chosen)']['fa_tick'], 2)}% (C) per second |")
    nw = T["tier"]["network"]
    for k, lab in (("network:Bot", "network Bot (unseen)"), ("network:WebAttack", "network WebAttack (unseen)"), ("lidar:GhostCluster", "lidar GhostCluster (unseen)")):
        x = v2u["attacks"][k]
        w(f"| {lab} | zero-day layer {pc(x['zero_day'], 2)}%, supervised {pc(x['supervised_detector'], 2)}% | see below |")
    wa = [nw["rules + L3"]["families"].get(f, {}).get("det") for f in ("Web-BruteForce", "Web-XSS")]
    w(f"| v3 network WebAttack (Web-BruteForce, Web-XSS), tick level at 1% | | rules + L3: {pc(wa[0])} / {pc(wa[1])}%; system composites: "
      f"{pc(hk['families'].get('Web-BruteForce', {}).get('detection'))} / {pc(hk['families'].get('Web-XSS', {}).get('detection'))}% |")
    w("| v3 network Bot | | not in the one-host D10 view; M1-NET leave-one-attack-out: unseen Bot 0% (cited, not re-run) |")
    lid = T["tier"]["lidar"]
    g = lid["frozen domain score (S3)"]["families"].get("GhostCluster", {}).get("det")
    l1 = lid["rules (physics / rule)"]["families"].get("GhostCluster", {}).get("det")
    w(f"| v3 lidar GhostCluster | | tick level at 1%: label-free L1 {pc(l1)}%; frozen domain score (with the supervised XGB) {pc(g)}%; box cloud, physically impossible on a single-return sensor |")
    w("")
    w("Protocol differences: v2 removed whole attack types from the detectors' training and scored per-sample rows of the pooled test set (Bot 5.3%, WebAttack 96.3%, "
      "D01 dedup features); v3 never trained any layer on attacks (physics / rule / normal-only), removes the held-out types from the combiner / novelty / config choices, "
      "and scores time series (1 Hz ticks, composite drives of 8-120 s with the onset inside the drive, any alarm after the onset counts).")
    (OUT / "s4_tables.md").write_text("\n".join(o) + "\n", encoding="utf-8")
    print("tables written")


if __name__ == "__main__":
    main()
