"""WP4 S7 tables: results/WP4/s7_tables.md generated from s7_d10.json, s7_d23.json, s7_dev_val.json, s7_prep.json (no hand-typed numbers).
Usage: python -u -W ignore tools/WP4_S7_tables.py"""
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from tools.WP4_S7_lib import EVAL10, EVAL23, RES, STACKS

SHORT = {"Bot": "Bot", "DDoS-LOIC-HTTP": "LOIC-HTTP", "DoS-GoldenEye": "GoldenEye", "DoS-Hulk": "Hulk", "DoS-SlowHTTPTest": "SlowHTTP", "DoS-Slowloris": "Slowloris",
         "FTP-Patator": "FTP", "SSH-Patator": "SSH", "PortScan": "PortScan", "Web-BruteForce": "Web-BF", "Web-XSS": "Web-XSS", "Infiltration": "Infiltr.", "Heartbleed": "Heartbl.",
         "Web-SQLi": "SQLi", "DDoS-HOIC": "HOIC", "DDoS-LOIC-UDP": "LOIC-UDP"}


def p(x, d=1):
    return "-" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{100 * x:.{d}f}"


def pc(x, ci, d=1):
    return f"{p(x, d)} [{p(ci[0], d)}, {p(ci[1], d)}]" if ci else p(x, d)


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]) + "\n"


def fam_table(entries, fams, ci=True, with_n=None):
    """entries: list of (label, summary dict)."""
    head = ["stack", "FA %", "macro %"] + [SHORT.get(f, f) for f in fams]
    rows = []
    for lab, s in entries:
        rows.append([lab, pc(s["fa"], s.get("fa_ci") if ci else None, 2), pc(s["macro"], s.get("macro_ci") if ci else None)] +
                    [pc(s["detection"].get(f), s.get("detection_ci", {}).get(f) if ci else None, 0 if ci else 1) for f in fams])
    if with_n:
        rows.append(["n flows", "", ""] + [str(with_n["n"].get(f, "")) for f in fams])
        rows.append(["10-min blocks holding the family (CI unit)", "", ""] + [str(with_n["n_blocks"].get(f, "")) for f in fams])
    return table(head, rows)


def main():
    r = json.load(open(os.path.join(RES, "s7_d10.json")))
    dev = json.load(open(os.path.join(RES, "s7_dev_val.json")))
    prep = json.load(open(os.path.join(RES, "s7_prep.json")))
    o = []
    A = o.append
    A("# WP4 S7 tables (generated by tools/WP4_S7_tables.py from results/WP4/s7_*.json)\n")
    A("Rows: D10 test STAGE stream (pre-dedup, %d flows, %d ten-minute blocks); detection = share of attack flows with a combined alarm; brackets = 95%% bootstrap over 10-minute blocks (2000 resamples). "
      "Headline benign = published BENIGN minus the audited Infiltration file.\n" % (r["n_rows"], r["n_blocks"]))
    fams = EVAL10 + ["Infiltration"]
    A("## 1. Final stacks, published labels (detection % per family, CI in brackets)\n")
    ent = [(k + " [" + v["method"] + "]", v["published"]) for k, v in r["stacks"].items()]
    A(fam_table(ent, fams, True, r["stacks"]["H"]["published"]))
    A("\nAUC (all attack vs headline benign) and families >= 50%:\n")
    A(table(["stack", "layers", "AUC", "families >= 50% of 11", "FA % published labels (audit file included)", "FA % audit file alone"],
            [[k, ", ".join(x.replace("net.", "") for x in v["layers"]), "%.4f" % v["published"]["auc"], v["published"]["n_ge50"], p(v["published"]["fa_pub"], 2),
              p(v["published"]["fa_audit_file"], 1)] for k, v in r["stacks"].items()]))
    A("\n## 2. Bot with the documentation correction (benign flows between the five Ares victims and 205.174.165.73:8080 relabelled Bot)\n")
    c = prep
    A("Rule matches: val %d (%d published Bot + %d relabelled), test %d (%d published Bot + %d relabelled); matches with another attack label: none.\n" % (
        c["val"]["rule_matches"], c["val"]["of_which_published_bot"], c["val"]["relabelled_benign_to_bot"], c["test"]["rule_matches"], c["test"]["of_which_published_bot"],
        c["test"]["relabelled_benign_to_bot"]))
    A(table(["stack", "Bot published (n=%d) %%" % r["stacks"]["H"]["published"]["n"]["Bot"], "Bot corrected (n=%d) %%" % r["stacks"]["H"]["bot_corrected"]["n"]["Bot"],
             "FA published %", "FA corrected %"],
            [[k, pc(v["published"]["detection"]["Bot"], v["published"]["detection_ci"]["Bot"]), pc(v["bot_corrected"]["detection"]["Bot"], v["bot_corrected"]["detection_ci"]["Bot"]),
              pc(v["published"]["fa"], v["published"]["fa_ci"], 2), pc(v["bot_corrected"]["fa"], v["bot_corrected"]["fa_ci"], 2)] for k, v in r["stacks"].items()]))
    A("\n## 3. Dedup-rows view (rows of the de-duplicated final table only; PortScan keeps ~1% of its flows), detection %\n")
    A(fam_table([(k, v["dedup_rows"]) for k, v in r["stacks"].items()], fams, False, r["stacks"]["H"]["dedup_rows"]))
    A("\n## 4. Delay (minutes from the first attack flow of a test segment to the first combined alarm; one value per segment, '-' = never; resolution 1 minute)\n")
    rows = []
    for f in EVAL10:
        rows.append([SHORT[f]] + [", ".join("-" if x is None else "%.0f" % x for x in r["stacks"][k]["delay_min"].get(f, [])) for k in ("H", "O", "O+L4")])
    A(table(["family", "H", "O", "O+L4"], rows))
    A("\n## 5. Ablation, stack H (combiner re-selected on validation for every sub-stack; 'alone' = layer at its own 1% threshold)\n")
    for base in ("H", "O"):
        ab = r["ablation"][base]
        ent = [("all (" + r["stacks"][base]["method"] + ")", ab["all"])]
        ent += [("alone " + n.replace("net.", ""), s) for n, s in ab["alone"].items()]
        ent += [("all but " + n.replace("net.", "") + " [" + s["method"] + "]", s) for n, s in ab["all_but"].items()]
        A("\n### stack %s\n" % base)
        A(fam_table(ent, EVAL10, False))
        A("\nOR of the layers' own alarms (information; budgets add up): FA %s %%, macro %s %%\n" % (p(r["or_view"][base]["fa"], 2), p(r["or_view"][base]["macro"])))
    A("\n## 6. Every layer alone (own 1% threshold), published labels, detection %\n")
    A(fam_table([(n, v["published"]) for n, v in r["layers_alone"].items()], fams, False))
    A("\n## 7. Combiner sensitivity (information; the frozen method is the one chosen on validation)\n")
    rows = []
    for nm, d in r["combiner_sensitivity"].items():
        for m, v in d.items():
            rows.append([nm, m + (" (chosen)" if m == r["stacks"][nm]["method"] else ""), p(v["fa"], 2), p(v["macro"]), v["n_ge50"], "%.4f" % v["auc"]])
    A(table(["stack", "method", "FA %", "macro11 %", "families >= 50%", "AUC"], rows))
    A("\nSelection on validation (held-out-half detection at the 1% budget):\n")
    A(table(["stack", "chosen", "noisy_or", "logistic", "max"], [[k, dev["method"][k]] + ["%.3f" % dev["selection"][k][m] for m in ("noisy_or", "logistic", "max")] for k in STACKS if k in dev["selection"]]))
    A("\n## 8. Null control of the combiner (logistic only)\n")
    for k, v in r["null"].items():
        A("- %s: %s" % (k, v["note"] if "note" in v else "mean AUC %.3f over 5 shuffled-label refits (%s), bound %.2f: %s" % (
            v["mean_auc"], ", ".join("%.3f" % x["auc"] for x in v["seeds"]), v["bound"], "met" if v["met"] else "NOT met")))
    A("\nL4 null control (S6): shuffled-label retrain, 5 seeds, mean flow-level AUC 0.477 (bound 0.55), results/WP4/s6_d10.json.\n")
    if "loao" in r:
        A("\n## 9. Leave-one-attack-out, test side (family / group removed from the combiner selection; L4 retrained without it). Detection of the held-out family %, CI in brackets\n")
        base_det = {"H": r["stacks"]["H"]["published"]["detection"], "O": r["stacks"]["O"]["published"]["detection"]}
        for sn in ("H", "O", "O+topology", "O+L4", "L4 alone"):
            rows = []
            for nm, e in r["loao"].items():
                s = e["stacks"][sn]
                for m in e["members"]:
                    if m not in s["detection"]:
                        continue
                    ref = r["stacks"][sn]["published"]["detection"].get(m)
                    rows.append([nm if len(e["members"]) > 1 else "", SHORT.get(m, m), s["n"][m], pc(s["detection"][m], s["detection_ci"][m]), p(ref), p(s["fa"], 2), s["method"]])
                if len(e["members"]) > 1:
                    rows.append([nm + " (group pooled)", "", s["group_n"], p(s["group_detection"]), "", "", ""])
            A("\n### stack %s\n" % sn)
            A(table(["held-out group", "family", "n test flows", "LOAO detection % [CI]", "non-LOAO detection %", "FA %", "combiner"], rows))
        rows = []
        for sn in ("H", "O", "O+topology", "O+L4", "L4 alone"):
            single = [e["stacks"][sn]["detection"][EVAL10[i]] for i, nm in enumerate(EVAL10) for e in [r["loao"].get(nm)] if e and EVAL10[i] in e["stacks"][sn]["detection"]]
            ref = [r["stacks"][sn]["published"]["detection"][f] for f in EVAL10 if f in r["loao"]]
            rows.append([sn, len(single), p(float(np.mean(single))) if single else "-", p(float(np.mean(ref))) if ref else "-"])
        A("\nMacro over the single-family hold-outs (each family detected by the stack that never saw it):\n")
        A(table(["stack", "n families", "LOAO macro %", "non-LOAO macro % (same families)"], rows))
    open(os.path.join(RES, "s7_tables_d10.md"), "w").write("\n".join(o))
    # ---------------- D23
    p23 = os.path.join(RES, "s7_d23.json")
    if os.path.exists(p23):
        d = json.load(open(p23))
        o = ["# WP4 S7 tables, D23 (generated from results/WP4/s7_d23.json)\n"]
        A = o.append
        A("Sample rows: %s. D10 combiner methods: H %s, O %s.\n" % (d["n_sample"], d["method_H_d10"], d["method_O_d10"]))
        z = d["zero_shot_tcp_flags_all_days"]
        A("## 1. Zero-shot net.tcp_flags (D10 fit and threshold) on every D23 day (flow level; the only headline layer whose inputs exist on every day)\n")
        A("FA %s %% overall; by day: %s\n" % (pc(z["fa"], z.get("fa_ci"), 1), ", ".join("%s %s" % (k[5:], p(v, 1)) for k, v in z["fa_by_day"].items())))
        A(fam_table([("tcp_flags zero-shot", z)], [f for f in EVAL23], True))
        A("\n## 2. Zero-shot on Tue-20-02 (L2a layers need addresses; D10 thresholds, D10 combiner; only DDoS-LOIC-HTTP exists that day)\n")
        rows = []
        for view, v in d["zero_shot_tue"].items():
            if not isinstance(v, dict) or "H" not in v:
                continue
            for nm in ("H", "H without tcp_flags"):
                s = v[nm]
                rows.append([view, nm, pc(s["fa"], s["fa_ci"], 2), pc(s["detection"].get("DDoS-LOIC-HTTP"), s["detection_ci"].get("DDoS-LOIC-HTTP"), 1), "%.3f" % s["auc"]])
            for n, s in v["layers_alone"].items():
                rows.append([view, "alone " + n.replace("net.", ""), p(s["fa"], 2), p(s["detection"].get("DDoS-LOIC-HTTP")), ""])
        A(table(["rows", "stack", "FA % [CI]", "LOIC-HTTP detection % [CI]", "AUC"], rows))
        on = d["on_network"]
        A("\n## 3. On-network regime (refit on the D23 warm-up; thresholds from the D23 benign validation; combiner = noisy_or, no attack label)\n")
        A("Warm-up: %s\n" % on["warm_up"])
        A("### Tue-20-02, O = tcp_flags + scan + trw + bruteforce + dos_rate + service + AE (sample rows)\n")
        ent = [("O", on["tue"]["O"]), ("H layers only", on["tue"]["H_on_network"])] + [("alone " + n.replace("net.", ""), s) for n, s in on["tue"]["layers_alone"].items()]
        A(table(["stack", "FA % [CI]", "LOIC-HTTP detection % [CI]", "AUC"], [[l, pc(s["fa"], s["fa_ci"], 2), pc(s["detection"].get("DDoS-LOIC-HTTP"), s["detection_ci"].get("DDoS-LOIC-HTTP"), 1), "%.3f" % s.get("auc", float("nan"))] for l, s in ent]))
        A("\nAll-but-one (O, Tue): " + "; ".join("%s: FA %s / LOIC %s" % (n.replace("net.", ""), p(s["fa"], 2), p(s["detection"].get("DDoS-LOIC-HTTP"))) for n, s in on["tue"]["all_but"].items()) + "\n")
        fl = on["flow_all_days"]
        A("### All days, O-flow = tcp_flags + service + AE (flow level, sample rows), detection %, CI in brackets\n")
        ent = [("O-flow", fl["O_flow"])] + [("alone " + n.replace("net.", ""), s) for n, s in fl["layers_alone"].items()]
        A(fam_table(ent, EVAL23, True, fl["O_flow"]))
        A("\nFA by day (O-flow): " + ", ".join("%s %s" % (k[5:], p(v, 1)) for k, v in fl["O_flow"]["fa_by_day"].items()) + "\n")
        A("Detection by day | family (O-flow): " + "; ".join("%s %s" % (k, p(v, 0)) for k, v in fl["O_flow"]["detection_by_day_family"].items()) + "\n")
        A("\n## 4. dos_rate warm-up length on D23 Tue (information)\n")
        A(table(["fraction of warm-up", "hours", "flows", "known destinations", "FA % (test)", "LOIC detection %", "AUC"],
                [[k, "%.1f" % v["hours"], v["flows"], v["known_destinations"], p(v["fa_benign_test"], 2), p(v["detection_loic"]), "%.3f" % v["auc"]] for k, v in d["dos_rate_warmup_d23_tue"].items()]))
        A("\n## 5. dos_rate warm-up length on D10 validation (information)\n")
        w = dev["warmup"]
        A(table(["fraction", "minutes", "flows", "known destinations", "FA % (val benign)", "Hulk %", "GoldenEye %", "LOIC %", "AUC"],
                [[k, v["minutes"], v["flows"], v["known_destinations"], p(v["fa_benign_val"], 2), p(v["detection"]["DoS-Hulk"]), p(v["detection"]["DoS-GoldenEye"]),
                  p(v["detection"]["DDoS-LOIC-HTTP"]), "%.3f" % v["auc"]] for k, v in w.items() if k[0] in "01"]))
        open(os.path.join(RES, "s7_tables_d23.md"), "w").write("\n".join(o))
    print("tables written")


if __name__ == "__main__":
    main()
