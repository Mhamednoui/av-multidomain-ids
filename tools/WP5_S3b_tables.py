"""WP5 S3b step 4: tables and acceptance verdicts from the stored JSON (no recomputation of detections).
Reads results/WP5/{s3b_geometry,s3b_clean,s3b_inject_Mobile,s3b_inject_Stationary,s6_veremi,s6_tampa}.json.
Writes results/WP5/s3b_tables.md (long tables) and results/WP5/s3b_acceptance.json (verdicts). Run from codes_v3/: python -I -u -W ignore tools/WP5_S3b_tables.py"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.dont_write_bytecode = True
import numpy as np

OUT = ROOT / "results" / "WP5"
ENVS = ["Mobile", "Stationary"]
SEEN = [str(i) for i in list(range(1, 12)) + list(range(13, 20))]      # 12 DelayedMessages is reported apart (VeReMi artefact, no message age)
NAMES = {"1": "ConstPos", "2": "ConstPosOffset", "3": "RandomPos", "4": "RandomPosOffset", "5": "ConstSpeed", "6": "ConstSpeedOffset", "7": "RandomSpeed", "8": "RandomSpeedOffset",
         "9": "EventualStop", "10": "Disruptive", "11": "DataReplay", "12": "DelayedMessages", "13": "DoS", "14": "DoSRandom", "15": "DoSDisruptive", "16": "GridSybil",
         "17": "DataReplaySybil", "18": "DoSRandomSybil", "19": "DoSDisruptiveSybil", "12b": "DelayedBurst", "20": "GhostNearReceiver", "21": "FarPosOffset"}
ORDER = [str(i) for i in range(1, 20)] + ["12b", "20", "21"]


def pc(x, d=1):
    return "-" if x is None else f"{100 * x:.{d}f}%"


def load(name):
    return json.loads((OUT / name).read_text())


def gate(geo):
    res = {}
    for env, e in geo["envs"].items():
        bins = e["by_bin"]
        far, near = ["2-5 km", ">5 km"], ["<100 m", "100-300 m", "0.3-1 km"]

        def pooled(key_share, key_n, names):
            tot = sum(bins[b][key_n] for b in names)
            return sum((bins[b][key_share] or 0) * bins[b][key_n] for b in names) / tot if tot else None
        r = {"E1_ratio_range_far": [min(bins[b]["haversine_over_local_ratio_p1_p99"][0] for b in far if bins[b]["haversine_over_local_ratio_p1_p99"]),
                                    max(bins[b]["haversine_over_local_ratio_p1_p99"][1] for b in far if bins[b]["haversine_over_local_ratio_p1_p99"])]}
        r["E1"] = r["E1_ratio_range_far"][0] >= 0.9 and r["E1_ratio_range_far"][1] <= 1.1
        r["E2_far"], r["E2_near"] = pooled("E2_violation_share", "E2_pairs", far), pooled("E2_violation_share", "E2_pairs", near)
        r["E2"] = r["E2_far"] <= 0.01 and r["E2_far"] <= r["E2_near"] + 0.005
        r["E2prime_far"], r["E2prime_near"] = pooled("E2prime_violation_share", "E2prime_pairs", far), pooled("E2prime_violation_share", "E2prime_pairs", near)
        r["E2prime"] = r["E2prime_far"] <= 0.01 and r["E2prime_far"] <= r["E2prime_near"] + 0.005
        far_p99, near_p99 = max(bins[b]["age_s_p99"] for b in far), max(bins[b]["age_s_p99"] for b in near)
        fg = e["far_gt_2km"]
        r["E3_far_age_p99"], r["E3_near_age_p99_max_bin"] = far_p99, near_p99
        r["E3_far_recordings"], r["E3_top_recording_share"] = fg["recordings"], fg["top_recording_share"]
        r["E3"] = bool(far_p99 <= 2 * near_p99 and fg["recordings"] >= 3 and (fg["top_recording_share"] or 1) <= 0.5)
        lb = geo["E4_link_budget"][env]
        r["E4_margin_db"], r["E4"] = lb["margin_to_minus95_dbm_db"], lb["margin_to_minus95_dbm_db"] >= 0
        r["explained_pre_registered"] = bool(r["E1"] and r["E2"] and r["E3"] and r["E4"])
        r["explained_amended_E2prime"] = bool(r["E1"] and r["E2prime"] and r["E3"] and r["E4"])
        res[env] = r
    return res


def mean_over(inj_env, cfg, key, codes=SEEN, min_scored=50):
    vals, used = [], []
    for c in codes:
        t = inj_env["types"].get(c)
        if not t or "physics" not in t or t["physics"]["n_scored"] < min_scored:
            continue
        v = t[cfg][key]
        if v is not None:
            vals.append(v)
            used.append(c)
    return (float(np.mean(vals)) if vals else None), used


def main():
    geo, clean = load("s3b_geometry.json"), load("s3b_clean.json")
    inj = {e: load(f"s3b_inject_{e}.json") for e in ENVS}
    ver = load("s6_veremi.json")["groups"]["all but L4 (= L1+L2+L3)"]
    tam = load("s6_tampa.json")["groups"]["all but L4 (= L1+L2+L3)"]
    g = gate(geo)
    acc = {"gate": g, "F1": {}, "F2": {}, "R2": {}, "R3": {}, "I1": {}}
    md = ["# S3b tables (generated by tools/WP5_S3b_tables.py from the JSON files; test split scored once)", ""]
    # ---- geometry gate -------------------------------------------------------------------------------------------------
    md += ["## 1. Geometry gate for the km-scale distances (train + validation recordings)", "", "| environment | E1 frame (ratio far) | E2 as pre-registered (far / near) | E2prime generation-time dt, post-hoc (far / near) | E3 relay (far age p99 vs 2 x near; recordings; top share) | E4 link margin | verdict pre-registered | verdict with E2prime |",
           "|---|---|---|---|---|---|---|---|"]
    for env, r in g.items():
        md.append(f"| {env} | {'PASS' if r['E1'] else 'FAIL'} ({r['E1_ratio_range_far'][0]:.3f}-{r['E1_ratio_range_far'][1]:.3f}) | {'PASS' if r['E2'] else 'FAIL'} ({pc(r['E2_far'], 2)} / {pc(r['E2_near'], 2)}) | "
                  f"{'PASS' if r['E2prime'] else 'FAIL'} ({pc(r['E2prime_far'], 2)} / {pc(r['E2prime_near'], 2)}) | {'PASS' if r['E3'] else 'FAIL'} ({r['E3_far_age_p99']:.2f} s vs {2 * r['E3_near_age_p99_max_bin']:.2f} s; {r['E3_far_recordings']} rec; {pc(r['E3_top_recording_share'], 0)}) | "
                  f"{'PASS' if r['E4'] else 'FAIL'} ({r['E4_margin_db']:+.1f} dB) | {'EXPLAINED' if r['explained_pre_registered'] else 'NOT explained'} | {'EXPLAINED' if r['explained_amended_E2prime'] else 'NOT explained'} |")
    md.append("")
    # ---- clean false alarms --------------------------------------------------------------------------------------------
    md += ["## 2. Real genuine traffic, test split (key numbers; full tables in s3b_clean.md)", "",
           "| environment | variant | FA per message [CI] | alarms per receiver-hour | alarm events per hour | genuine senders k=3 | genuine senders k val (k) |", "|---|---|---|---|---|---|---|"]
    for env in ENVS:
        e = clean["envs"][env]
        for nm, lab in (("A_physics", "A: frozen VeReMi calibration"), ("physics", "B: re-calibrated on V2AIX validation"), ("physics+rx", "B + range OR appearance"), ("physics+fresh", "B + freshness")):
            f = e["false_alarms"][nm]
            m, s = f["per_message"], f["sender"]
            kv = "n/a" if nm == "A_physics" else f"{pc(s['at_k_val'], 1)} (k={s['k_val']})"
            md.append(f"| {env} | {lab} | {pc(m['p'], 2)} [{pc(m['ci'][0], 2)}, {pc(m['ci'][1], 2)}] | {f['alarms_per_hour']:.0f} | {f['events_per_hour']:.0f} | {pc(s['k3'], 1)} ({s['senders_k3']}/{s['n_senders']}) | {kv} |")
        acc["F1"][env] = {"fa_msg_B": e["false_alarms"]["physics"]["per_message"]["p"], "met_msg": e["false_alarms"]["physics"]["per_message"]["p"] <= 0.015,
                          "genuine_senders_kval": e["false_alarms"]["physics"]["sender"]["at_k_val"], "met_sender": e["false_alarms"]["physics"]["sender"]["at_k_val"] <= 0.03,
                          "genuine_senders_k3": e["false_alarms"]["physics"]["sender"]["k3"], "alarms_per_hour": e["false_alarms"]["physics"]["alarms_per_hour"],
                          "receiver_hours": e["receiver_hours"]}
        acc["F2"][env] = {"fa_msg_A": e["false_alarms"]["A_physics"]["per_message"]["p"], "gt_2pct": e["false_alarms"]["A_physics"]["per_message"]["p"] > 0.02}
    md.append("")
    # ---- per type ------------------------------------------------------------------------------------------------------
    for env in ENVS:
        ie = inj[env]
        md += [f"## 3. Injected attacks on real V2AIX CAMs: {env} (test recordings; base {ie['base_messages']} messages, {ie['base_senders']} senders; B thresholds at 1% of validation)", "",
               "| type | name | injected msgs | attackers | scored share | physics scored [CI] | physics all rows | sender k=3 | sender k val | L1 | L2 | L3 | fresh | range | appear (tracks) | physics+rx | VeReMi scored | Tampa scored |",
               "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for c in ORDER:
            t = ie["types"].get(c)
            if not t or "physics" not in t:
                md.append(f"| {c} | {NAMES[c]} | 0 | - | - | - | - | - | - | - | - | - | - | - | - | - | - | - |")
                continue
            p = t["physics"]
            vk = ver["classes"][int(c) - 1] if c.isdigit() and int(c) <= 19 else None
            vs = ver["msg_scored"][vk]["p"] if vk else None
            tm = tam["msg_scored"][vk]["p"] if vk and vk in tam["msg_scored"] and tam["msg_scored"][vk]["n"] > 0 else None
            sc_txt = "-" if p["msg_scored"] is None else f"{pc(p['msg_scored'])} [{pc(p['msg_scored_ci'][0])}, {pc(p['msg_scored_ci'][1])}] (n={p['n_scored']})"
            md.append(f"| {c} | {NAMES[c]} | {t['_meta']['n_injected']} | {p['n_attackers']} | {pc(t['_meta']['scored_share'], 0)} | {sc_txt} | {pc(p['msg_all'])} | {pc(p['sender_k3'])} | {pc(p['sender_kval'])} (k={p['k_val']}) | "
                      f"{pc(t['L1']['msg_all'])} | {pc(t['L2']['msg_all'])} | {pc(t['L3']['msg_all'])} | {pc(t['fresh']['msg_all'])} | {pc(t['range']['msg_all'])} | {pc(t['appear']['track_any'])} | {pc(t['physics+rx']['msg_all'])} | {pc(vs)} | {pc(tm)} |")
        m_phys, used = mean_over(ie, "physics", "msg_scored")
        m_rx, _ = mean_over(ie, "physics+rx", "msg_scored")
        m_all, _ = mean_over(ie, "physics", "msg_all", codes=used, min_scored=0)
        m_s3, _ = mean_over(ie, "physics", "sender_k3", codes=used, min_scored=0)
        m_sk, _ = mean_over(ie, "physics", "sender_kval", codes=used, min_scored=0)
        vm = np.mean([ver["msg_scored"][ver["classes"][int(c) - 1]]["p"] for c in used if ver["msg_scored"][ver["classes"][int(c) - 1]]["p"] is not None])
        md += ["", f"Mean over the types with >= 50 scored rows ({', '.join(used)}): physics scored-row detection {pc(m_phys)}; physics + receiver layers {pc(m_rx)}; all rows {pc(m_all)}; sender k=3 {pc(m_s3)}; sender k val {pc(m_sk)}; "
               f"VeReMi physics-only on the same types {pc(float(vm))} (VeReMi seen-class mean {pc(ver['mean_msg_scored']['seen']['p'])}), Tampa seen-class mean {pc(tam['mean_msg_scored']['seen']['p'])}.", ""]
        acc["I1"][env] = {"types_used": used, "mean_scored_physics": m_phys, "mean_scored_physics_rx": m_rx, "mean_all_rows": m_all, "mean_sender_k3": m_s3, "mean_sender_kval": m_sk,
                          "veremi_same_types": float(vm), "met": m_phys is not None and m_phys >= 0.60}
        # ---- receiver layers ----
        t21, t20, t2, tb = ie["types"].get("21"), ie["types"].get("20"), ie["types"].get("2"), ie["types"].get("12b")
        e = clean["envs"][env]
        rf = e["false_alarms"]["range"]
        ap = e["false_alarms"]["appear"]
        acc["R2"][env] = {"gate_pre_registered": g[env]["explained_pre_registered"], "gate_amended": g[env]["explained_amended_E2prime"],
                          "fa_pooled_among_rx_messages": rf["per_message_with_rx"], "fa_met": rf["per_message_with_rx"] is not None and rf["per_message_with_rx"] <= 0.015,
                          "far_offset_detection_msg": t21["range"]["msg_all"] if t21 and "range" in t21 else None, "far_offset_detection_sender": t21["range"]["sender_k3"] if t21 and "range" in t21 else None,
                          "range_threshold_km": e["range_pooled_val_raw_quantiles_km"]["0.99"]}
        acc["R3"][env] = {"fa_per_evaluable_first": ap["per_evaluable_first"], "evaluable_first_test": ap["evaluable_first_messages"], "fa_met": ap["per_evaluable_first"] is not None and ap["per_evaluable_first"] <= 0.02,
                          "ghost_tracks_detected": t20["appear"]["track_any"] if t20 and "appear" in t20 else None, "ghost_tracks": t20["appear"]["n_injected_tracks"] if t20 and "appear" in t20 else None,
                          "physical_300m_fa": ap["physical_300m_alarms_on_evaluable_first"], "fresh_on_delay_burst": tb["fresh"]["msg_all"] if tb and "fresh" in tb else None}
    acc["R3"]["ghost_met_in_one_env"] = any((acc["R3"][e]["ghost_tracks_detected"] or 0) >= 0.5 for e in ENVS)
    # ---- ablation ---------------------------------------------------------------------------------------------------------
    md += ["## 4. Ablation: mean scored-row detection over the types used (B thresholds)", "", "| configuration | Mobile | Stationary |", "|---|---|---|"]
    for cfg in ("L1", "L2", "L3", "physics", "fresh", "range", "range_loc", "appear", "rx", "physics+range", "physics+fresh", "physics+rx"):
        row = []
        for env in ENVS:
            m, _ = mean_over(inj[env], cfg, "msg_scored")
            row.append(pc(m))
        md.append(f"| {cfg} | {row[0]} | {row[1]} |")
    md += ["", "Detection of the receiver-aware types (all injected rows; appearance = share of ghost TRACKS whose first message alarms):", "",
           "| env | type | range | range per location | appear (tracks) | physics | physics+rx | fresh | physics+fresh |", "|---|---|---|---|---|---|---|---|---|"]
    for env in ENVS:
        for c in ("20", "21", "12b", "2", "3", "4"):
            t = inj[env]["types"].get(c)
            if t and "physics" in t:
                md.append(f"| {env} | {c} {NAMES[c]} | {pc(t['range']['msg_all'])} | {pc(t['range_loc']['msg_all'])} | {pc(t['appear']['track_any'])} ({t['appear']['n_injected_tracks']} tracks) | {pc(t['physics']['msg_all'])} | {pc(t['physics+rx']['msg_all'])} | {pc(t['fresh']['msg_all'])} | {pc(t['physics+fresh']['msg_all'])} |")
    (OUT / "s3b_tables.md").write_text("\n".join(md))
    (OUT / "s3b_acceptance.json").write_text(json.dumps(acc, indent=1, default=float))
    print("\n".join(md[:60]))
    print(json.dumps({k: acc[k] for k in ("F1", "F2", "R2", "R3", "I1")}, indent=1, default=float))


if __name__ == "__main__":
    main()
