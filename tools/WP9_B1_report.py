"""WP9 B1: tables from results/WP9/B1_*_test.json, *_selection.json, *_control2.json and the saved test scores.

Writes results/WP9/B1_tables.md and results/WP9/B1_regime.json (regime diagnostic: score separation restricted to
attack-bearing segments, i.e. normal windows that share the capture / block regime with the attack windows).
No new scoring: only reads saved scores. The regime diagnostic is descriptive (nothing is selected with it).
"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import WP9_B1_lib as L

OUT = L.OUT


def f(x, d=3):
    return "n/a" if x is None else f"{x:.{d}f}"


def ci(v, key, d=3):
    c = v.get("ci95", {}).get(key)
    return f"{f(v[key], d)} [{f(c[0], d)}, {f(c[1], d)}]" if c and v.get(key) is not None else f(v.get(key), d)


def regime_stats(tag, model, sub, thr):
    z = np.load(L.SCORES / f"{tag}_test.npz", allow_pickle=True)
    pre = f"{model}__{sub}"
    # score arrays were stored as a dict of arrays under keys 'y','s',... inside a per-key dict: np.savez stored dicts as objects
    d = z[pre].item()
    y, s, seg = d["y"], d["s"].astype(np.float64), d["seg"]
    att_seg = {x for x in np.unique(seg[y != 0])}
    in_att = np.array([x in att_seg for x in seg])
    out = {"n_att_segments": len(att_seg), "n_normal_in_attack_segments": int(((y == 0) & in_att).sum()),
           "n_normal_in_attack_free_segments": int(((y == 0) & ~in_att).sum())}
    m = in_att & (y >= 0)
    if ((y == 0) & in_att).sum() and (y[m] != 0).any():
        out["auc_attack_vs_normal_same_segments"] = L.auc_binary((y[m] != 0).astype(int), s[m])
        out["fpr_normal_in_attack_segments"] = float(np.mean(s[(y == 0) & in_att] >= thr))
    if ((y == 0) & ~in_att).sum():
        out["fpr_normal_in_attack_free_segments"] = float(np.mean(s[(y == 0) & ~in_att] >= thr))
    if (y != 0).any() and ((y == 0) & ~in_att).any():
        mm = ~in_att & (y == 0) | (y != 0)
        out["auc_attack_vs_normal_attack_free_segments"] = L.auc_binary((y[mm] != 0).astype(int), s[mm])
    out["recall_any"] = float(np.mean(s[y != 0] >= thr)) if (y != 0).any() else None
    return out


def main():
    lines = ["# WP9 B1 tables (generated by tools/WP9_B1_report.py from results/WP9/B1_*_test.json; do not edit by hand)\n"]
    reg = {}
    for tag in ["carhacking", "road", "d11_set_01", "d11_set_02", "d11_set_03", "d11_set_04"]:
        tp = OUT / f"B1_{tag}_test.json"
        if not tp.exists():
            continue
        t = json.load(open(tp))
        sel = json.load(open(OUT / f"B1_{tag}_selection.json"))
        c2p = OUT / f"B1_{tag}_control2.json"
        c2 = json.load(open(c2p))["units"] if c2p.exists() else {}
        lines.append(f"\n## {tag}: model {sel['chosen']} (vehicle-agnostic secondary {sel['chosen_vehicle_agnostic']})\n")
        lines.append("| model | subset | row | windows | groups | macro-F1 (95% CI) | attack F1 binary (CI) | FPR (CI) | recall any (CI) | AUC (CI) |")
        lines.append("|---|---|---|---|---|---|---|---|---|---|")
        for mname, mm in t["models"].items():
            for sub, v in mm["subsets"].items():
                lines.append(f"| {mname} | {sub} | {v['row']} | {v['n_windows']} | {v.get('n_groups')} | {ci(v, 'macro_f1') if v['row'] == 'seen attack types' else 'n/a (unseen row)'} | "
                             f"{ci(v, 'f1_attack_binary')} | {ci(v, 'fpr')} | {ci(v, 'recall_any')} | {ci(v, 'auc')} |")
                try:
                    reg[f"{tag}|{mname}|{sub}"] = regime_stats(tag, mname, sub, mm["thr_from_validation"])
                except Exception as e:  # noqa
                    reg[f"{tag}|{mname}|{sub}"] = {"error": str(e)}
        lines.append("\nPer-class recall (class-specific; row 'seen attack types'), 95% CI:\n")
        classes = t["classes"]
        for mname, mm in t["models"].items():
            for sub, v in mm["subsets"].items():
                if v["row"] != "seen attack types":
                    continue
                cells = []
                for k, r in v["per_class_recall"].items():
                    cc = (v.get("ci95_per_class_recall") or {}).get(k)
                    cells.append(f"{classes[int(k)]}: {f(r, 2)}" + (f" [{f(cc[0], 2)},{f(cc[1], 2)}]" if cc else "") + f" (n={v['per_class_n'][k]})")
                lines.append(f"- {mname} / {sub}: " + "; ".join(cells))
        if "event_level" in next(iter(t["models"].values())):
            mm = next(iter(t["models"].values()))
            lines.append("\nROAD event level (test captures; detected = alarm in a window containing an injected frame):\n")
            lines.append("| capture | class | attack windows | detected | first alarm window |")
            lines.append("|---|---|---|---|---|")
            for e in mm["event_level"]:
                lines.append(f"| {e['capture']} | {e['class']} | {e['attack_windows']} | {e['detected']} | {e['first_alarm_window']} |")
            lines.append(f"\nFPR context: {mm['fpr_context']}\n\nAmbient FPR by capture: {mm['ambient_fpr_by_capture']}\n")
        if c2:
            lines.append("\nControls: global shuffled-label (fit) and within-capture label permutation (control2), validation AUC:\n")
            for u, cc in sel["controls"].items():
                a = cc.get("shuffled_auc_window") if cc["unit"] == "window" else cc.get("shuffled_auc_frame")
                lines.append(f"- {u} ({cc['unit']}): global shuffle AUC {f(a)} pass={cc['pass']}; within-capture AUC "
                             f"{f(c2.get(u, {}).get('within_capture_shuffled_auc'))}")
        lines.append("\nRegime diagnostic (test scores at the frozen threshold): same-segment AUC and FPR by segment type:\n")
        for key, r in reg.items():
            if key.startswith(tag + "|"):
                lines.append(f"- {key.split('|', 1)[1]}: " + ", ".join(f"{a}={f(b) if isinstance(b, float) else b}" for a, b in r.items()))
    fr = json.load(open(OUT / "B1_frames.json")) if (OUT / "B1_frames.json").exists() else {}
    if fr:
        lines.append("\n## Frame-expanded metrics (every frame inherits its window decision; CI = segment bootstrap)\n")
        lines.append("| tag | model | subset | frames | attack frames | precision | recall | F1 (CI) | FPR (CI) | accuracy |")
        lines.append("|---|---|---|---|---|---|---|---|---|---|")
        for k, r in fr.items():
            tg, mn, sb = k.split("|")
            c = r["ci95"]
            lines.append(f"| {tg} | {mn} | {sb} | {r['frames']} | {r['attack_frames']} | {f(r['precision'])} | {f(r['recall'])} | "
                         f"{f(r['f1'])} [{f(c['f1'][0])}, {f(c['f1'][1])}] | {f(r['fpr'])} [{f(c['fpr'][0])}, {f(c['fpr'][1])}] | {f(r['accuracy'])} |")
    # D11 summary over the four sets
    lines.append("\n## D11 summary over sets 01..04 (primary = chosen model of each set; agnostic = vehicle-agnostic secondary)\n")
    lines.append("| test subset | row | model kind | window attack-F1 mean (sd) | window FPR mean (sd) | recall any mean (sd) | AUC mean (sd) | frame-expanded F1 mean (sd) | frame FPR mean (sd) |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for sub in ["test_01", "test_02", "test_03", "test_04"]:
        for kind in ("primary", "agnostic"):
            vals = {k: [] for k in ("f1", "fpr", "rec", "auc", "ff1", "ffpr")}
            for sn in ("set_01", "set_02", "set_03", "set_04"):
                tg = f"d11_{sn}"
                tp = OUT / f"B1_{tg}_test.json"
                if not tp.exists():
                    continue
                sel = json.load(open(OUT / f"B1_{tg}_selection.json"))
                t = json.load(open(tp))
                mn = sel["chosen"] if kind == "primary" else sel["chosen_vehicle_agnostic"]
                v = t["models"][mn]["subsets"][sub]
                vals["f1"].append(v["f1_attack_binary"]); vals["fpr"].append(v["fpr"]); vals["rec"].append(v["recall_any"]); vals["auc"].append(v["auc"])
                r = fr.get(f"{tg}|{mn}|{sub}")
                if r:
                    vals["ff1"].append(r["f1"]); vals["ffpr"].append(r["fpr"])
            ms = lambda a: f"{np.mean(a):.3f} ({np.std(a):.3f})" if a else "n/a"
            row = "seen attack types" if sub in ("test_01", "test_02") else "UNSEEN attack families"
            lines.append(f"| {sub} | {row} | {kind} | {ms(vals['f1'])} | {ms(vals['fpr'])} | {ms(vals['rec'])} | {ms(vals['auc'])} | {ms(vals['ff1'])} | {ms(vals['ffpr'])} |")
    (OUT / "B1_tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    L.jd(reg, OUT / "B1_regime.json")
    print("written")


if __name__ == "__main__":
    main()
