"""WP6 S5b: markdown tables from results/WP6/s5b_dev.json, s5b_test.json, s5b_acceptance.json, side by side with M2 (s5_test.json, s5_acceptance.json)
-> results/WP6/s5b_tables.md (numbers copied, not typed). Run: python -u -W ignore tools/WP6_S5b_tables.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common.config import results_dir  # noqa: E402

OUT = results_dir("WP6")
P = lambda x: "-" if x is None else f"{100 * x:.1f}"
F = lambda x, d=2: "-" if x is None else f"{x:.{d}f}"
CI = lambda c, k=100, d=1: "-" if not c else f"[{k * c[0]:.{d}f}, {k * c[1]:.{d}f}]"
LV = ("WARN", "DEGRADE", "SAFE_STOP")


def main():
    dev = json.loads((OUT / "s5b_dev.json").read_text())
    t = json.loads((OUT / "s5b_test.json").read_text())
    acc = json.loads((OUT / "s5b_acceptance.json").read_text())
    m2 = json.loads((OUT / "s5_test.json").read_text())
    L = ["# WP6 S5b tables (M2 addendum, system v2; generated by tools/WP6_S5b_tables.py)", "",
         "Test = ONE run on NEW composites (seed [42, 66, 5, ord(family)]), 4th scoring of fusion test data. M2 columns = results/WP6/s5_test.json (S4 composites, LiDAR interim).", ""]
    L += ["## 1 Acceptance (rule in notes/WP6_crossdomain.md 'S5b start')", "", "| Rule | S5b | M2 | Bound | Verdict |", "|---|---|---|---|---|"]
    for k, v in acc.items():
        val = {a: b for a, b in v.items() if a not in ("rule", "met", "verdict") and not a.startswith("M2") and not (a == "value" and isinstance(b, dict))}
        mv = {a: b for a, b in v.items() if a.startswith("M2")}
        L.append(f"| {k} | {json.dumps(val, default=str)[:300]} | {json.dumps(mv)[:200]} | {v['rule']} | {('MET' if v['met'] else 'NOT MET') if 'met' in v else v.get('verdict')} |")
    L += ["", "## 2 Validation (nested held-out over the 3 S5 group folds)", "", "### 2a LiDAR entry x calibration pool x budget allocation (cal=trainval = round 2, post-hoc, labelled)", "",
          "| Config | FA tick K | FA tick C | det K | det C | pooled det | qualifies (FA <= 2.5%) |", "|---|---|---|---|---|---|---|"]
    for k, r in dev["calibration_grid"].items():
        L.append(f"| {k} | {P(r['K']['fa_tick'])} | {P(r['C']['fa_tick'])} | {P(r['K']['mean_detection_selection'])} | {P(r['C']['mean_detection_selection'])} | {P(r['pooled_detection'])} | {'yes' if r['qualifies'] else 'no'} |")
    w = dev["calibration_grid"].get("lidar=combined|cal=trainval|wsplit", {}).get("K", {})
    L += ["", f"wsplit weights K (1 / clip(rho)): `{json.dumps({a: round(b, 2) for a, b in (w.get('weights') or {}).items()})}`, rho: `{json.dumps({a: round(b, 2) for a, b in (w.get('rho') or {}).items()})}`",
          "", f"Chosen: `{json.dumps(dev['calibration_choice'])}`", "", "### 2b Correlator (chosen calibration)", "",
          "| Correlator | events/h K | events/h C | event det K | event det C | pooled | SAFE_STOP/h K | SAFE_STOP/h C | qualifies (<= 10/h) |", "|---|---|---|---|---|---|---|---|---|"]
    for k, r in dev["correlator_grid"].items():
        L.append(f"| {k} | {F(r['K']['events_per_hour'])} | {F(r['C']['events_per_hour'])} | {P(r['K']['mean_event_detection_selection'])} | {P(r['C']['mean_event_detection_selection'])} | "
                 f"{P(r['pooled_event_detection'])} | {F(r['K']['clean_response_per_hour']['SAFE_STOP'])} | {F(r['C']['clean_response_per_hour']['SAFE_STOP'])} | {'yes' if r['qualifies'] else 'no'} |")
    L += ["", f"Chosen: `{json.dumps(dev['correlator_choice'])}`", "", "### 2c Event blame (detected selection-family events; plurality = M2 reference)", "",
          "| Rule | K correct | K wrong | K undecided | C correct | C wrong | C undecided | qualifies (wrong <= 10%) |", "|---|---|---|---|---|---|---|---|"]
    for k, r in dev["blame_grid"].items():
        L.append(f"| {k} | {P(r['K']['correct'])} | {P(r['K']['wrong'])} | {P(r['K']['undecided'])} | {P(r['C']['correct'])} | {P(r['C']['wrong'])} | {P(r['C']['undecided'])} | {'yes' if r['qualifies'] else 'no'} |")
    L += ["", f"Chosen: `{json.dumps(dev['blame_choice'])}`", "", "Validation held-out of the frozen system v2: " + "; ".join(
        f"{fam} FA tick {P(v['fa_tick'])}%, {F(v['events_per_hour'])} events/h, response/h {json.dumps({a: round(b, 2) for a, b in v['clean_response_per_hour'].items()})}"
        for fam, v in dev["val_heldout_chosen"].items()), ""]
    L += ["## 3 Test headline, side by side with M2", "", "| | K S5b | K M2 | C S5b | C M2 |", "|---|---|---|---|---|"]
    S, M = t["system"], m2["system"]
    rows = [("raw tick FA % [CI]", lambda x: f"{P(x['fa_tick'])} {CI(x['ci_single_event']['fa_tick'])}"),
            ("alert events / clean hour [CI]", lambda x: f"{F(x['events_per_hour'])} {CI(x['ci_single_event']['events_per_hour'], 1, 1)}"),
            ("alert events / clean hour, correlator off", lambda x: F(x["correlator_off"]["events_per_hour"])),
            ("clean hours", lambda x: F(x["clean_hours"])),
            ("WARN / DEGRADE / SAFE_STOP per clean hour", lambda x: " / ".join(F(x["clean_response_per_hour"][k]) for k in LV)),
            ("share of clean composites with an alert event", lambda x: P(x.get("clean_composites_with_event"))),
            ("mean EVENT detection, single-domain families [CI]", lambda x: f"{P(x['mean_event_detection_single'])} {CI(x['ci_single_event']['mean'])}"),
            ("mean TICK detection, single-domain [CI]", lambda x: f"{P(x['mean_tick_detection_single'])} {CI(x['ci_single_tick']['mean'])}"),
            ("held-out (S4 zero-day) event detection [CI]", lambda x: f"{P(x['mean_event_detection_heldout'])} {CI(x['ci_heldout_event']['mean'] if x['ci_heldout_event'] else None)}"),
            ("seen (non-held-out) event detection", lambda x: P(x["mean_event_detection_seen"])),
            ("blame correct / wrong / undecided (detected single-domain)", lambda x: " / ".join(P(x["blame_single_pooled"][k]) for k in ("correct", "wrong", "undecided"))),
            ("blame on coordinated scenarios correct / wrong / undecided", lambda x: " / ".join(P(x["blame_coordinated_pooled"][k]) for k in ("correct", "wrong", "undecided"))),
            ("tick recall (share of attack ticks flagged)", lambda x: P(x["tick_recall_attack_ticks"])),
            ("events explained", lambda x: f"{x['explanations']['with_explanation']} / {x['explanations']['events']}")]
    for name, f in rows:
        L.append(f"| {name} | {f(S['K'])} | {f(M['K']) if _ok(f, M['K']) else '-'} | {f(S['C'])} | {f(M['C']) if _ok(f, M['C']) else '-'} |")
    sh = S["K"]["m2_shared"]
    L += ["", f"K mean event detection on the {len(sh['families'])} families shared with M2 (LiDAR excluded): S5b {P(sh['mean_event_detection'])}%, M2 {P(sh['m2_mean_event_detection'])}%.", ""]
    L += ["## 4 Event detection by attacked domain (single-domain families)", "", "| family | domain | S5b event | M2 event | S5b tick | M2 tick |", "|---|---|---|---|---|---|"]
    for fam in ("K", "C"):
        for d, v in S[fam]["event_detection_by_attacked_domain"].items():
            L.append(f"| {fam} | {d} | {P(v)} | {P(M[fam]['event_detection_by_attacked_domain'].get(d))} | {P(S[fam]['tick_detection_by_attacked_domain'][d])} | {P(M[fam]['tick_detection_by_attacked_domain'].get(d))} |")
    for fam in ("K", "C"):
        tab, mt = S[fam]["families"], M[fam]["families"]
        L += ["", f"## 5{fam} Per family ({fam}): event / tick detection, median delay (s), blame, max response of detected composites; M2 event detection where the family existed", "",
              "| family | domain | category | event det | M2 event det | tick det | delay event | delay tick | blame c / w / u | WARN / DEGRADE / SAFE_STOP |", "|---|---|---|---|---|---|---|---|---|---|"]
        for f in sorted(tab, key=lambda z: (tab[z]["attacked"], z)):
            x = tab[f]
            rm = x.get("response_max") or {}
            L.append(f"| {f} | {x['attacked']} | {x['category']} | {P(x['detection'])} | {P(mt[f]['detection']) if f in mt else '-'} | {P(x['tick_detection'])} | {F(x['median_delay_s'], 0)} | "
                     f"{F(x['median_tick_delay_s'], 0)} | {P(x.get('blame_correct'))} / {P(x.get('blame_wrong'))} / {P(x.get('blame_undecided'))} | {' / '.join(P(rm.get(k)) for k in LV)} |")
    L += ["", "## 6 Ablation (test; each domain removed, threshold from validation), side by side with M2", "", "| family | configuration | FA tick | events/h | event det single | M2 event det single | held-out |", "|---|---|---|---|---|---|---|"]
    for fam in ("K", "C"):
        x = S[fam]
        L.append(f"| {fam} | full | {P(x['fa_tick'])} | {F(x['events_per_hour'])} | {P(x['mean_event_detection_single'])} | {P(M[fam]['mean_event_detection_single'])} | {P(x['mean_event_detection_heldout'])} |")
        for k, a in x["ablation"].items():
            mb = M[fam]["ablation"].get(k, {})
            L.append(f"| {fam} | {k} | {P(a['fa_tick'])} | {F(a['events_per_hour'])} | {P(a['mean_event_detection_single'])} | {P(mb.get('mean_event_detection_single'))} | {P(a['mean_event_detection_heldout'])} |")
        c0 = x["correlator_off"]
        L.append(f"| {fam} | correlator off | {P(c0['fa_tick'])} | {F(c0['events_per_hour'])} | {P(c0['mean_detection_single'])} | {P(M[fam]['correlator_off']['mean_detection_single'])} | {P(c0['mean_detection_heldout'])} |")
    L += ["", "## 7 Rule ablation on the same alarms (what the M2 rules would give)", "", "| family | variant | events/h | WARN / DEGRADE / SAFE_STOP per clean hour | blame c / w / u | event det single |", "|---|---|---|---|---|---|"]
    for fam in ("K", "C"):
        x = S[fam]
        L.append(f"| {fam} | S5b (decided majority, SAFE_STOP needs 2 domains) | {F(x['events_per_hour'])} | {' / '.join(F(x['clean_response_per_hour'][k]) for k in LV)} | "
                 f"{' / '.join(P(x['blame_single_pooled'][k]) for k in ('correct', 'wrong', 'undecided'))} | {P(x['mean_event_detection_single'])} |")
        for k in ("m2_blame_rule_plurality", "m2_safe_stop_rule_one_domain", "m2_rules_both", "correlator_with_corroboration"):
            v = x[k]
            L.append(f"| {fam} | {k} | {F(v['events_per_hour'])} | {' / '.join(F(v['clean_response_per_hour'][q]) for q in LV)} | "
                     f"{' / '.join(P(v['blame_single_pooled'][q]) for q in ('correct', 'wrong', 'undecided'))} | {P(v['mean_event_detection_single'])} |")
    L += ["", "## 8 LiDAR families (K): frozen LiDAR domain at system level (per-scan attacks every 3rd scan; ep_ / epW_ = 3 s persistent episodes; cmp_ = comparison rows)", "",
          "| family | event det | tick det | delay event (s) | blame c / w / u | WARN / DEGRADE / SAFE_STOP |", "|---|---|---|---|---|---|"]
    for f, x in S["K"]["lidar_rows"].items():
        rm = x.get("response_max") or {}
        L.append(f"| {f} | {P(x['detection'])} | {P(x['tick_detection'])} | {F(x['median_delay_s'], 0)} | {P(x['blame_correct'])} / {P(x['blame_wrong'])} / {P(x['blame_undecided'])} | {' / '.join(P(rm.get(k)) for k in LV)} |")
    L.append(f"\nChance level: {P(S['K']['clean_composites_with_event'])}% of the clean K composites (median 16 s) contain an alert event.")
    cu = t["coupling"]
    L += ["", "## 9 Coupling test (GPS attack bends the OXTS ego pose of L2c / L2d; worst case INS follows GNSS 1:1)", "", "### 9a Scan level, all 350 test GPS attack runs, post-onset scans", "",
          "| family | runs | post-onset scans | median max offset (m) | median max step per scan (m) | LiDAR alarm true pose | coupled | L2c true | coupled | L2d true | coupled |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for f, x in cu["scan_level"].items():
        L.append(f"| {f} | {x['runs']} | {x['post_onset_scans']} | {F(x['median_max_offset_m'], 1)} | {F(x['median_max_step_m'], 3)} | {P(x['clean_alarm'])} | {P(x['coupled_alarm'])} | "
                 f"{P(x['clean_L2c'])} | {P(x['coupled_L2c'])} | {P(x['clean_L2d'])} | {P(x['coupled_L2d'])} |")
    L += ["", "### 9b System level (K test composites of the GPS families; control = same drive and times with the true pose)", "",
          "| family | variant | LiDAR own alarm, post-onset ticks | pre-onset | event det | tick det | blame c / w / u | blamed on lidar | WARN / DEGRADE / SAFE_STOP |", "|---|---|---|---|---|---|---|---|---|"]
    for f in cu["composites_coupled"]:
        for name, key in (("control", "composites_control_synced"), ("coupled", "composites_coupled")):
            x = cu[key][f]
            L.append(f"| {f} | {name} | {P(x['lidar_own_alarm_post_onset_ticks'])} | {P(x['lidar_own_alarm_pre_onset_ticks'])} | {P(x['event_detection'])} | {P(x['tick_detection'])} | "
                     f"{' / '.join(P(x['blame'][k]) for k in ('correct', 'wrong', 'undecided'))} | {P(x['blamed_lidar'])} | {' / '.join(P(x['response_max'][k]) for k in LV)} |")
    L += ["", f"Model: {cu['model']}.", ""]
    (OUT / "s5b_tables.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("written", OUT / "s5b_tables.md")


def _ok(f, x):
    try:
        f(x)
        return True
    except (KeyError, TypeError):
        return False


if __name__ == "__main__":
    main()
