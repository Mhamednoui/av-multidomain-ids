"""WP9 B3 step 6: tables from results/WP9/B3_test.json, B3_selection.json, B3_controls.json -> results/WP9/B3_tables.md (no hand-typed numbers)."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import WP9_B3_lib as L

R = L.OUT
test = json.loads((R / "B3_test.json").read_text())
sel = json.loads((R / "B3_selection.json").read_text())
ctl = json.loads((R / "B3_controls.json").read_text())


def f(o, key, d=3):
    p = o["point"].get(key)
    if p is None:
        return "-"
    ci = o["ci95"].get(key)
    s = f"{p:.{d}f}"
    return s + (f" [{ci[0]:.{d}f}, {ci[1]:.{d}f}]" if ci else "")


lines = []
A = lines.append
A("# B3 tables (generated by tools/WP9_B3_report.py)\n")
A(f"Chosen: {sel['chosen']['name']} (validation macro-F1 {sel['chosen_val']['macro_f1']:.4f}); tied with best: {', '.join(sel['tied_with_best'])}.")
A(f"Test blocks: {test['test_blocks']}; bootstrap over blocks, 1000 resamples.\n")
A("## Overall (message level, 20-class)\n")
A("| operating point | macro-F1 | macro-F1 without class 12 | binary F1 | precision | recall | FPR | AUC | mean alarm recall (19 classes) |")
A("|---|---|---|---|---|---|---|---|---|")
for nm, o in test["ops"].items():
    A(f"| {nm} | {f(o, 'macro_f1')} | {f(o, 'macro_f1_no12')} | {f(o, 'binary.f1')} | {f(o, 'binary.precision')} | {f(o, 'binary.recall')} | {f(o, 'fpr')} | {f(o, 'auc') if nm != 'G_argmax' else '-'} | {f(o, 'mean_alarm_recall')} |")
for nm, o in test["v3_reference"].items():
    A(f"| v3 L4 reference (binary), {nm} | - | - | {f(o, 'binary.f1')} | {f(o, 'binary.precision')} | {f(o, 'binary.recall')} | {f(o, 'fpr')} | {f(o, 'auc')} | {f(o, 'mean_alarm_recall')} |")
A("")
A("## Per-class recall at H (alarm recall = any alarm; class recall = correct class), with block-bootstrap CI\n")
A("| class | alarm recall H | class-correct recall H | alarm recall S | v3 L4 ref alarm recall H |")
A("|---|---|---|---|---|")
H, S, V = test["ops"]["H_budget1pct"], test["ops"]["S_valF1opt"], test["v3_reference"]["H_budget1pct"]
for k in range(1, 20):
    flag = " (artefact, flagged)" if k == 12 else ""
    A(f"| {k} {L.NAMES[k]}{flag} | {f(H, f'alarm_recall.{k}')} | {f(H, f'class_recall.{k}')} | {f(S, f'alarm_recall.{k}')} | {f(V, f'alarm_recall.{k}')} |")
A("")
A("## DoS family subset (classes 13, 14, 15, 18, 19) vs the B0 bar (F1 0.93-0.998, 70/30 within-dataset)\n")
A("F1 genuine-vs-type. natural = mixed-CSV prevalence; matched = genuine weighted so the sender mix is 70% genuine / 30% attack.\n")
A("| type | op | natural F1 | natural precision | matched F1 | matched precision | recall |")
A("|---|---|---|---|---|---|---|")
for k in ("13", "14", "15", "18", "19", "pooled"):
    nm = L.NAMES[int(k)] if k != "pooled" else "pooled DoS family"
    for op, o in (("H", H), ("S", S), ("v3 ref H", V)):
        A(f"| {nm} | {op} | {f(o, f'dos.{k}.natural.f1')} | {f(o, f'dos.{k}.natural.precision')} | {f(o, f'dos.{k}.matched.f1')} | {f(o, f'dos.{k}.matched.precision')} | {f(o, f'dos.{k}.natural.recall')} |")
A("")
A(f"## Sender level (k = {sel['sender_k']} alarms, chosen on validation: genuine-sender FA {sel['val_genuine_sender_fa_at_k']:.4f})\n")
A(f"Test genuine-sender FA {f(H, 'sender_fa')}; mean sender detection over 19 classes {f(H, 'sender_mean')}\n")
A("| class | sender detection |")
A("|---|---|")
for k in range(1, 20):
    A(f"| {k} {L.NAMES[k]} | {f(H, f'sender_detection.{k}')} |")
A("")
A("## Row kinds at H (point estimates)\n")
A("| row kind | rows | genuine rows | genuine alarm rate |")
A("|---|---|---|---|")
for k, v in test["row_kinds_H"].items():
    A(f"| {k} | {v['n']} | {v['genuine_n']} | {v['genuine_alarm_rate']} |")
A(f"\nClass 12 placeholder diagnostic: {json.dumps(test['class12_placeholder_H'])}\n")
A("## Candidates on validation (1% budget)\n")
A("| candidate | features | macro-F1 | mean alarm recall | AUC | binary F1 |")
A("|---|---|---|---|---|---|")
for n, v in sel["all_candidates"].items():
    A(f"| {n} | {len(L.SETS[n.split('_', 1)[1].rsplit('_d', 1)[0]]) if n.startswith('xgb') else '-'} | {v['macro_f1']:.4f} | {v['mean_alarm_recall']:.4f} | {v['auc']:.4f} | {v['binary_f1']:.4f} |")
A("")
A("## Controls (validation AUC attack vs genuine, pass band 0.42-0.58)\n")
A("| unit | val AUC | pass |")
A("|---|---|---|")
for n, v in ctl["units"].items():
    A(f"| {n} | {v['val_auc']:.3f} | {v['pass']} |")
A(f"\nTop-10 importance (total gain share): {', '.join(f'{k} {v:.3f}' for k, v in ctl['importance']['top10'])}; track-descriptor share {ctl['importance']['track_descriptor_share']:.3f}, raw x,y share {ctl['importance']['raw_xy_share']:.3f}; RED FLAG: {ctl['importance']['RED_FLAG']}.")
(R / "B3_tables.md").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
