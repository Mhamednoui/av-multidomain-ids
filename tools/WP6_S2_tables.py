"""WP6 S2: tables (results/WP6/s2_tables.md) and acceptance verdicts (results/WP6/s2_acceptance.json) generated from
s2_dev.json and s2_test.json (no hand-typed numbers). Run: python -u -W ignore tools/WP6_S2_tables.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common.config import results_dir  # noqa: E402

OUT = results_dir("WP6")
P = lambda x: "-" if x is None else f"{100 * x:.1f}"
F = lambda x, n=2: "-" if x is None else f"{x:.{n}f}"


def attack_table(s, title):
    L = [f"### {title}", f"k = {s['k']}, tau = {s['tau']:.6f}; clean FA rows {P(s['fa_rows'])}% of {s['clean_rows']} rows, clean runs with >= 1 alarm "
         f"{P(s['fa_runs'])}% of {s['clean_runs']}; clean rows with a decided blame: {s['clean_rows_with_decided_blame']}", "",
         "| attack | runs | detection % | median delay s | correct blame % | wrong blame % | undecided % | blamed domain counts |", "|---|---|---|---|---|---|---|---|"]
    for a, v in s["attacks"].items():
        L.append(f"| {a} | {v['runs']} | {P(v['detection'])} | {F(v['median_delay_s'], 1)} | {P(v.get('correct_blame'))} | {P(v.get('wrong_blame'))} | "
                 f"{P(v['undecided'])} | {v['blame_counts']} |")
    p = s["pooled_single"]
    L.append(f"\nMean single-domain detection {P(s['mean_detection_single'])}%; pooled over detected single-domain runs ({p['detected']}): correct blame "
             f"{P(p['correct_blame'])}%, wrong {P(p['wrong_blame'])}%, undecided {P(p['undecided'])}%.")
    if "ci95_groups" in s:
        c = s["ci95_groups"]
        L.append(f"95% bootstrap over drives / routes: mean detection [{P(c['mean_detection_single'][0])}, {P(c['mean_detection_single'][1])}]%, "
                 f"FA rows [{P(c['fa_rows'][0])}, {P(c['fa_rows'][1])}]%.")
    if "edge_fa_rows" in s:
        L.append("Edge-level clean FA rows (%): " + ", ".join(f"{k} {P(v)}" for k, v in s["edge_fa_rows"].items()) + ".")
    return L


def main():
    dev = json.loads((OUT / "s2_dev.json").read_text())
    te = json.loads((OUT / "s2_test.json").read_text())
    ch = te["choices"]
    L = ["# WP6 S2 tables (generated by tools/WP6_S2_tables.py from s2_dev.json, s2_test.json)", "",
         "## 1. Sigma honesty on clean VAL (AC1: |mean| <= 0.25, std <= 1.25, p99 |z| <= 4; std < 0.8 allowed)", "",
         "| data set / setup | edge | n | mean z | std z | p99 abs z | AC1 |", "|---|---|---|---|---|---|---|"]
    for e, h in dev["kitti_honesty_val"]["edges"].items():
        L.append(f"| KITTI (kitti_R) | {e} | {h['n']} | {F(h['mean'])} | {F(h['std'])} | {F(h['p99_abs'])} | {dev['kitti_honesty_val']['ac1'][e]} |")
    for mo in ("A", "B"):
        c = dev["comma_honesty_val"][mo]
        for e, h in c["edges"].items():
            L.append(f"| comma setup {mo} | {e} | {h['n']} | {F(h['mean'])} | {F(h['std'])} | {F(h['p99_abs'])} | {c['ac1'][e]} |")
    L += ["", f"comma setup cells (train routes, fallback): A {dev['comma_honesty_val']['A']['cells']}; B {dev['comma_honesty_val']['B']['cells']}.",
          f"Chosen: comma setup {ch['comma_setup_mode']} (rule: candidates passing AC1, std closest to 1; if none passes, fewest failing edges). Failing edges A: {dev['comma_honesty_val']['A']['n_fail']}, B: {dev['comma_honesty_val']['B']['n_fail']}. Route setups: "
          + "; ".join(f"{k[17:]} {v['part']} gyro {v['gyro_hz']:.0f} Hz gnss {v['gnss_hz']:.1f} Hz" for k, v in dev["comma_setups"].items()), "",
          "## 2. CUSUM reference k on VAL (choice = max mean detection over the selection attacks)", "",
          "| data set | k | selection mean detection % | val FA rows % | correct blame % | wrong % | undecided % |", "|---|---|---|---|---|---|---|"]
    for ds in ("kitti", "comma"):
        for k, s in dev[f"{ds}_k"].items():
            p = s["pooled_single"]
            L.append(f"| {ds} | {k} | {P(s['selection_mean_detection'])} | {P(s['fa_rows'])} | {P(p['correct_blame'])} | {P(p['wrong_blame'])} | {P(p['undecided'])} |")
    L += ["", f"Chosen: KITTI k = {ch['kitti_k']}, comma k = {ch['comma_k']}.", "", "## 3. TEST (run once)", ""]
    for ds in ("kitti", "comma"):
        L += attack_table(te[ds]["chosen"], f"{ds} chosen") + [""]
        L += attack_table(te[ds]["ablation_inst"], f"{ds} ablation: instantaneous |z| (k = inst)") + [""]
    v = te["kitti"]["chosen"]["vs_gps_domain"]
    L += ["## 4. KITTI TEST: cross-domain vs the frozen GPS domain (same runs)", "",
          f"GPS domain clean FA rows {P(v['gps_domain_fa_rows'])}%; cross {P(te['kitti']['chosen']['fa_rows'])}%; union {P(v['union_fa_rows'])}%.", "",
          "| attack | runs | GPS domain % | cross % | union % | GPS-domain misses | of which caught by cross |", "|---|---|---|---|---|---|---|"]
    for a, x in v["attacks"].items():
        L.append(f"| {a} | {x['runs']} | {P(x['gps_domain'])} | {P(x['cross'])} | {P(x['union'])} | {x['gps_misses']} | {x['cross_catches_gps_misses']} |")
    d = v["doppler_meaconing_pooled"]
    L.append(f"\nDoppler + meaconing pooled: GPS domain {P(d['gps_domain'])}%, union {P(d['union'])}%.")
    fr = te["comma"]["chosen"]["full_route_fa"]
    L += ["", "## 5. comma TEST: continuous CUSUM over whole routes (deployment mode, information)", "",
          f"FA rows {P(fr['fa_rows'])}% of {fr['rows']}; per route: " + ", ".join(f"{k[17:]} {P(x)}%" for k, x in fr["per_route"].items())]
    (OUT / "s2_tables.md").write_text("\n".join(L) + "\n")

    k, c = te["kitti"]["chosen"], te["comma"]["chosen"]
    ac = {
        "AC1_sigma_not_too_narrow_val": {"kitti": all(dev["kitti_honesty_val"]["ac1"].values()),
                                         "kitti_failing": [e for e, ok in dev["kitti_honesty_val"]["ac1"].items() if not ok],
                                         "comma": all(dev["comma_honesty_val"][ch["comma_setup_mode"]]["ac1"].values())},
        "AC2_test_fa_rows_le_1.5pct": {"kitti": k["fa_rows"], "comma": c["fa_rows"], "met": {"kitti": k["fa_rows"] <= 0.015, "comma": c["fa_rows"] <= 0.015}},
        "AC3_mean_detection_ge_70pct": {"kitti": k["mean_detection_single"], "comma": c["mean_detection_single"],
                                        "met": {"kitti": k["mean_detection_single"] >= 0.70, "comma": c["mean_detection_single"] >= 0.70},
                                        "caveat": "obtained at the FA of AC2, which is above budget"},
        "AC4_blame_correct_ge_80_wrong_le_5": {"kitti": k["pooled_single"], "comma": c["pooled_single"],
                                               "met": {ds: s["pooled_single"]["correct_blame"] >= 0.80 and s["pooled_single"]["wrong_blame"] <= 0.05 for ds, s in (("kitti", k), ("comma", c))}},
        "AC5_union_gain_ge_10pts_doppler_meaconing": {**v["doppler_meaconing_pooled"], "gain_pts": 100 * (d["union"] - d["gps_domain"]),
                                                      "union_fa_rows": v["union_fa_rows"], "met": d["union"] - d["gps_domain"] >= 0.10},
        "AC6_coordinated_prediction": {"kitti_gps_can": k["attacks"]["gps_can"]["blame_counts"], "comma_gnss_can": c["attacks"]["gnss_can"]["blame_counts"],
                                       "comma_can_bus": c["attacks"]["can_bus"]["blame_counts"],
                                       "note": "comma 'can' domain in gnss_can = the honest wheel message (same bus as the spoofed speed message)"},
    }
    (OUT / "s2_acceptance.json").write_text(json.dumps(ac, indent=1))
    print(json.dumps(ac, indent=1))


if __name__ == "__main__":
    main()
