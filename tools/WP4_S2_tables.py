"""WP4 S2: markdown tables from results/WP4/s2_d10.json, s2_d23.json, s2_diag_val.json -> results/WP4/s2_tables.md (no hand-typed numbers)."""
import json
import os

R = os.path.join(os.path.dirname(__file__), "..", "results", "WP4")
d10 = json.load(open(os.path.join(R, "s2_d10.json")))
d23 = json.load(open(os.path.join(R, "s2_d23.json")))
dg = json.load(open(os.path.join(R, "s2_diag_val.json")))
p = lambda x: "-" if x is None else "%.1f%%" % (100 * x)
out = []


def layer_table(title, res, nested=None):
    layers = list(res)
    fams = sorted({f for r in res.values() for f in r["detection"]})
    out.append("### " + title)
    out.append("| family (n flows) | " + " | ".join(layers) + " |")
    out.append("|---|" + "---|" * len(layers))
    for f in fams:
        n = max(r["n"].get(f, 0) for r in res.values())
        out.append("| %s (%d) | " % (f, n) + " | ".join(p(res[l]["detection"].get(f)) for l in layers) + " |")
    out.append("| FA on benign (n=%d) | " % list(res.values())[0]["n_benign"] + " | ".join(p(res[l]["fa_benign"]) for l in layers) + " |")
    out.append("| AUC | " + " | ".join("%.3f" % res[l]["auc"] for l in layers) + " |")
    out.append("")


out.append("# WP4 S2 tables (generated by tools/WP4_S2_tables.py from the JSON files; detection = share of flows alarmed at the 1% budget set on benign validation)\n")
out.append("D10 test: %d flows (%d benign); harness subsample val %d / test %d flows. Known hosts (>= %d benign train flows): %s\n" % (
    d10["n_test"], d10["n_test_benign"], d10["subsample"]["val"], d10["subsample"]["test"], d10["allow_params"]["min_support"], ", ".join(d10["known_hosts"])))
layer_table("D10 test, each layer alone (all flows, final = de-duplicated table)", d10["layers"])
ps = d10["portscan_predup"]
out.append("### D10 PortScan before de-duplication (stage cache), flows in the PortScan test window %s: n=%d" % (" .. ".join(ps["window"]), ps["n_flows"]))
out.append("| " + " | ".join(ps["detection"]) + " |")
out.append("|" + "---|" * len(ps["detection"]))
out.append("| " + " | ".join(p(v) for v in ps["detection"].values()) + " |\n")
for key, ttl in (("harness_all", "all five layers"), ("harness_no_identity", "without net.allow_pair (no source identity)")):
    h = d10[key]
    cm = h["combined"]
    out.append("### D10 harness, %s (combiner chosen on validation halves: %s; selection %s)" % (
        ttl, cm["method"], {k: round(v, 3) for k, v in cm["method_selection"].items()}))
    fams = sorted(cm["detection_by_attack"])
    out.append("| configuration | AUC | detection | FA | " + " | ".join(fams) + " |")
    out.append("|---|---|---|---|" + "---|" * len(fams))
    for k, r in h["ablation"].items():
        out.append("| %s | %.3f | %s | %.2f%% | " % (k, r["auc"], p(r["detection"]), 100 * r["false_alarm_rate"]) +
                   " | ".join(p(r["detection_by_attack"].get(f)) for f in fams) + " |")
    out.append("")
out.append("### D10 diagnostic (train / validation only)")
out.append("Benign train: %.2f%% of flows go to the web server 192.168.10.50 (%d flows, %d on port 80); attack validation flows: %.2f%% go to it; "
           "%.1f%% of the benign validation alarms of net.allow_service are flows to it. Attacker address 172.16.0.1 appears in benign train as source in %d flows and as destination in %d." % (
               100 * dg["benign_train_share_dst_web_server"], dg["benign_train_flows_dst_web_server"], dg["benign_train_flows_dst_web_server_port80"],
               100 * dg["attack_val_share_dst_web_server"], 100 * dg["val_benign_alarms_to_web_server_share"], dg["attacker_as_src_benign_train"], dg["attacker_as_dst_benign_train"]))
out.append("")
layer_table("D23 test, in-dataset: layers fitted on D23 benign train, flag / protocol / rate layers, all files", d23["in_dataset_flaglayers"])
layer_table("D23 test, in-dataset: allow-list layers, Tuesday 20-02 only (only file with IPs)", d23["in_dataset_allow_tue"])
layer_table("D23 test, TRANSFER: D10-fitted layers and thresholds, flag / protocol / rate layers, all files", d23["transfer_flaglayers"])
layer_table("D23 test, TRANSFER: D10-fitted allow-list layers, Tuesday 20-02", d23["transfer_allow_tue"])
for key, ttl in (("harness_in_dataset_flag", "D23 in-dataset, 3 flag layers"), ("harness_transfer_flag", "D23 transfer from D10, 3 flag layers")):
    cm = d23[key]["combined"]
    out.append("### Harness: %s - combined (%s): AUC %.3f, detection %s, FA %.2f%%" % (ttl, cm["method"], cm["auc"], p(cm["detection"]), 100 * cm["false_alarm_rate"]))
    out.append("| " + " | ".join(sorted(cm["detection_by_attack"])) + " |")
    out.append("|" + "---|" * len(cm["detection_by_attack"]))
    out.append("| " + " | ".join(p(cm["detection_by_attack"][f]) for f in sorted(cm["detection_by_attack"])) + " |\n")
open(os.path.join(R, "s2_tables.md"), "w").write("\n".join(out))
print("written", len(out))
