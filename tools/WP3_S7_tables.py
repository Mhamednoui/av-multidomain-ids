"""WP3 S7: readable tables (results/WP3/S7/S7_tables.md) generated from final.json, dev_l3.json, dev_l4.json, dev_stack.json, objects_*.json.
Usage: python -u -W ignore tools/WP3_S7_tables.py"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common.config import RESULTS
from lidar.learned_eval import CMP, PHYS

RES = RESULTS / "WP3" / "S7"
NAME = {"raw_L1": "L1", "raw_L2a": "L2a (intensity)", "raw_L2c": "L2c", "raw_L2d": "L2d", "raw_L3": "L3", "raw_L4": "L4",
        "raw_L4_NOPHANTOM": "L4_nophantom (cmp)", "raw_L4_V2": "L4_v2 box cloud (cmp)"}
ATT_SHORT = {"ph_replace_near": "repl near", "ph_replace_far": "repl far", "ph_budget_near": "budget near", "ph_budget_far": "budget far",
             "PointDrop": "PointDrop", "IntensitySpoof": "IntSpoof", "cmp_boxcloud": "box cloud*", "cmp_mradd_near": "mr-add near*",
             "cmp_mradd_far": "mr-add far*"}
ATT = PHYS + CMP


def p(x, d=1):
    return "-" if x is None else f"{100 * x:.{d}f}"


def row(cells):
    return "| " + " | ".join(str(c) for c in cells) + " |"


def table(header, rows):
    return "\n".join([row(header), row(["---"] * len(header))] + [row(r) for r in rows]) + "\n"


def main():
    f = json.loads((RES / "final.json").read_text())
    d3 = json.loads((RES / "dev_l3.json").read_text())
    d4 = json.loads((RES / "dev_l4.json").read_text())
    ds = json.loads((RES / "dev_stack.json").read_text())
    out = [f"# S7 tables (generated by tools/WP3_S7_tables.py from final.json, dev_*.json)\n\nCombiner chosen on validation: {f['combiner']}. "
           "* = comparison attack, physically impossible on a single-return sensor.\n"]

    out.append("## L3 validation round (13 train drives -> 3 val drives; threshold 1 % of val clean scans)\n")
    out.append(table(["features/model", "val FA %"] + [ATT_SHORT[a] for a in PHYS] + ["mean"],
                     [[k, p(v["val_fa"])] + [p(v["detection"][a]) for a in PHYS] + [p(v["mean_phys"])] for k, v in d3["candidates"].items()]))
    out.append(f"Choice: {d3['choice']}\n")

    out.append("## L4 validation: hyperparameter search (12 random configs)\n")
    out.append(table(["#", "trees", "val FA %", "mean phys det %", "params"],
                     [[i, s["n_trees"], p(s["val_fa"]), p(s["mean_phys"]), json.dumps(s["params"])] for i, s in enumerate(d4["search"])]))
    cv = d4["chosen_val"]
    out.append(f"Chosen: {d4['choice']}\n\nValidation (train-fitted, threshold 1 % of val clean rows): FA {p(cv['fa'])} %, AUC {d4['val_auc']:.3f} (six physical attacks vs clean).\n")
    out.append(table(["attack", "L4 det % (val)", "L4 AUC (val)", "L4_nophantom det %", "L4_v2 det %"],
                     [[ATT_SHORT[a], p(cv["det"].get(a)), f"{d4['val_auc_by_attack'][a]:.3f}", p(d4["variant_nophantom"]["det"].get(a)), p(d4["variant_v2"]["det"].get(a))] for a in ATT]))

    out.append("## Leakage controls (validation)\n")
    nc = d4["null_control"]
    out.append(f"C1 shuffled-label null control, 5 seeds: AUCs {[round(a, 3) for a in nc['aucs']]}, mean {nc['mean']:.3f} (bound 0.55): {'MET' if nc['met'] else 'NOT MET'}.\n")
    imp = d4["importance"]
    out.append("C2 feature importance (gain share): top-10 " + ", ".join(f"{k} {100 * v:.1f}%" for k, v in imp["top10"].items()) + f"; top-1 share {100 * imp['top1_share']:.1f} %.\n")
    out.append("By group: " + ", ".join(f"{k} {100 * v:.1f}%" for k, v in list(imp["by_group"].items())[:8]) + "\n")
    for c, v in imp["per_class"].items():
        out.append(f"- {c}: top " + ", ".join(f"{k} {100 * s:.1f}%" for k, s in list(v["top10"].items())[:6]) + "; groups " + ", ".join(f"{k} {100 * s:.0f}%" for k, s in v["groups"].items()))
    ab = d4["ablation_top5"]
    out.append(f"\nAblation (retrain without {ab['dropped']}): mean physical detection {p(ab['mean_phys'])} % (full model {p(d4['chosen_val']['det'] and sum(d4['chosen_val']['det'][a] for a in PHYS) / 6)} %).\n")
    out.append("C3 leave-one-attack-type-out (val FA of the reduced model, held-out detection vs in-distribution detection):\n")
    out.append(table(["held out", "val FA %", "held-out det %", "in-distribution det %"],
                     [[g, p(v["val_fa"]), ", ".join(f"{ATT_SHORT[a]} {p(x)}" for a, x in v["held_out_detection"].items()),
                       ", ".join(f"{ATT_SHORT[a]} {p(x)}" for a, x in v["in_distribution_detection"].items())] for g, v in d4["loto"].items()]))

    out.append("## Test (ONE verdict run): single layers at the pooled out-of-fold 1 % threshold\n")
    out.append(table(["layer", "FA %", "worst drive FA %"] + [ATT_SHORT[a] for a in ATT],
                     [[NAME[c], p(v["fa"]), p(max(v["fa_per_drive"].values()))] + [p(v["det"].get(a)) for a in ATT] for c, v in f["layers"].items()]))
    out.append("Test AUC (attack vs clean test scans):\n")
    out.append(table(["layer"] + [ATT_SHORT[a] for a in ATT], [[NAME[c]] + [f"{v['auc'].get(a, float('nan')):.3f}" for a in ATT] for c, v in f["layers"].items()]))
    out.append("Per-drive test FA % of each layer:\n")
    drives = sorted(next(iter(f["layers"].values()))["fa_per_drive"])
    out.append(table(["layer"] + drives, [[NAME[c]] + [p(v["fa_per_drive"].get(d)) for d in drives] for c, v in f["layers"].items()]))

    out.append("## Test: stacks (label-free combiner, threshold 1 % of pooled out-of-fold clean combined scores)\n")
    out.append(table(["stack", "FA %", "worst drive FA %", "LODO FA mean/max %"] + [ATT_SHORT[a] for a in ATT],
                     [[k, p(v["fa"]), p(max(v["fa_per_drive"].values())),
                       f"{p(sum(v['fa_ref_lodo'].values()) / len(v['fa_ref_lodo']))}/{p(max(v['fa_ref_lodo'].values()))}"] + [p(v["det"].get(a)) for a in ATT]
                      for k, v in f["stacks"].items()]))
    out.append("## Does X add beyond the physics stack? (paired scan-level bootstrap, difference in detection points, 95 % CI)\n")
    rows = []
    for name, v in f["adds"].items():
        for a in PHYS + CMP:
            e = v["per_attack"][a]
            rows.append([name, ATT_SHORT[a], p(e["physics"]), p(e["with_X"]), f"{100 * e['diff']:+.1f}", f"[{100 * e['ci95'][0]:+.1f}, {100 * e['ci95'][1]:+.1f}]"])
    out.append(table(["stack", "attack", "physics %", "with X %", "diff pts", "95 % CI"], rows))
    out.append(table(["stack", "attacks with gain >= 3 pts and CI > 0", "stack FA %", "ADDS"],
                     [[k, ", ".join(v["attacks_with_gain"]) or "none", p(v["fa"]), "yes" if v["adds"] else "no"] for k, v in f["adds"].items()]))

    out.append("## X alone against the best single physics layer per attack (reference chosen on the test data = favourable to physics)\n")
    rows = []
    for x, v in f["vs_best_physics_layer"].items():
        for a in PHYS + CMP:
            e = v[a]
            rows.append([NAME[x], ATT_SHORT[a], NAME[e["best_physics_layer"]], p(e["best_physics"]), p(e["X_alone"]), f"{100 * e['diff']:+.1f}",
                         f"[{100 * e['ci95'][0]:+.1f}, {100 * e['ci95'][1]:+.1f}]"])
    out.append(table(["X", "attack", "best physics layer", "best physics %", "X alone %", "diff pts", "95 % CI"], rows))
    if any("episodes" in v for v in f["layers"].values()):
        out.append("## Test: persistent sensor-fixed phantom episodes (21 per kind), detected within 3 s\n")
        rows = []
        for c, v in f["layers"].items():
            e = v["episodes"]
            rows.append([NAME[c], p(e["false_episode_rate"])] + [f"{e['kinds'][k]['detected_3s']}/{e['kinds'][k]['episodes']}" for k in sorted(e["kinds"])])
        for k, v in f["stacks"].items():
            if "episodes" in v:
                e = v["episodes"]
                rows.append([k, p(e["false_episode_rate"])] + [f"{e['kinds'][kk]['detected_3s']}/{e['kinds'][kk]['episodes']}" for kk in sorted(e["kinds"])])
        kinds = sorted(next(iter(f["layers"].values()))["episodes"]["kinds"])
        out.append(table(["layer / stack", "false-episode rate %"] + kinds, rows))
    for mode in ("dev", "final"):
        fn = RES / f"objects_{mode}.json"
        if fn.exists():
            o = json.loads(fn.read_text())
            out.append(f"## L3 object level ({mode}): phantom objects (>= 50 % injected) vs clean objects n >= 50\n")
            out.append(table(["attack", "phantom objects", "median points", "AUC", "share above clean q99"],
                             [[ATT_SHORT[a], v["n_phantom_objects"], f"{v['median_points']:.0f}", f"{v['auc_vs_clean_objects_n50']:.3f}", p(v["share_above_clean_q99"])] for a, v in o["attacks"].items()]))
    (RES / "S7_tables.md").write_text("\n".join(out))
    print("written")


if __name__ == "__main__":
    main()
