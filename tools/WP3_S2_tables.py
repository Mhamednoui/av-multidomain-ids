"""WP3 S2: markdown tables generated from results/WP3/S2/{final,dev,calib_report}.json -> results/WP3/S2/tables.md."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common.config import RESULTS

R = RESULTS / "WP3" / "S2"
f, d, c = (json.load(open(R / n)) for n in ("final.json", "dev.json", "calib_report.json"))
pc = lambda x: f"{100 * x:.1f}"
L = []

L += ["# WP3 S2 tables (generated by tools/WP3_S2_tables.py from final.json, dev.json, calib_report.json)", "",
      "## A. Real car-like clusters vs phantoms, VALIDATION drives (per range bin)", "",
      "Columns: n real / n phantom, KS D of occupancy q and of intensity, median points real / phantom.", ""]
for name, rows in (("calibrated (beta)", c["variants"]["beta"]["val_compare"]), ("old S1 phantom", c["val_s1_vs_real"]),
                   ("exact-ray, no calibration", c["val_exact_vs_real"])):
    L += [f"### {name}", "", "| range m | n real | n ph | D_q | D_int | med pts real | med pts ph | q real | q ph |", "|---|---|---|---|---|---|---|---|---|"]
    for x in rows:
        if "D_q" in x:
            L.append(f"| {x['bin']} | {x['n_real']} | {x['n_other']} | {x['D_q']:.2f} | {x['D_int']:.2f} | {x['med_n_real']:.0f} | "
                     f"{x['med_n_other']:.0f} | {x['med_q_real']:.2f} | {x['med_q_other']:.2f} |")
    L.append("")
L += ["### Point count at equal angular size (strata = terciles of the real clusters' sensor cells), ratio phantom / real", "",
      "| range m | stratum | n real | n ph | med real | med calibrated | ratio cal | ratio old S1 |", "|---|---|---|---|---|---|---|---|"]
old = {(x["bin"], x["stratum"]): x for x in c["val_s1_by_size"]}
for x in c["variants"]["beta"]["val_by_size"]:
    o = old.get((x["bin"], x["stratum"]))
    L.append(f"| {x['bin']} | {x['stratum']} | {x['n_real']} | {x['n_other']} | {x['med_n_real']:.0f} | {x['med_n_other']:.0f} | "
             f"{x['ratio']:.2f} | {o['ratio']:.2f} |" if o else f"| {x['bin']} | {x['stratum']} | {x['n_real']} | {x['n_other']} | {x['med_n_real']:.0f} | {x['med_n_other']:.0f} | {x['ratio']:.2f} | - |")
L += ["", "## B. v2 model on old vs calibrated phantoms (onset / sustained, detection %), threshold = val-normal quantile", "",
      "| mode | band | median pts old | median pts cal | VAL 1% old | VAL 1% cal | TEST 1% old | TEST 1% cal | TEST 2% old | TEST 2% cal |", "|---|---|---|---|---|---|---|---|---|---|"]
for mode in ("add", "budget_add", "replace", "budget"):
    for band in ("near", "far"):
        for t in ("onset", "sustained"):
            k = lambda v, s: s[f"{v}|{mode}|{band}|{t}"]
            L.append(f"| {mode} {t} | {band} | {k('old', f['test_v2_phantoms'])['median_points']:.0f} | {k('cal', f['test_v2_phantoms'])['median_points']:.0f} | "
                     f"{pc(k('old', d['val_v2_phantoms'])['det']['0.01'])} | {pc(k('cal', d['val_v2_phantoms'])['det']['0.01'])} | "
                     f"{pc(k('old', f['test_v2_phantoms'])['det']['0.01'])} | {pc(k('cal', f['test_v2_phantoms'])['det']['0.01'])} | "
                     f"{pc(k('old', f['test_v2_phantoms'])['det']['0.02'])} | {pc(k('cal', f['test_v2_phantoms'])['det']['0.02'])} |")

L += ["", "## C. L1 detection on TEST (%, alarm at the 1% clean-validation budget; FA = clean test scans)", ""]
types = ["PointDrop", "IntensitySpoof", "BoxCloud"] + [f"{v}_{m}_{b}" for v in ("cal", "old") for m in ("add", "replace", "budget_add", "budget") for b in ("near", "far")]
lay = list(f["test_detection"])
L += ["| attack | " + " | ".join(lay + ["v2_or_L1"]) + " |", "|---|" + "---|" * (len(lay) + 1)]
L.append("| FA clean test | " + " | ".join(pc(f["test_detection"][k]["FA"]) for k in lay) + f" | {pc(f['v2_or_L1_1pct']['FA'])} |")
for t in types:
    L.append(f"| {t} | " + " | ".join(pc(f["test_detection"][k][t]) for k in lay) + f" | {pc(f['v2_or_L1_1pct'][t])} |")

L += ["", "## D. False alarms per test drive (%)", "", "| drive | " + " | ".join(lay + ["v2_or_L1"]) + " |", "|---|" + "---|" * (len(lay) + 1)]
for dr in f["test_detection"]["v2"]["FA_by_drive"]:
    L.append(f"| {dr} | " + " | ".join(pc(f["test_detection"][k]["FA_by_drive"][dr]) for k in lay) + f" | {pc(f['v2_or_L1_1pct']['FA_by_drive'][dr])} |")

L += ["", "## E. Clean-scan L1 statistics (mean / q99 / max)", ""]
for p, s in f["stat_summary"].items():
    L.append(f"- {p}: " + "; ".join(f"{k} {v['mean']:.1f} / {v['q99']:.0f} / {v['max']:.0f}" for k, v in s.items()))
L += ["", "## F. Harness ablation (common/evaluate.py): see L1_ablation.md in this folder (combined = best method on validation halves)."]
(R / "tables.md").write_text("\n".join(L) + "\n")
print("\n".join(L[-60:]))
