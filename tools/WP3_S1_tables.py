"""WP3 S1: readable tables (results/WP3/S1_tables.md) and acceptance verdicts
(results/WP3/S1_acceptance.json), generated from results/WP3/S1_reproduction.json + split.json.
Acceptance rule: notes/WP3_lidar.md (A1-A7, written before any result). Run from codes_v3/."""
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from lidar.data import cache_size_gb
from common.config import RESULTS

OUT = RESULTS / "WP3"
P = lambda x: f"{100 * x:.1f}"


def main():
    r = json.load(open(OUT / "S1_reproduction.json"))
    sp = json.load(open(OUT / "split.json"))
    a2, a3, ray, ep = r["A2_v2_model_on_v3_layer"], r["A3_retrained"], r["A4_raycast"], r["episodes_v2model"]
    ref = a2["v2_reference"]
    L = ["# WP3 S1 tables (generated by tools/WP3_S1_tables.py from S1_reproduction.json)", ""]
    L += ["## A1 descriptor identity vs v2 splits/lidar_*.pkl", "| part | rows v3 | rows v2 | keys equal | max abs diff | allclose |", "|---|---|---|---|---|---|"]
    for part in ("train", "val", "test"):
        a = r["A1_identity"][part]
        L.append(f"| {part} | {a['rows_v3']} | {a['rows_v2']} | {a.get('keys_equal')} | {a.get('max_abs_diff')} | {a.get('allclose')} |")
    L += ["", "## A2 v2 model (model.json) on the v3 layer vs v2 reference", "| item | v3 layer | v2 | diff |", "|---|---|---|---|"]
    L.append(f"| test accuracy % | {P(a2['test']['accuracy'])} | {P(ref['test_accuracy'])} | {a2['checks']['acc_diff_pts']:.3f} pts |")
    L.append(f"| test AUC | {a2['test_auc']:.4f} | {ref['test_auc']:.4f} | {a2['checks']['auc_diff']:.5f} |")
    for k, o in a2["ops"].items():
        L.append(f"| {k} threshold / test FA % | {o['threshold']:.4f} / {P(o['test_false_alarm_rate'])} | "
                 f"{ref['ops'][k]['threshold']:.4f} / {P(ref['ops'][k]['test_false_alarm_rate'])} | |")
        for a, v in o["test_detection"].items():
            L.append(f"| {k} {a} detection % | {P(v)} | {P(ref['ops'][k]['test_detection'][a])} | {100 * (v - ref['ops'][k]['test_detection'][a]):.2f} pts |")
    L += ["", "## A3 baseline retrained in v3 (20-trial search, seed 42, deployed = higher val macro-F1)",
          f"deployed: {a3['deployed']}; test accuracy {P(a3['test']['accuracy'])} % (v2 {P(ref['test_accuracy'])}); test AUC {a3['test_auc']:.4f} (v2 {ref['test_auc']:.4f})", "",
          "| operating point | test FA % | PointDrop % | IntensitySpoof % | GhostCluster (box cloud) % |", "|---|---|---|---|---|"]
    for k, o in a3["ops"].items():
        d = o["test_detection"]
        L.append(f"| {k} | {P(o['test_false_alarm_rate'])} | {P(d['PointDrop'])} | {P(d['IntensitySpoof'])} | {P(d['GhostCluster'])} |")
    L += ["", "## A4 ray-cast phantoms, v2 protocol (v2 model, threshold = val FA 2% -> ~1% test FA)",
          "| mode / timing | detection % (v3 layer) | v2 % | median points | 5-15 m | 15-25 m | 25-40 m |", "|---|---|---|---|---|---|---|"]
    v2d = json.load(open(Path(__file__).resolve().parent.parent.parent / "codes_v2" / "results" / "lidar_raycast_test.json"))
    v2ref = {k: 100 * v["detection"] for k, v in v2d["detection"]["val_fpr_0.02"].items() if isinstance(v, dict) and "detection" in v}
    k2 = "val_fpr_0.02"
    for name, d in ray["rayv2"][k2].items():
        br = d["by_range"]
        L.append(f"| {name} | {P(d['detection'])} | {v2ref.get(name, float('nan')):.1f} | {d['median_points']:.0f} | "
                 f"{P(br['5-15 m'])} | {P(br['15-25 m'])} | {P(br['25-40 m'])} |")
    for k in ray["rayw3"]:
        L += ["", f"## WP3 near / far phantoms with the v2 model, threshold {k} (WP3 eval phantoms, test, n = rows with >=1 spoofed return)",
              "| mode / band / timing | detection % | n | median points |", "|---|---|---|---|"]
        for name, d in ray["rayw3"][k].items():
            L.append(f"| {name} | {P(d['detection'])} | {d['n']} | {d['median_points']:.0f} |")
    L += ["", "## Persistent episodes (v2 sequence logic, v2 temporal model + v3-refit single-scan model), test",
          f"threshold {ep['threshold']:.3f} (99th pct of val normal statistic); normal scan FA {P(ep['test_normal_scan_fa'])} %", "",
          "| episode type | episodes | detected within 3 s | median delay s |", "|---|---|---|---|"]
    for name, d in ep["episodes"].items():
        L.append(f"| {name} | {d['n']} | {d['detected_3s']} | {d['median_delay_s']} |")
    (OUT / "S1_tables.md").write_text("\n".join(L), encoding="utf-8")

    t = subprocess.run([sys.executable, "-W", "ignore", "tests/run_tests.py", "test_physics"], capture_output=True, text=True,
                       cwd=Path(__file__).resolve().parent.parent)
    n_tests = t.stdout.count("PASS  lidar/")
    acc = {"A1": r["A1_identity"]["met"], "A2": a2["checks"]["met"],
           "A3": bool(abs(a3["test"]["accuracy"] - ref["test_accuracy"]) <= 0.015 and abs(a3["test_auc"] - ref["test_auc"]) <= 0.01),
           "A4": bool(all(abs(100 * ray["rayv2"][k2][n]["detection"] - v) <= 1.0 for n, v in v2ref.items() if n in ray["rayv2"][k2])),
           "A5": bool({p: v["scans"] for p, v in sp["parts"].items()} == {"train": 2588, "val": 552, "test": 1533}),
           "A6": bool(t.returncode == 0 and n_tests >= 10), "A6_tests_passed": n_tests,
           "A7": bool(cache_size_gb() <= 5.0), "cache_gb": cache_size_gb()}
    acc["S1_met"] = all(acc[k] for k in ("A1", "A2", "A3", "A4", "A5", "A6", "A7"))
    json.dump(acc, open(OUT / "S1_acceptance.json", "w"), indent=1)
    print(acc)


if __name__ == "__main__":
    main()
