"""WP2 S7: summary tables from the stored JSON (no scoring). Writes results/WP2/s7_summary.md (ablation, per-capture matrix, v2 side-by-side, FA history).
Usage: python -u -W ignore tools/WP2_S7_summary.py
"""
import json

from WP2_S7_lib import MASQ_TEST, OUT, TEST_AMB, TEST_ATTACK

T = json.load(open(OUT / "s7_test.json"))
O = json.load(open(OUT / "s7_others.json"))
A = json.load(open(OUT / "s7_accel.json"))
D = json.load(open(OUT / "s7_diag_dev.json"))
DEV = json.load(open(OUT / "s7_dev.json"))["dev_ablation"]


def p(x, d=1):
    return "-" if x is None else f"{100 * x:.{d}f}%"


def dl(r):
    return "miss" if r.get("delay_s") is None else f"{r['delay_s']:.2f}"


L = ["# S7 summary tables (generated by tools/WP2_S7_summary.py from s7_test.json, s7_others.json, s7_accel.json, s7_diag_dev.json, s7_dev.json)\n"]
L.append("## 1. Ablation on the ROAD test (exposure 6). Windows 1 s; clean windows = 4 ambient captures + the 6 unique attack-capture leads (1375 windows)\n")
L.append("| configuration | combiner | clean FA (95% cluster bootstrap) | false alerts/h | FA w/o highway diag | masquerade (of 5, CP 95%) | plain (of 6) | benign_anomaly | extended_short | reverse | highway diag |")
L.append("|---|---|---|---|---|---|---|---|---|---|---|")
for k, c in T["configs"].items():
    ci = c["clean_fa_ci95_cluster_bootstrap"]
    a = c["ambient_fa"]
    L.append(f"| {k} | {c['method']} | {p(c['clean_fa_pooled'], 2)} ({p(ci[0], 2)} - {p(ci[1], 2)}) | {c['false_alerts_per_hour']:.0f} | {p(c['fa_without_highway_diag'], 2)} | "
             f"{c['masquerade_detected']} ({p(c['masquerade_ci95_clopper_pearson'][0], 0)}-{p(c['masquerade_ci95_clopper_pearson'][1], 0)}) | {c['plain_detected']} | "
             f"{p(a['ambient_dyno_drive_benign_anomaly'])} | {p(a['ambient_dyno_drive_extended_short'])} | {p(a['ambient_dyno_reverse'])} | {p(a['ambient_highway_street_driving_diagnostics'])} |")
L.append("\n## 2. Per capture, detection (delay in s, 'miss' = not detected), ROAD test\n")
cfgs = ["all", "only_L1", "only_L3c", "only_L3d", "all_but_L1", "all+L2b (optional)"]
L.append("| capture | " + " | ".join(cfgs) + " |")
L.append("|---|" + "---|" * len(cfgs))
for n in TEST_ATTACK:
    cells = []
    for k in cfgs:
        r = T["configs"][k]["per_capture"][n]
        cells.append(dl(r))
    L.append(f"| {n} | " + " | ".join(cells) + " |")
L.append("\nWindow recall of the attack windows (combined 'all'): " + ", ".join(f"{n.replace('_attack', '')} {p(T['configs']['all']['per_capture'][n]['window_recall'], 0)}" for n in TEST_ATTACK))
L.append("\nAlarmed attack windows by layer inside the combined alarms (count): " + "; ".join(f"{n.replace('_attack', '')}: {v}" for n, v in T["alarm_windows_by_layer_in_attack"].items()))
L.append("\n## 3. v2 side-by-side (ROAD test, same 11 attack captures; v2 numbers from ../codes_v2/results/road_windows.json, read only)\n")
v1, v01, vp = O["v2_road"]["R1_val_fpr_0.01"], O["v2_road"]["R1_val_fpr_0.001"], O["v2_road"]["R2_val_fpr_0.01"]
L.append("| capture | v2 timing 0.1% | v2 timing 1% | v2 payload 1% | v3 stack (all) | v3 L3-only (all_but_L1) |")
L.append("|---|---|---|---|---|---|")
for n in TEST_ATTACK:
    def v(x):
        r = x["per_capture"][n]
        return f"{r['delay_s']:.2f}" if r["detected"] else "miss"
    L.append(f"| {n} | {v(v01)} | {v(v1)} | {v(vp)} | {dl(T['configs']['all']['per_capture'][n])} | {dl(T['configs']['all_but_L1']['per_capture'][n])} |")
L.append(f"| clean-window FA | {p(v01['test_window_fpr'], 2)} ({v01['false_alerts_per_hour']:.0f}/h) | {p(v1['test_window_fpr'], 2)} ({v1['false_alerts_per_hour']:.0f}/h) | {p(vp['test_window_fpr'], 2)} ({vp['false_alerts_per_hour']:.0f}/h) | "
         f"{p(T['configs']['all']['clean_fa_pooled'], 2)} ({T['configs']['all']['false_alerts_per_hour']:.0f}/h) | {p(T['configs']['all_but_L1']['clean_fa_pooled'], 2)} ({T['configs']['all_but_L1']['false_alerts_per_hour']:.0f}/h) |")
L.append("\n(v2 FA counts all its normal test windows, v3 the clean ones: v2 'window FA' denominators differ, see the source.)\n")
L.append("## 4. What the calibration predicts (development folds, threshold-LOCO of the frozen stack) vs the test\n")
L.append("| unit | predicted FA (threshold from the other folds) |\n|---|---|")
for u, v in D["combined_threshold_loco"].items():
    L.append(f"| {u} | {p(v, 1)} |")
L.append(f"\nPooled: dyno folds {p(D['combined_pooled_dyno'], 2)}, road blocks {p(D['combined_pooled_road'], 2)}, all {p(D['combined_pooled_all'], 2)}. Test clean FA {p(T['configs']['all']['clean_fa_pooled'], 2)}.")
L.append("\n## 5. Accelerator captures (whole-capture check; injection precedes the capture, no labels)\n")
L.append("| capture | kind | windows | alarm fraction (combined) | first alarm s |\n|---|---|---|---|---|")
for n, c in A["captures"].items():
    a = c["all"]
    L.append(f"| {n} | {a['kind']} | {a['windows']} | {p(a['alarm_fraction'], 1)} | {a['first_alarm_s']} |")
L.append("\n## 6. Development ablation (LOCO normals + validation attack windows; in-sample for the combiner)\n")
L.append("| configuration | AUC | detection (window) | FA |\n|---|---|---|---|")
for k, v in DEV.items():
    L.append(f"| {k} | {v['auc']:.3f} | {p(v['detection'])} | {p(v['false_alarm_rate'], 2)} |")
open(OUT / "s7_summary.md", "w").write("\n".join(L))
print("\n".join(L))
