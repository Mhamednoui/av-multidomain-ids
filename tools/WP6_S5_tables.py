"""WP6 S5: markdown tables from results/WP6/s5_dev.json, s5_test.json, s5_acceptance.json, s5_diag.json -> results/WP6/s5_tables.md (numbers copied, not typed).
Run: python -u -W ignore tools/WP6_S5_tables.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common.config import results_dir  # noqa: E402

OUT = results_dir("WP6")
P = lambda x: "-" if x is None else f"{100 * x:.1f}"
F = lambda x, d=2: "-" if x is None else f"{x:.{d}f}"
CI = lambda c, k=100, d=1: "-" if not c else f"[{k * c[0]:.{d}f}, {k * c[1]:.{d}f}]"


def main():
    dev = json.loads((OUT / "s5_dev.json").read_text())
    t = json.loads((OUT / "s5_test.json").read_text())
    acc = json.loads((OUT / "s5_acceptance.json").read_text())
    dg = json.loads((OUT / "s5_diag.json").read_text())
    L = ["# WP6 S5 tables (M2 system; generated by tools/WP6_S5_tables.py)", ""]
    L += ["## 1 Acceptance (test, once; rule in notes/WP6_crossdomain.md 'S5 start')", "", "| Rule | Value | Bound | Verdict |", "|---|---|---|---|"]
    for k, v in acc.items():
        val = {a: b for a, b in v.items() if a not in ("rule", "met")}
        L.append(f"| {k} | {json.dumps(val, default=str)[:260]} | {v['rule']} | {'MET' if v['met'] else 'NOT MET'} |")
    L += ["", "## 2 Validation: calibration grid (nested held-out over 3 group folds; selection = non-held-out families)", "",
          "| Config | FA tick K | FA tick C | det K | det C | pooled det | qualifies (FA <= 2.5%) |", "|---|---|---|---|---|---|---|"]
    for k, r in dev["calibration_grid"].items():
        L.append(f"| {k} | {P(r['K']['fa_tick'])} | {P(r['C']['fa_tick'])} | {P(r['K']['mean_detection_selection'])} | {P(r['C']['mean_detection_selection'])} | "
                 f"{P(r['pooled_detection'])} | {'yes' if r['qualifies'] else 'no'} |")
    L += ["", f"Chosen: `{json.dumps(dev['calibration_choice'])}`", "",
          "## 3 Validation: correlator grid (chosen calibration, nested held-out alarms)", "",
          "| Correlator | events/h K | events/h C | event det K | event det C | pooled | safe-stop/h K | safe-stop/h C | degrade/h K | degrade/h C | qualifies (<= 10/h) |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, r in dev["correlator_grid"].items():
        L.append(f"| {k} | {F(r['K']['events_per_hour'])} | {F(r['C']['events_per_hour'])} | {P(r['K']['mean_event_detection_selection'])} | {P(r['C']['mean_event_detection_selection'])} | "
                 f"{P(r['pooled_event_detection'])} | {F(r['K']['clean_response_per_hour']['SAFE_STOP'])} | {F(r['C']['clean_response_per_hour']['SAFE_STOP'])} | "
                 f"{F(r['K']['clean_response_per_hour']['DEGRADE'])} | {F(r['C']['clean_response_per_hour']['DEGRADE'])} | {'yes' if r['qualifies'] else 'no'} |")
    off = dev["correlator_off_val"]
    L += ["", f"Correlator off (S3 alarm events) on validation: K {F(off['K']['events_per_hour'])} events/h, det {P(off['K']['mean_detection_selection'])}; "
              f"C {F(off['C']['events_per_hour'])} events/h, det {P(off['C']['mean_detection_selection'])}.", f"Chosen: `{json.dumps(dev['correlator_choice'])}`", "",
          "Validation nested held-out of the chosen M2 system: " + "; ".join(
              f"{fam} FA tick {P(v['fa_tick'])}%, {F(v['events_per_hour'])} events/h, response/h {json.dumps({a: round(b, 2) for a, b in v['clean_response_per_hour'].items()})}"
              for fam, v in dev["val_heldout_chosen"].items()), ""]
    L += ["## 4 Test headline (M2 system, once)", "", "| | K | C |", "|---|---|---|"]
    K, C = t["system"]["K"], t["system"]["C"]
    rows = [("raw tick FA % [CI]", lambda x: f"{P(x['fa_tick'])} {CI(x['ci_single_event']['fa_tick'])}"),
            ("alert events / clean hour [CI]", lambda x: f"{F(x['events_per_hour'])} {CI(x['ci_single_event']['events_per_hour'], 1, 1)}"),
            ("clean hours", lambda x: F(x["clean_hours"])),
            ("WARN / DEGRADE / SAFE_STOP per clean hour", lambda x: " / ".join(F(x["clean_response_per_hour"][k]) for k in ("WARN", "DEGRADE", "SAFE_STOP"))),
            ("LOG-only alarm ticks / clean hour", lambda x: F(x["log_ticks_per_hour"], 1)),
            ("mean EVENT detection, single-domain families [CI]", lambda x: f"{P(x['mean_event_detection_single'])} {CI(x['ci_single_event']['mean'])}"),
            ("mean TICK detection (no correlator), single-domain [CI]", lambda x: f"{P(x['mean_tick_detection_single'])} {CI(x['ci_single_tick']['mean'])}"),
            ("held-out (S4 zero-day) event detection [CI]", lambda x: f"{P(x['mean_event_detection_heldout'])} {CI(x['ci_heldout_event']['mean'] if x['ci_heldout_event'] else None)}"),
            ("seen (non-held-out domain) event detection", lambda x: P(x["mean_event_detection_seen"])),
            ("blame correct / wrong / undecided (detected single-domain, pooled)", lambda x: " / ".join(P(x["blame_single_pooled"][k]) for k in ("correct", "wrong", "undecided"))),
            ("blame on coordinated scenarios correct / wrong / undecided", lambda x: " / ".join(P(x["blame_coordinated_pooled"][k]) for k in ("correct", "wrong", "undecided"))),
            ("tick recall (share of attack ticks flagged, v2-style)", lambda x: P(x["tick_recall_attack_ticks"])),
            ("events explained", lambda x: f"{x['explanations']['with_explanation']} / {x['explanations']['events']}"),
            ("vehicle groups for the CI", lambda x: str(x["ci_single_event"]["n_vehicle_groups"])),
            ("system threshold (noisy_or score)", lambda x: F(x["threshold"], 6))]
    for name, fn in rows:
        L.append(f"| {name} | {fn(K)} | {fn(C)} |")
    L += ["", "Event detection by attacked domain (single-domain families): " + "; ".join(
        f"{fam}: " + ", ".join(f"{d} {P(v)}" for d, v in t["system"][fam]["event_detection_by_attacked_domain"].items()) for fam in ("K", "C")), ""]
    for fam in ("K", "C"):
        S = t["system"][fam]
        L += [f"## 5{fam} Per family ({fam}, test): event / tick detection, median delays (s), blame, response of detected composites", "",
              "| Family | attacked | category | n | event det | tick det | delay event | delay tick | blame ok / wrong / undec | max response WARN / DEGRADE / SAFE_STOP |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for f, x in sorted(S["families"].items(), key=lambda kv: (str(kv[1]["attacked"]), kv[0])):
            bl = " / ".join(P(x.get(f"blame_{k}")) for k in ("correct", "wrong", "undecided"))
            rm = " / ".join(P(x["response_max"][k]) for k in ("WARN", "DEGRADE", "SAFE_STOP")) if "response_max" in x else "-"
            L.append(f"| {f} | {x['attacked']} | {x['category']} | {x['n']} | {P(x['detection'])} | {P(x['tick_detection'])} | {F(x['median_delay_s'], 0)} | "
                     f"{F(x['median_tick_delay_s'], 0)} | {bl} | {rm} |")
        L.append("")
    L += ["## 6 Ablation (test): each domain removed (threshold re-fitted on validation, same procedure), correlator off", "",
          "| Family | Config | raw tick FA | events/h | event det single | held-out |", "|---|---|---|---|---|---|"]
    for fam in ("K", "C"):
        S = t["system"][fam]
        L.append(f"| {fam} | M2 (all) | {P(S['fa_tick'])} | {F(S['events_per_hour'])} | {P(S['mean_event_detection_single'])} | {P(S['mean_event_detection_heldout'])} |")
        for name, a in S["ablation"].items():
            L.append(f"| {fam} | {name} | {P(a['fa_tick'])} | {F(a['events_per_hour'])} | {P(a['mean_event_detection_single'])} | {P(a['mean_event_detection_heldout'])} |")
        o = S["correlator_off"]
        L.append(f"| {fam} | correlator off (S3 alarm events) | {P(o['fa_tick'])} | {F(o['events_per_hour'])} | {P(o['mean_detection_single'])} | {P(o['mean_detection_heldout'])} |")
    L += ["", "## 6b What cross-domain adds (test): event detection of the vehicle-block families with vs without the cross entry (ablation thresholds from validation)", "",
          "| Family | family | with cross | without cross | gain (points) |", "|---|---|---|---|---|"]
    for fam in ("K", "C"):
        S = t["system"][fam]
        wo = S["ablation"]["without cross"]["families"]
        vf = [f for f, x in S["families"].items() if x["attacked"] in ("gps", "cross", "gps+can")]
        for f in vf:
            L.append(f"| {fam} | {f} | {P(S['families'][f]['detection'])} | {P(wo[f])} | {100 * (S['families'][f]['detection'] - wo[f]):+.1f} |")
        g = [S["families"][f]["detection"] - wo[f] for f in vf]
        L.append(f"| {fam} | MEAN over {len(vf)} vehicle-block families | {P(sum(S['families'][f]['detection'] for f in vf) / len(vf))} | {P(sum(wo[f] for f in vf) / len(vf))} | "
                 f"{100 * sum(g) / len(g):+.1f} |")
    L += ["", "## 7 Equal-FA G5 comparison (TEST-INFORMED, labelled): each attacked domain's entry alone at the fused system's clean test tick FA", "",
          "| Family | attacked domain | alone tick det | fused tick det | fused event det | alone FA tick |", "|---|---|---|---|---|---|"]
    for fam in ("K", "C"):
        for d, g in t["system"][fam]["g5_equal_fa_test_informed"].items():
            L.append(f"| {fam} | {d} | {P(g['alone_tick_detection'])} | {P(g['fused_tick_detection'])} | {P(g['fused_event_detection'])} | {P(g['alone_fa_tick'])} |")
    L += ["", "## 8 Post-test diagnostic (no choice made from it; s5_diag.json)", "",
          "| | entry | share of clean ticks >= 0.99 (val nested, mean of 3 folds) | same on test | own alarm rate test | strongest at clean alarm ticks (test) |", "|---|---|---|---|---|---|"]
    for fam in ("K", "C"):
        v = dg["val_nested_heldout"][fam]
        te = dg["test"][fam]
        for d in te["share_ge_099"]:
            vm = sum(p["share_ge_099"][d] for p in v) / len(v)
            L.append(f"| {fam} | {d} | {P(vm)} | {P(te['share_ge_099'][d])} | {P(te['own_alarm_rate'][d])} | {P(te['strongest_at_clean_alarm_ticks'].get(d, 0.0))} |")
    for fam in ("K", "C"):
        te = dg["test"][fam]
        L.append(f"\n{fam} clean events by blamed domain / response (test): `{json.dumps(te['clean_events_by_blamed_response'])}`; median alarm ticks per clean event "
                 f"{te['alarm_ticks_per_clean_event_median']}; clean composites with >= 1 alert event: test {P(te['clean_composites_with_an_event'])}% "
                 f"(median length {te['clean_composite_median_length_s']:.0f} s), val nested folds "
                 + ", ".join(P(p["clean_composites_with_an_event"]) for p in dg["val_nested_heldout"][fam]) + " %")
    v2 = t.get("v2", {})
    w = v2.get("simulation_with_correlator") or {}
    fo = v2.get("simulation_fusion_only") or {}
    L += ["", "## 9 v2 side-by-side (NOT like-for-like)", "", "| | v2 live simulation (meta + temporal correlator) | v3 M2 K | v3 M2 C |", "|---|---|---|---|",
          f"| false alarms | {P(w.get('fpr'))}% of normal rows (fusion only {P(fo.get('fpr'))}%) | {P(K['fa_tick'])}% of clean ticks, {F(K['events_per_hour'])} events/h | "
          f"{P(C['fa_tick'])}% of clean ticks, {F(C['events_per_hour'])} events/h |",
          f"| detection | recall {P(w.get('recall'))}% of attack rows | tick recall {P(K['tick_recall_attack_ticks'])}%, composite event det {P(K['mean_event_detection_single'])}% | "
          f"tick recall {P(C['tick_recall_attack_ticks'])}%, event det {P(C['mean_event_detection_single'])}% |",
          f"| first-alert delay | {json.dumps(v2.get('first_alert_delay_rows'))} rows | per family (section 5) | per family (section 5) |",
          "", "Why not like-for-like: v2 = 7,800 rows in 12 long blocks from the four domains' test sets with a SUPERVISED meta-classifier trained on the same attack classes, "
          "random halves, a correlator that escalates threat levels (no events, no clean-hour rate) and a LiDAR phantom proxy; v3 = 1 Hz composite drives over five domains "
          "+ cross-domain, label-free combiner, group-aware LOGO thresholds, held-out (zero-day) types, events per clean hour."]
    (OUT / "s5_tables.md").write_text("\n".join(L) + "\n")
    print("written", OUT / "s5_tables.md")


if __name__ == "__main__":
    main()
