"""WP6 S2b: tables (results/WP6/s2b_tables.md) and acceptance (results/WP6/s2b_acceptance.json) from s2b_dev.json (round 1),
s2b_dev_r2.json (round 2, post-hoc) and s2b_choice_r2.json (final choice over both rounds). Validation (dev folds) only.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common.config import results_dir  # noqa: E402

OUT = results_dir("WP6")
P = lambda x: "-" if x is None else f"{100 * x:.1f}"


def main():
    r1 = json.loads((OUT / "s2b_dev.json").read_text())
    r2 = json.loads((OUT / "s2b_dev_r2.json").read_text())
    ch = json.loads((OUT / "s2b_choice_r2.json").read_text())
    ch1 = json.loads((OUT / "s2b_choice.json").read_text())
    L = ["# WP6 S2b tables (dev folds only: leave-one-drive/route-out over train + val; generated by tools/WP6_S2b_tables.py)", "",
         f"Choice round 1 (pre-registered): {ch1}. Final choice over rounds 1 + 2: {ch}.", "",
         "## 1. Candidates (held-out folds pooled)", "",
         "| data set | round | candidate | FA rows % | FA val groups % | worst group (FA %) | selection det % | mean single det % | correct blame % | wrong % | undecided % |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    allr = {}
    for ds in ("kitti", "comma"):
        for rnd, r in (("1", r1), ("2 (post-hoc)", r2)):
            for n, s in r[ds].items():
                allr[(ds, n)] = s
                p = s["pooled_single"]
                L.append(f"| {ds} | {rnd} | {n} | {P(s['fa_rows'])} | {P(s['fa_val_groups'])} | {s['worst_group'][0][-20:]} ({P(s['worst_group'][1])}) | "
                         f"{P(s['selection_mean_detection'])} | {P(s['mean_detection_single'])} | {P(p['correct_blame'])} | {P(p['wrong_blame'])} | {P(p['undecided'])} |")
    for ds in ("kitti", "comma"):
        s = allr[(ds, ch[ds])]
        L += ["", f"## 2. {ds}: chosen {ch[ds]}, per attack (held-out folds)", "",
              "| attack | runs | detection % | detection val groups % | median delay s | correct blame % | wrong % | undecided % | blamed domain counts |",
              "|---|---|---|---|---|---|---|---|---|"]
        for a, v in s["attacks"].items():
            L.append(f"| {a} | {v['runs']} | {P(v['detection'])} | {P(v['detection_val_groups'])} | {'-' if v['median_delay_s'] is None else round(v['median_delay_s'], 1)} | "
                     f"{P(v.get('correct_blame'))} | {P(v.get('wrong_blame'))} | {P(v['undecided'])} | {v['blame_counts']} |")
        L.append("\nFA rows per held-out group (%): " + ", ".join(f"{g[-20:]} {P(x)}" for g, x in sorted(s["fa_per_group"].items())))
    (OUT / "s2b_tables.md").write_text("\n".join(L) + "\n")
    k, c = allr[("kitti", ch["kitti"])], allr[("comma", ch["comma"])]
    best_r2 = allr[("comma", "R2_wu60_k1_tb300")]
    ac = {"choice": ch,
          "B1_fa_rows_le_1.5pct": {"kitti": k["fa_rows"], "comma": c["fa_rows"], "met": k["fa_rows"] <= 0.015 and c["fa_rows"] <= 0.015,
                                   "worst_group": {"kitti": k["worst_group"], "comma": c["worst_group"]}},
          "B2_comma_no_route_above_5pct": {"worst": c["worst_group"], "met": c["worst_group"][1] <= 0.05},
          "B3_mean_detection_ge_70pct": {"kitti": k["mean_detection_single"], "comma": c["mean_detection_single"],
                                         "met": {"kitti": k["mean_detection_single"] >= 0.70, "comma": c["mean_detection_single"] >= 0.70}},
          "B4_wrong_blame_le_5pct": {"kitti": k["pooled_single"], "comma": c["pooled_single"],
                                     "met": {"kitti": k["pooled_single"]["wrong_blame"] <= 0.05, "comma": c["pooled_single"]["wrong_blame"] <= 0.05}},
          "info_best_bias_tolerant_comma": {"name": "R2_wu60_k1_tb300", "fa_rows": best_r2["fa_rows"], "worst": best_r2["worst_group"],
                                            "mean_detection_single": best_r2["mean_detection_single"]},
          "info_s2_case_comma_val_routes_continuous": {n: allr[("comma", n)]["fa_val_groups"] for n in ("cusum_k0.5", "inst", "R2_wu60_k1_tb300")}}
    (OUT / "s2b_acceptance.json").write_text(json.dumps(ac, indent=1))
    print(json.dumps(ac, indent=1))


if __name__ == "__main__":
    main()
