"""WP6 S1: tables (results/WP6/s1_tables.md) and acceptance verdicts (results/WP6/s1_acceptance.json) from the S1 JSON files.
No number is typed by hand: everything is read from s1_road_wheel.json, s1_kitti_dev.json, s1_kitti_test.json, s1_comma_dev.json,
s1_comma_test.json and the test log of tests/crossdomain.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common.config import results_dir  # noqa: E402

R = results_dir("WP6")
J = lambda n: json.loads((R / n).read_text())


def fmt(h):
    if not h or h.get("n", 0) == 0 or "mean" not in h:
        return "n/a | | | |"
    return f"{h['n']} | {h['mean']:+.2f} | {h['std']:.2f} | {h['p99_abs']:.2f} | {'yes' if h['honest'] else 'NO'}"


def block(title, blocks):
    out = [f"### {title}", "", "| pair quantity | split | sigma | n | mean z | std z | p99 abs z | honest |", "|---|---|---|---|---|---|---|---|"]
    keys = sorted(set().union(*[b[1].keys() for b in blocks]))
    for k in keys:
        for split, b in blocks:
            if k not in b:
                continue
            out.append(f"| {k} | {split} | published | {fmt(b[k].get('published'))} |")
            out.append(f"| {k} | {split} | recalibrated | {fmt(b[k].get('recalibrated'))} |")
    return out + [""]


def lat_rows(d, label):
    return [f"| {label} | {k} | {v['lag']:+.3f} | [{v['ci95'][0]:+.3f}, {v['ci95'][1]:+.3f}] | {v['corr_peak']:.3f} | {v['corr_at_0']:.3f} | {v['groups']} |"
            for k, v in d.items()]


def main():
    rw, kd, kt, cd, ct = J("s1_road_wheel.json"), J("s1_kitti_dev.json"), J("s1_kitti_test.json"), J("s1_comma_dev.json"), J("s1_comma_test.json")
    L = ["# WP6 S1 tables (generated by tools/WP6_S1_tables.py from results/WP6/s1_*.json)", ""]
    L += ["## 1. Sample counts per pair and split (1 Hz grid points)", "", "| data | pair quantity | train | val | test |", "|---|---|---|---|---|"]
    for name, d in (("KITTI", kd), ("comma2k19", cd)):
        cnt = {}
        for r in d["counts"]:
            cnt.setdefault(f"{r['pair']} {r['quantity']}", {})[r["part"]] = r["n"]
        for k, v in sorted(cnt.items()):
            L.append(f"| {name} | {k} | {v.get('train', 0)} | {v.get('val', 0)} | {v.get('test', 0)} |")
    L += ["", "comma2k19 hours (CAN span) per split: " + ", ".join(f"{k} {v:.2f} h" for k, v in cd["hours"].items()), ""]
    L += ["## 2. Latency (cross-correlation of first differences; b lags a by `lag` s; 95% CI = bootstrap over drives / routes)", "",
          "| data / split | pair (a-b) | lag s | 95% CI | corr peak | corr at 0 | groups |", "|---|---|---|---|---|---|---|"]
    L += lat_rows(kd["latency_train"], "KITTI train") + lat_rows(kt["latency_test"], "KITTI test") + lat_rows(cd["latency_train"], "comma train")
    L += ["", "## 3. Normalised residuals z (pre-registered recalibration: constant bias)", ""]
    L += block("KITTI (CAN simulated; pre-registered simulator)", [("train", kd["train"]), ("val", kd["val"]), ("test", kt["test"])])
    L += block("comma2k19 (real CAN + u-blox GNSS + IMU)", [("train", cd["train"]), ("val", cd["val"]), ("test", ct["test"])])
    L += ["## 4. Revised design R (decided after the val verdict; R1 linear bias, R2 one-vehicle CAN scale, R4 forward-displacement speed)", ""]
    L += block("KITTI revised R", [("train", kd["revised_R"]["train"]), ("val", kd["revised_R"]["val"]), ("test", kt["test_revised_R"])])
    L += block("comma2k19 revised R (R1 only)", [("train", cd["revised_R"]["train"]), ("val", cd["revised_R"]["val"]), ("test", ct["test_revised_R"])])
    L += ["## 5. Sigma models fitted on train (r ~ bias + c1 v + N(0, a^2 + (b v)^2))", "", "| set | pair quantity | bias mode | bias | c1 (per m/s) | a | b |", "|---|---|---|---|---|---|---|"]
    sm = J("s1_sigma_models.json")
    for s in ("kitti", "kitti_R", "comma", "comma_R"):
        for k, m in sorted(sm[s]["models"].items()):
            L.append(f"| {s} | {k} | {m.get('bias_mode', 'const')} | {m['bias']:+.4f} | {m.get('bias_per_mps', 0.0):+.5f} | {m['a']:.4f} | {m['b']:.4f} |")
    L += ["", "## 6. CAN speed relation and unit", ""]
    for part, d in (("train", cd["scale_train"]), ("val", cd["scale_val"]), ("test", ct["scale_test"])):
        for k, v in d.items():
            L.append(f"- comma {part} {k}: CAN = {v['slope']:.4f} x GNSS [{v['ci95'][0]:.4f}, {v['ci95'][1]:.4f}], n = {v['n']}, per route {min(v['per_route']):.4f}-{max(v['per_route']):.4f}")
    u = cd["raw_unit_train"]
    L.append(f"- comma raw 0xAA counts vs GNSS (train): {u['vs_gnss']['unit_kmh_per_count']:.5f} km/h per count, offset {u['vs_gnss']['offset_kmh']:+.2f} km/h (n = {u['vs_gnss']['n']}); vs comma's decoded speed: {u['vs_comma_decoded']['unit_kmh_per_count']:.5f} km/h per count, offset {u['vs_comma_decoded']['offset_kmh']:+.2f} km/h")
    L.append(f"- ROAD 0x6e0 (train ambient): period {rw['period_s']:.4f} s, quantum {rw['quantum_raw']:.0f} raw, noise {rw['noise_std_mps_median']:.4f} m/s, spread {100 * rw['spread_rel_median']:.2f}% ; with 0.01 km/h: highway p99 {rw['A6_i_highway_kmh_p99'][0]:.1f} km/h, max p99 |1 s accel| {rw['A6_ii_acc_p99_max']:.2f} m/s^2")
    L.append("")
    L += ["| ROAD capture | duration s | period s | raw max | km/h p99 | km/h max | noise m/s | accel p99 | wheel / 0xd0.5 raw |", "|---|---|---|---|---|---|---|---|---|"]
    for c in rw["captures"]:
        f = lambda x, p=3: "n/a" if x is None else f"{x:.{p}f}"
        L.append(f"| {c['capture']} | {c['duration_s']:.0f} | {c['period_s_median']:.4f} | {c['raw_max']:.0f} | {c['kmh_p99']:.1f} | {c['kmh_max']:.1f} | {f(c['noise_std_mps'], 4)} | {f(c['acc_p99_mps2'], 2)} | {f(c['wheel_over_speedo_raw'], 4)} |")
    (R / "s1_tables.md").write_text("\n".join(L) + "\n")

    # acceptance
    honest_val = {**{f"kitti {k}": v.get("recalibrated", {}).get("honest") for k, v in kd["val"].items()},
                  **{f"comma {k}": v.get("recalibrated", {}).get("honest") for k, v in cd["val"].items()}}
    honest_val_R = {**{f"kitti {k}": v.get("recalibrated", {}).get("honest") for k, v in kd["revised_R"]["val"].items()},
                    **{f"comma {k}": v.get("recalibrated", {}).get("honest") for k, v in cd["revised_R"]["val"].items()}}
    lat_ok = all(v["lag"] is not None and v["ci95"] is not None for v in list(kd["latency_train"].values()) + list(cd["latency_train"].values()))
    slope = cd["scale_train"]["can"]["slope"]
    acc = {
        "A1_streams": {"verdict": "MET", "kitti_sources": ["gps", "imu", "lidar", "can (simulated)"], "comma_sources": ["can", "wheel", "gnss", "imu"],
                       "v2x": "no ego self-report in any data set: V2X provides other vehicles' motion only (adapter crossdomain/v2x_self.py, tested)"},
        "A2_latency": {"verdict": "MET" if lat_ok else "NOT MET", "unit_test": "tests/crossdomain/test_witness.py::test_lag_recovery (+ through can_sim): 0.30 s within 0.05 s",
                       "note": "comma gnss-imu yaw peak correlation only %.2f: low confidence" % cd["latency_train"]["gnss-imu yaw_rate"]["corr_peak"]},
        "A3_sigma_honesty_val": {"verdict": "MET" if all(v for v in honest_val.values()) else "NOT MET", "per_pair_recalibrated": honest_val,
                                 "revised_R_val_information_only": honest_val_R},
        "A4_tests": "see test log (full suite) in the step report",
        "A5_api": "crossdomain/__init__.py docstring + reports/WP6_S1.md section API",
        "A6_can_unit": {"road_plausible": bool(rw["A6_i_pass"] and rw["A6_ii_pass"]), "road_confirmable": False,
                        "comma_slope_train": slope, "comma_slope_within_5pct": bool(abs(slope - 1) <= 0.05),
                        "comma_val_speed_honest_after_A3": bool(honest_val.get("comma gnss-can speed")),
                        "verdict": "ROAD unit PLAUSIBLE (not confirmable); comma CAN-vs-GNSS slope within 5% but val residual not honest -> relation NOT 'validated' by the A6 wording"},
    }
    (R / "s1_acceptance.json").write_text(json.dumps(acc, indent=1))
    print(json.dumps(acc, indent=1))


if __name__ == "__main__":
    main()
